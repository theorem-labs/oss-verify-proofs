      stepn F_a8c34 D_a8c34.
      stepn F_a8c38 D_a8c38.
      stepn F_a8c3c D_a8c3c.
      mk_eq. apply mst_refl.
    - post. unfold v_addi. unorm. f_equal. lia.
  Qed.

