Lemma crc_shift32_extract : forall x,
  Z.shiftr (Z.shiftl x 32 mod 2^64) 32 = (x mod 2^32)%Z.
Proof.
  intros x. rewrite Z.shiftl_mul_pow2,Z.shiftr_div_pow2 by lia.
  pose proof (Z.div_mod x (2^32) ltac:(lia)) as DX.
  pose proof (Z.mod_pos_bound x (2^32) ltac:(lia)) as RX.
  replace (x*2^32)%Z with ((x mod 2^32)*2^32+(x/2^32)*2^64)%Z by nia.
  rewrite Z.mod_add by lia. rewrite Z.mod_small by nia.
  rewrite Z.div_mul by lia. reflexivity.
Qed.
Definition crc_seed (x : word) : Z := Z.lxor (bv_unsigned x mod 2^32) CRC_MASK.
Lemma crc_seed_range : forall x, (0 <= crc_seed x < 2^32)%Z.
Proof. intros x. unfold crc_seed. apply lxor_bound;[lia|apply Z.mod_pos_bound;lia|unfold CRC_MASK;lia]. Qed.
