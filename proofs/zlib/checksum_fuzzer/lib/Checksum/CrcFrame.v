Definition CRC_FRAME : Z := 80%Z.
Definition crc32_value_post (answer : Z)
  (ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 : word)
  (F : bvmap 5 word) (fc : bv 32) (lo : Z) (m : word -> option byte) : machine_state -> Prop :=
  fun final => exists t0 t1 t2 a1 a2 a3 a4 a5 a6 a7 t3 t4 t5 t6 m',
    final = MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 answer) a1 a2 a3 a4 a5 a6 a7
      s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
      F (ret_pc ra) fc None m' (seg_rom rsegs) /\
    munch [(bv_unsigned sp-CRC_FRAME,bv_unsigned sp)]%Z m m' /\
    wmono rsegs m m' /\ stk rsegs m' lo (bv_unsigned sp).

Section CrcEpilogue.
  Variables (ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 : word)
    (F : bvmap 5 word) (fc : bv 32) (lo : Z) (m m1 : word -> option byte) (junk : list byte).
  Hypothesis MU : munch [(bv_unsigned sp-CRC_FRAME,bv_unsigned sp)]%Z m m1.
  Hypothesis WM : wmono rsegs m m1.
  Hypothesis LO : (lo+CRC_FRAME <= bv_unsigned sp)%Z.
  Hypothesis ST : stk rsegs m1 lo (bv_unsigned sp-CRC_FRAME).
  Hypothesis FR : rw_cells rsegs m1 (bv_unsigned sp-CRC_FRAME)
    [CB 8 junk; C8 s8; C8 s7; C8 s6; C8 s5; C8 s4; C8 s3; C8 s2; C8 s1; C8 s0].
  Theorem crc32_epilogue : forall (q : Z)
    t0 t1 t2 g8 g9 a1 a2 a5 a6 a7 g18 g19 g20 g21 g22 g23 g24 t3 t4 t5 t6,
    (0 <= q < 2^32)%Z ->
    evt rsegs (crc32_value_post (Z.lxor q CRC_MASK)
      ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 F fc lo m)
    (MS (mkR ra (Z_to_bv 64 (bv_unsigned sp-CRC_FRAME)) gp tp t0 t1 t2 g8 g9
      (Z_to_bv 64 CRC_TABS) a1 a2 (Z_to_bv 64 CRC_MASK) (Z_to_bv 64 q) a5 a6 a7
      g18 g19 g20 g21 g22 g23 g24 s9 s10 s11 t3 t4 t5 t6)
      F (Z_to_bv 64 0x14bb4) fc None m1 (seg_rom rsegs)).
  Proof.
    intros. unfold crc32_value_post,CRC_FRAME in *.
    pose proof (bv_unsigned_in_range _ sp) as Rsp.
    do 11 zstep.
    replace (bv_unsigned sp-80+80)%Z with (bv_unsigned sp) by lia.
    rewrite Z_to_bv_bv_unsigned.
    change (CRC_MASK mod 18446744073709551616)%Z with CRC_MASK.
    release_frame FR ST (bv_unsigned sp).
    zstep. finish.
  Qed.
End CrcEpilogue.
