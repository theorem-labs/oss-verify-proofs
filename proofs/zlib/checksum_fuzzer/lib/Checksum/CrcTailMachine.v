Section ByteTailLoop.
  Variables (ra sp gp tp t0 t1 t2 s0 s1 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
    (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte).
  Variables (B : Z) (inp : list byte).
  Hypothesis INP : bytes_at rsegs m B inp.
  Hypothesis TABLE : bytes_at rsegs m CRC_TABS crc_table_bytes.
  Hypothesis TOP : (B+Z.of_nat (length inp) < 2^64)%Z.
  Variable Q : machine_state -> Prop.
  Notation L := (Z.of_nat (length inp)).
  Notation AT pc x11 x12 x13 x14 x15 x16 :=
    (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 CRC_TABS)
      x11 x12 x13 x14 x15 x16 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
      F (Z_to_bv 64 pc) fc None m (seg_rom rsegs)).
  Lemma tail_byte_loop : forall (k : nat) (i q : Z) x13 x15 x16,
    k = Z.to_nat (L-i) -> (0 <= i < L)%Z -> (0 <= q < 2^32)%Z ->
    (forall x15', evt rsegs Q
      (AT 0x14bb4 (Z_to_bv 64 (B+L)) (Z_to_bv 64 (B+L)) x13
        (Z_to_bv 64 (raw_crc (skipn (Z.to_nat i) inp) q)) x15' (Z_to_bv 64 (B+L)))) ->
    evt rsegs Q (AT 0x14b88 (Z_to_bv 64 (B+i)) (Z_to_bv 64 (B+L)) x13
      (Z_to_bv 64 q) x15 x16).
  Proof.
    induction k as [|k IH];intros i q x13 x15 x16 Hk Hi Hq CONT;[lia|].
    pose proof (bytes_at_bound _ _ _ _ INP) as BB.
    rewrite (raw_suffix_step inp i q Hi) in CONT.
    eapply tail_byte_update;[exact INP|exact TABLE|exact Hi|exact Hq|].
    intros x15'. zstep. if_cases K; zify_cond K.
    - replace (B+i+1)%Z with (B+(i+1))%Z by lia.
      eapply (IH (i+1)%Z (raw_byte q (bbyte inp i)));
        [lia|lia|apply raw_byte_range;exact Hq|exact CONT].
    - assert (E : (i+1=L)%Z) by lia.
      rewrite E in CONT. rewrite Nat2Z.id in CONT.
      rewrite skipn_all in CONT. cbn [raw_crc] in CONT.
      replace (B+i+1)%Z with (B+L)%Z by lia. apply CONT.
  Qed.
End ByteTailLoop.
