Section ByteTail.
  Variables (ra sp gp tp t0 t1 t2 s0 s1 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
    (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte).
  Variables (B : Z) (inp : list byte).
  Hypothesis INP : bytes_at rsegs m B inp.
  Hypothesis TABLE : bytes_at rsegs m CRC_TABS crc_table_bytes.
  Variable Q : machine_state -> Prop.
  Notation AT pc x11 x12 x13 x14 x15 x16 :=
    (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 CRC_TABS)
      x11 x12 x13 x14 x15 x16 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
      F (Z_to_bv 64 pc) fc None m (seg_rom rsegs)).

  Lemma tail_byte_update : forall (i q : Z) x12 x13 x15 x16,
    (0 <= i < Z.of_nat (length inp))%Z -> (0 <= q < 2^32)%Z ->
    (forall x15', evt rsegs Q (AT 0x14bb0 (Z_to_bv 64 (B+i+1)) x12 x13
      (Z_to_bv 64 (raw_byte q (bbyte inp i))) x15' (Z_to_bv 64 (B+i+1)))) ->
    evt rsegs Q (AT 0x14b88 (Z_to_bv 64 (B+i)) x12 x13 (Z_to_bv 64 q) x15 x16).
  Proof.
    intros i q x12 x13 x15 x16 Hi Hq CONT.
    pose proof (rd1_at rsegs m B inp i _ INP ltac:(lia) ltac:(lia) eq_refl) as RD.
    pose proof (byte_unsigned_range (bbyte inp i)) as Hb.
    set (b := bv_unsigned (bbyte inp i)) in *.
    set (ix := Z.land (Z.lxor b q) 255).
    assert (Hix : (0 <= ix < 256)%Z) by (unfold ix;pose proof (land255_range (Z.lxor b q));lia).
    pose proof (crc_byte_table_at m ix TABLE Hix) as RT.
    replace (4*ix)%Z with (Z.shiftl ix 2) in RT by (rewrite Z.shiftl_mul_pow2 by lia;ring).
    unfold ix,b in RT.
    pose proof (csteps_range 8 ix ltac:(lia)) as Htable.
    assert (VAL : Z.lxor (Z.shiftr q 8)
      (bv_unsigned (zx32 (Z_to_bv 64 (csteps 8 ix)))) = raw_byte q (bbyte inp i)).
    { rewrite (Exec.DA_Myrk.zx32_small (csteps 8 ix) Htable).
      rewrite Z_to_bv_unsigned. unfold bv_wrap. change (bv_modulus 64) with (2^64)%Z.
      rewrite Z.mod_small by lia. unfold raw_byte. fold b.
      rewrite (byte_table_step q b Hq Hb). unfold ix.
      rewrite (Z.lxor_comm b q). apply Z.lxor_comm. }
    do 10 zstep.
    fold b ix. rewrite VAL.
    apply CONT.
  Qed.
End ByteTail.
