Lemma adler_srliw16_pack : forall a b,
  (0 <= a < ADLER_BASE)%Z -> (0 <= b < ADLER_BASE)%Z ->
  bv_swrap 32 (Z.shiftr (bv_wrap 32 (adler_pack a b)) 16) = b.
Proof.
  intros a b HA HB. unfold bv_wrap. change (bv_modulus 32) with (2^32)%Z.
  rewrite (Z.mod_small (adler_pack a b) (2^32) (adler_pack_range a b HA HB)),(adler_pack_high a b HA).
  unfold_swrap32. unfold ADLER_BASE in HB. rewrite Z.mod_small;lia.
Qed.
Lemma adler_seed_decode : forall (ra sp gp tp t0 t1 t2 s0 s1 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
  (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte) (Q : machine_state -> Prop) a b,
  (0 <= a < ADLER_BASE)%Z -> (0 <= b < ADLER_BASE)%Z ->
  evt rsegs Q (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 1) a1 a2 (Z_to_bv 64 b) (Z_to_bv 64 a) a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6) F (Z_to_bv 64 0x14dd8) fc None m (seg_rom rsegs)) ->
  evt rsegs Q (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 (adler_pack a b)) a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6) F (Z_to_bv 64 0x14dc8) fc None m (seg_rom rsegs)).
Proof. intros ra sp gp tp t0 t1 t2 s0 s1 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 F fc m Q a b HA HB CONT.
  pose proof (adler_pack_range a b HA HB) as HP.
  do 1 zstep. rewrite adler_srliw16_pack by assumption.
  do 3 zstep. rewrite adler_pack_low by assumption. exact CONT.
Qed.
