Section CrcAlignByte.
  Variables (ra sp gp tp t0 t1 t2 s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
    (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte).
  Variables (B : Z) (inp : list byte).
  Hypothesis INP : bytes_at rsegs m B inp.
  Hypothesis TABLE : bytes_at rsegs m CRC_TABS crc_table_bytes.
  Variable Q : machine_state -> Prop.
  Notation L := (Z.of_nat (length inp)).
  Notation AT pc x11 x12 x13 x14 x16 x17 :=
    (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 CRC_TABS)
      x11 x12 x13 x14 (Z_to_bv 64 1) x16 x17 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
      F (Z_to_bv 64 pc) fc None m (seg_rom rsegs)).
  Theorem crc_align_byte : forall (i q : Z) x13 x16 x17,
    (0 <= i < L)%Z -> (0 <= q < 2^32)%Z ->
    (forall x16', evt rsegs Q
      (AT 0x14604 (Z_to_bv 64 (B+i+1)) (Z_to_bv 64 (L-i-1)) x13
        (Z_to_bv 64 (raw_byte q (bbyte inp i))) x16' (Z_to_bv 64 (L-i)))) ->
    evt rsegs Q
      (AT 0x145d8 (Z_to_bv 64 (B+i)) (Z_to_bv 64 (L-i)) x13 (Z_to_bv 64 q) x16 x17).
  Proof.
    intros i q x13 x16 x17 Hi Hq CONT.
    pose proof (rd1_at rsegs m B inp i _ INP ltac:(lia) ltac:(lia) eq_refl) as RD.
    pose proof (byte_unsigned_range (bbyte inp i)) as HB.
    pose proof (land255_range (Z.lxor (bv_unsigned (bbyte inp i)) q)) as HI.
    pose proof (crc_byte_table_at m (Z.land (Z.lxor (bv_unsigned (bbyte inp i)) q) 255) TABLE ltac:(lia)) as RT.
    replace (4*Z.land (Z.lxor (bv_unsigned (bbyte inp i)) q) 255)%Z with
      (Z.shiftl (Z.land (Z.lxor (bv_unsigned (bbyte inp i)) q) 255) 2) in RT
      by (rewrite Z.shiftl_mul_pow2 by lia;ring).
    do 11 zstep. rewrite (crc_loaded_byte_value q (bbyte inp i) Hq). apply CONT.
  Qed.
End CrcAlignByte.
