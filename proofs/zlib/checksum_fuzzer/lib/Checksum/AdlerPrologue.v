Section AdlerPrologue.
  Variables (ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
    (F : bvmap 5 word) (fc : bv 32) (lo : Z) (m : word -> option byte).
  Variables (B : Z) (inp : list byte).
  Hypothesis INP : bytes_at rsegs m B inp.
  Hypothesis TABLE : bytes_at rsegs m 0x119e0 (le8 (Z_to_bv 64 ADLER_MAGIC)).
  Hypothesis ST : stk rsegs m lo (bv_unsigned sp).
  Hypothesis LO : (lo+ADLER_FRAME <= bv_unsigned sp)%Z.
  Hypothesis DI : (B+Z.of_nat (length inp) <= bv_unsigned sp-ADLER_FRAME \/ bv_unsigned sp <= B)%Z.
  Hypothesis DT : (0x119e0+8 <= bv_unsigned sp-ADLER_FRAME \/ bv_unsigned sp <= 0x119e0)%Z.
  Variable Q : machine_state -> Prop.
  Theorem adler_save_frame :
    (forall m1 junk,
      munch [(bv_unsigned sp-ADLER_FRAME,bv_unsigned sp)]%Z m m1 ->
      wmono rsegs m m1 -> stk rsegs m1 lo (bv_unsigned sp-ADLER_FRAME) ->
      rw_cells rsegs m1 (bv_unsigned sp-ADLER_FRAME)
        [CB 8 junk;C8 s2;C8 s1;C8 s0] ->
      bytes_at rsegs m1 B inp -> bytes_at rsegs m1 0x119e0 (le8 (Z_to_bv 64 ADLER_MAGIC)) ->
      evt rsegs Q (MS (mkR ra (Z_to_bv 64 (bv_unsigned sp-ADLER_FRAME)) gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
        F (Z_to_bv 64 0x14e40) fc None m1 (seg_rom rsegs))) ->
    evt rsegs Q (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
      F (Z_to_bv 64 0x14e30) fc None m (seg_rom rsegs)).
  Proof.
    intros CONT. unfold ADLER_FRAME in *.
    assert (TI : forall m1, munch [(bv_unsigned sp-32,bv_unsigned sp)]%Z m m1 -> bytes_at rsegs m1 B inp).
    { intros m1 HM. eapply bytes_at_transport;[exact INP|exact HM|].
      cbn [disjoint_from]. exact (conj DI I). }
    assert (TT : forall m1, munch [(bv_unsigned sp-32,bv_unsigned sp)]%Z m m1 -> bytes_at rsegs m1 0x119e0 (le8 (Z_to_bv 64 ADLER_MAGIC))).
    { intros m1 HM. eapply bytes_at_transport;[exact TABLE|exact HM|].
      rewrite length_le8. cbn [disjoint_from]. exact (conj DT I). }
    clear INP TABLE.
    pose proof (munch_refl [(bv_unsigned sp-32,bv_unsigned sp)]%Z m) as MU.
    pose proof (wmono_refl rsegs m) as WM.
    pose proof (bv_unsigned_in_range 64 sp) as Rsp.
    carve_frame 32%nat ST.
    do 4 zstep. try Stor0fe.sb_flush.
    eapply CONT;[exact MU|exact WM|exact ST|exact FR|apply TI;exact MU|apply TT;exact MU].
  Qed.
End AdlerPrologue.
