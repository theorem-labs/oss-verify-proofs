Section CrcTailReturn.
  Variables (ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 : word)
    (F : bvmap 5 word) (fc : bv 32) (lo : Z) (m m1 : word -> option byte) (junk : list byte).
  Variables (B : Z) (inp : list byte).
  Hypothesis INP : bytes_at rsegs m1 B inp.
  Hypothesis TABLE : bytes_at rsegs m1 CRC_TABS crc_table_bytes.
  Hypothesis TOP : (B+Z.of_nat (length inp) < 2^64)%Z.
  Hypothesis MU : munch [(bv_unsigned sp-CRC_FRAME,bv_unsigned sp)]%Z m m1.
  Hypothesis WM : wmono rsegs m m1.
  Hypothesis LO : (lo+CRC_FRAME <= bv_unsigned sp)%Z.
  Hypothesis ST : stk rsegs m1 lo (bv_unsigned sp-CRC_FRAME).
  Hypothesis FR : rw_cells rsegs m1 (bv_unsigned sp-CRC_FRAME)
    [CB 8 junk; C8 s8; C8 s7; C8 s6; C8 s5; C8 s4; C8 s3; C8 s2; C8 s1; C8 s0].
  Theorem crc_tail_returns : forall (i q : Z)
    t0 t1 t2 g8 g9 a3 a5 a6 a7 g18 g19 g20 g21 g22 g23 g24 t3 t4 t5 t6,
    (0 <= i <= Z.of_nat (length inp))%Z -> (0 <= q < 2^32)%Z ->
    evt rsegs (crc32_value_post (Z.lxor (raw_crc (skipn (Z.to_nat i) inp) q) CRC_MASK)
      ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 F fc lo m)
    (MS (mkR ra (Z_to_bv 64 (bv_unsigned sp-CRC_FRAME)) gp tp t0 t1 t2 g8 g9
      (Z_to_bv 64 CRC_TABS) (Z_to_bv 64 (B+i)) (Z_to_bv 64 (Z.of_nat (length inp)-i))
      a3 (Z_to_bv 64 q) a5 a6 a7 g18 g19 g20 g21 g22 g23 g24 s9 s10 s11 t3 t4 t5 t6)
      F (Z_to_bv 64 0x14a60) fc None m1 (seg_rom rsegs)).
  Proof.
    intros i q t0 t1 t2 g8 g9 a3 a5 a6 a7 g18 g19 g20 g21 g22 g23 g24 t3 t4 t5 t6 Hi Hq.
    eapply crc_tail_all;[exact INP|exact TABLE|exact TOP|exact Hi|exact Hq|].
    intros. unfold crc_tail_cont. intros.
    eapply crc32_epilogue;
      [exact MU|exact WM|exact LO|exact ST|exact FR|apply raw_crc_range;exact Hq].
  Qed.
End CrcTailReturn.
