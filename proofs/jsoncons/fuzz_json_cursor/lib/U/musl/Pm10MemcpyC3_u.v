        stepn F_b5be8 D_b5be8. stepn F_b5bec D_b5bec.
        stepn F_b5bf0 D_b5bf0.
        msw F_b5bf4 D_b5bf4 kk ltac:(m8).
        msw F_b5bf8 D_b5bf8 (kk + 4)%Z ltac:(m8).
        msw F_b5bfc D_b5bfc (kk + 8)%Z ltac:(m8).
        msw F_b5c00 D_b5c00 (kk + 12)%Z ltac:(m8).
        stepn F_b5c04 D_b5c04.
        stepn F_b5c08 D_b5c08.
        stepb_ft F_b5c0c D_b5c0c ltac:(unfold v_addi; cond).
        mk_eq. apply mst_refl.
