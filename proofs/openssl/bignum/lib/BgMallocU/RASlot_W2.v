  pose proof MR' as (_ & _ & (_ & _ & _ & _ & GUARD & _) & _).
  unfold RSSP_GUARD, rta_frame, OssFuzzTheorems.Proofs.openssl.bignum.lib.Spec.Malloc.MCEIL in *; try (pose proof ceil_window_holds as CEIL_RANGE__); unfold ceil_window in *.
