Lemma ru64s_read : forall m A ws (i : Z) w a,
  bytes_at bgusegs m A (u64s ws) -> nth_error ws (Z.to_nat i) = Some w -> 0 <= i -> a = wa (A + 8 * i) ->
  ov_read_bytes bgusegs m a 8 = Some (le8 w).
