Definition payload_shadow_ok (data n : Z) (mem : word -> option byte) : Prop :=
  (forall g, 0 <= g < n / 8 -> mem_byte mem (SH_A + data / 8 + g) 0) /\
  (n mod 8 <> 0 -> mem_byte mem (SH_A + data / 8 + n / 8) (n mod 8)).

