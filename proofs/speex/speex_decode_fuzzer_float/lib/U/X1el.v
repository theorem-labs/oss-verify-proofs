Definition rfree_opt_null_stmt_at (ENTRY : Z) : Prop :=
forall (ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
(F : bvmap 5 word) (fc : bv 32) (m : mem) (s : PState),
a0 = Z_to_bv 64 0 ->
implM rsegs (raw_free_opt None) s
(fun (_ : unit) s' ms' => s' = s /\
ms' = MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
F (ret_pc ra) fc None m (seg_rom rsegs))
(MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
F (Z_to_bv 64 ENTRY) fc None m (seg_rom rsegs)).

Lemma rfree_opt_null_spec : rfree_opt_null_stmt_at RFREE_SYM.
Proof.
intros until s. intros A0. rewrite raw_free_opt_none. apply implM_ret.
eapply evt_mono; [exact (rfree_null_spec ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 F fc m A0)|].
intros ms' ->. split; reflexivity.
Qed.

Lemma rlibc_free_opt_null_spec : rfree_opt_null_stmt_at rfree_entry.
Proof.
intros until s. intros A0. rewrite raw_free_opt_none. apply implM_ret.
eapply evt_mono; [exact (rlibc_free_null_spec ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 F fc m A0)|].
intros ms' ->. split; reflexivity.
Qed.
