Lemma dig_shape : forall i, 0 <= dig i < 65536 \/ dig i = 4294967295.
Proof.
  intros i. unfold dig.
  assert (F : forallb (fun x => ((0 <=? x) && (x <? 65536)) || (x =? 4294967295)) DIGIT_TAB = true) by (vm_compute; reflexivity).
  rewrite forallb_forall in F.
  destruct (Nat.lt_ge_cases (Z.to_nat i) (length DIGIT_TAB)) as [L|L].
  - specialize (F _ (nth_In DIGIT_TAB 0 L)). apply orb_true_iff in F. destruct F as [F|F].
    + apply andb_true_iff in F. destruct F as [F1 F2]. apply Z.leb_le in F1. apply Z.ltb_lt in F2. left. lia.
    + apply Z.eqb_eq in F. right. exact F.
  - rewrite nth_overflow by exact L. left. lia.
Qed.

