# The minutes of unit time one check job is planned for.  GitHub cancels a hosted job at 360 minutes.  In run
# 42556340137 a sweep job spent 8 to 13 minutes on its checkout, its hash-pinned pip installs and its image pull, and
# about 4 more on its units without proofs, so 210 minutes of measured unit time plans a job of about 3.8 hours and
# leaves over 2 hours of margin.  A single unit above the cap cannot be made to fit by planning: it gets a job to
# itself and the job takes what the unit takes.
CAP = 210

# The most minutes one unit's check may take and still be run on a hosted runner.  GitHub cancels the job at 360
# and a shard pays 8 to 13 of those before its first unit, so a unit above this cannot be held inside the four
# hours the sweep plans its shards to; no packing can help, since a shard is never shorter than its longest unit.
# A sweep planned with `hosted` leaves such a unit out and its run summary names it (plan.hosted_skips).  Which
# units those are is read off SWEEP_TIMES and is never a list written by hand; `oft plan --hosted` names each
# one it leaves out, with the farm check of record that still stands for it, and no list of them is written
# down here, since a unit named in a shipped file is a unit the release says exists.  Three were over the cap
# on 2026-11-09, the longest at 347 minutes and itself a floor.  The cap is the four hours a shard is planned
# to and not the 6-hour limit itself, because a unit grows between runs: over the two runs of that day one
# unit went from 274 minutes to 302 and another from 191 to 260, so a unit at 300 could be cancelled on a
# slower day.
HOSTED_CAP = 240


def load(path=TABLE):
    """{unit: (minutes, peak_gib, cpus)} from the sizing table; lines starting with '#' and the header are skipped.  A
    unit listed twice, or a value that is not a positive finite number, is an error."""
    out = {}
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            if not line.strip() or line.startswith("#") or line.startswith("unit\t"):
                continue
            unit, minutes, peak, cpus = line.rstrip("\n").split("\t")
            if unit in out or not int(minutes) > 0 or not 0 < float(peak) < math.inf or not int(cpus) > 0:
                raise ValueError("%s:%d: a unit listed twice, or a value that is not a positive finite number"
                                 % (path, n))
            out[unit] = (int(minutes), float(peak), int(cpus))
    return out


def best_reading(readings):
    """One unit's row out of its readings, each (minutes, run, whether that run's check finished), as
    (minutes, run, outcome): a reading whose check finished beats one the 6-hour limit cut short however much
    longer the cut one ran, since a cut gives a floor and never a time; among readings of one kind the longest
    wins.  One unit finished at 169 minutes in run 42556340137 and was still running at 179 when run
    42597756616's shard 20 was cancelled: its row is 169 `finished`, not 179 of either kind (the second review
    of #2477).  No readings at all is an error: a unit nothing read has no row, which the packer reads as
    untimed, and a row made up here would be a weight with nothing behind it."""
    if not readings:
        raise ValueError("pack.best_reading: no reading to make a row from")
    finished = [(m, run) for m, run, fin in readings if fin]
    if finished:
        minutes, run = max(finished)
        return minutes, run, "finished"
    minutes, run = max((m, run) for m, run, _fin in readings)
    return minutes, run, "cut"


def sweep(rows=SWEEP_TIMES):
    """{unit: (minutes, outcome)}: each unit's row, derived from its readings in SWEEP_TIMES by best_reading, so
    no hand-written row can set a weight the rule would not.  One unit read twice in one run, a time that is not
    a positive whole number of minutes, a row naming no run, and an outcome that is neither `finished` nor `cut`
    are each an error: a weight with no measurement behind it is what the packer must not have, and these
    readings are typed by hand out of job logs."""
    readings = {}
    for unit, run, minutes, outcome in rows:
        if not isinstance(minutes, int) or minutes <= 0 or not run.strip() \
                or outcome not in ("finished", "cut") \
                or any(r == run for _m, r, _f in readings.get(unit, ())):
            raise ValueError("pack.SWEEP_TIMES: the reading of %r in run %r is listed twice, gives a time that "
                             "is not a positive whole number of minutes, names no run, or has an outcome that "
                             "is neither finished nor cut" % (unit, run))
        readings.setdefault(unit, []).append((minutes, run, outcome == "finished"))
    out = {}
    for unit, rs in readings.items():
        minutes, _run, outcome = best_reading(rs)
        out[unit] = (minutes, outcome)
    return out


def times(rows=SWEEP_TIMES):
    """{unit: minutes} for the units whose check some run saw finish: the weights the packer deals by.  A unit no
    run ever saw finish has no time of its own, only a floor, so it is not here and the packer gives it a job of
    its own like any other unit it has no time for."""
    return {u: m for u, (m, outcome) in sweep(rows).items() if outcome == "finished"}


def too_long_for_hosted(rows, cap=HOSTED_CAP):
    """The units of a `sweep` mapping that no hosted job can check, in name order: those measured above `cap`,
    whether the check finished or the 6-hour limit cut it short, since a floor already above the cap settles it.
    A unit with no row at all is not here: nothing measured says it does not fit."""
    return sorted(u for u, (minutes, _outcome) in rows.items() if minutes > cap)


def farm_checks(rows=FARM_CHECKS):
    """{unit: (run, date)}: the last passing farm check of record of each unit FARM_CHECKS lists, for the summary
    of a hosted sweep that leaves a unit out.  A unit with no passing one has no row.  A unit listed twice, a run
    that is not a `farm/<run>`, or a date that is not a UTC day is an error."""
    out = {}
    for unit, run, date in rows:
        if unit in out or not FARM_RUN.fullmatch(run) or not DAY.fullmatch(date):
            raise ValueError("pack.FARM_CHECKS: %r is listed twice, names a run that is not farm/<run>, or gives "
                             "a date that is not a UTC day" % (unit,))
        out[unit] = (run, date)
    return out


def full_width(table):
    """The most CPUs the table gives any unit: the runner's own width, which a job asking for it needs no limit for."""
    return max((row[2] for row in table.values()), default=0)


def unmeasured(units, proved, measured):
    """Those of units with proofs that `measured` gives no time, in name order: each is dealt a job of its own, and
    `oft plan` names them, since a unit enrolled since the last sweep has no measured time yet."""
    return sorted(u for u in units if u in proved and u not in measured)


def jobs_needed(table, measured, cap=CAP, skip=()):
    """The fewest jobs the units `measured` times need for no job holding more than one of them to pass `cap`: one
    for each unit that takes a job to itself, and `cap` minutes of the rest in each of the others.  `skip` is left
    out of the count: a hosted plan does not run those units at all (too_long_for_hosted).  This is a floor, over
    the units the sweep has timed; the plan gives a job to each untimed unit too, so a workflow's --max-jobs stands
    above it (tools/oft/tests/test_workflow_verdicts.py reads weekly.yml's against this)."""
    full = full_width(table)
    measured = {u: m for u, m in measured.items() if u not in skip}
    alone = {u for u, m in measured.items() if m > cap or (u in table and table[u][2] < full)}
    rest = sum(m for u, m in measured.items() if u not in alone)
    return len(alone) + math.ceil(rest / cap)


def shards(units, n, proved, table, measured, cap=CAP):
    """units dealt into n lists (n >= 1, at most len(units) when units is not empty), each sorted.  First each unit in
    `proved` that needs a job to itself, slowest first, when that leaves a job for the other proved units: one the
    table gives fewer CPUs than its most, one `measured` puts above `cap`, and one `measured` does not time at all.
    Then the other units in `proved` longest first, each to the job with the least time so far among the jobs not
    given to one of those; then the rest each to the job with the fewest units, so no job is empty.  Where there are
    not jobs enough for one each, no unit gets a job to itself and an untimed one counts as the longest timed one (an
    untimed unit is never a middling one: see the module's docstring)."""
    full = full_width(table)
    longest = max(measured.values(), default=1)
    minutes = lambda u: measured.get(u, longest)
    # math.inf for an untimed unit: above any cap, and first among the units dealt a job of their own
    weight = lambda u: measured.get(u, math.inf)
    alone = sorted((u for u in units if u in proved
                    and ((u in table and table[u][2] < full) or weight(u) > cap)),
                   key=lambda u: (-weight(u), u))
    if len(alone) >= n:
        alone = []
    out = [[] for _ in range(n)]
    load_ = [0] * n
    for i, u in enumerate(alone):
        out[i].append(u)
        load_[i] = math.inf
    for u in sorted((u for u in units if u in proved and u not in alone), key=lambda u: (-minutes(u), u)):
        i = min(range(n), key=lambda j: (load_[j], j))
        out[i].append(u)
        load_[i] += minutes(u)
    for u in sorted(u for u in units if u not in proved):
        out[min(range(n), key=lambda j: (len(out[j]), j))].append(u)
    return [sorted(s) for s in out]


def job_cpus(units, table):
    """The CPUs a job may use, for the units whose proofs it checks (the plan passes only those: a unit checked for
    its statements, counterexamples or findings alone never needs fewer): the fewest the table gives any of them, or 0
    (every CPU) when it lists none of them or gives each of them the most it gives any unit, the runner's full width."""
    full = full_width(table)
    fewest = min([table[u][2] for u in units if u in table], default=0)
    return 0 if fewest >= full else fewest
