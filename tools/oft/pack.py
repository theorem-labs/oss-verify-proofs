"""How `oft plan` deals units into check jobs, from the minutes the sweep measured for each unit (SWEEP_TIMES).

A check job runs its units one after the other, and a unit with proofs takes from minutes to hours (no cache: a pull
request saves none), while a unit without proofs takes seconds.  Dealt in name order, the heavy units piled up in a
few jobs and those jobs hit the 6-hour limit.  So the units with proofs go first, longest first, each to the job with
the least time so far (ties to the lowest index), and then the rest each to the job with the fewest units.  The result
depends only on the units, the set with proofs, the job count and the two tables, so it is deterministic.

A unit measured above CAP, and a unit with proofs the sweep has not measured at all, is dealt a job of its own.  An
unmeasured one counts as longer than any measured one, and never as a middling one: that is what lost shard 29 of
run 42556340137 (2026-11-09).  Its longest unit takes 236 minutes, no table listed it, the packer gave it the
listed median of 41, and the shard reached the 6-hour limit and was cancelled with no result.

The minutes here are the sweep's own, on the 16-core GitHub-hosted runner it runs on.  proof-times.tsv's minutes are
the release gate's 32-vCPU figures, which the build farm's job sizing projects widths from
(minutes * 60 * 32/n), so the two are not interchangeable; proof-times.tsv still gives the `cpus` column, which is
measured on the 16-core runner, and nothing is duplicated between them.

A job also carries `cpus`, the CPUs its check may use: the fewest proof-times.tsv gives any of its units, where a unit
that passed at the runner's full width counts for no limit.  Those are the CPUs measured to be safe on a 16-core 64 GB
runner (leptonica/paintcmap_fuzzer ran out of memory at 16, and openssl/hashtable swapped); 0 means every CPU the
runner has, so a larger runner is never held to 16.  ci/check-units.sh gives the checker container that many CPUs.
Since every unit of a limited job then runs on fewer CPUs, a proved unit the table limits gets a job with no other
proved unit, while there are jobs enough for the rest."""
