Ltac norm_bytes :=
  repeat first [ change (sxb (Z_to_bv 8 0)) with (Z_to_bv 64 0 : word) | change (zxb (Z_to_bv 8 0)) with (Z_to_bv 64 0 : word)
               | change (sxb (Z_to_bv 8 1)) with (Z_to_bv 64 1 : word) | change (zxb (Z_to_bv 8 1)) with (Z_to_bv 64 1 : word)
               | change (sxb (Z_to_bv 8 2)) with (Z_to_bv 64 2 : word) | change (zxb (Z_to_bv 8 2)) with (Z_to_bv 64 2 : word) ].
Ltac astep := zstep; norm_bytes; try (first [if_true | if_false]).
Ltac at_pc p := lazymatch goal with |- evtF _ _ _ (MS _ _ (Z_to_bv 64 ?q) _ _ _ _) => constr_eq q p end.
Ltac steps_to p := repeat (tryif at_pc p then fail else astep).
