Definition HS2 (r : Z) (w : bool) : acs := hstate (HSL_2 r) (ST_2 r) (if w then 1%nat else 2%nat).
Lemma HS2_cases : forall r h ch, 0 <= r <= 1 -> hlookup (HSL_2 r) h = Some ch -> exists w, ch = HS2 r w.
Proof.
  intros r h ch Hr Hh.
  assert (Hin : In h (map fst (HSL_2 r))).
  { revert Hh. generalize (HSL_2 r) as l. induction l as [|[h' a] l IH]; cbn; [intros Hh; discriminate|].
    destruct (Nat.eqb h h') eqn:E; intros Hh; [left; symmetry; apply Nat.eqb_eq; exact E | right; exact (IH Hh)]. }
  destruct (keys_2 r Hr h Hin) as [-> | ->]; [exists true | exists false]; unfold HS2, hstate; cbv beta iota; rewrite Hh; reflexivity.
Qed.

