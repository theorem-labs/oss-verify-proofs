  assert (F : forallb (fun x => ((0 <=? x) && (x <? 65536)) || (x =? 4294967295)) OD_DIGIT_TAB = true) by (vm_compute; reflexivity).
  rewrite forallb_forall in F.
  destruct (Nat.lt_ge_cases (Z.to_nat i) (length OD_DIGIT_TAB)) as [L|L].
  - specialize (F _ (nth_In OD_DIGIT_TAB 0 L)). apply orb_true_iff in F. destruct F as [F|F].
