Lemma otab_range : forall tab hi c, forallb (fun x => (0 <=? x) && (x <? hi)) tab = true -> 0 < hi -> 0 <= nth (Z.to_nat c) tab 0 < hi.
Proof.
  intros tab hi c F Hh. rewrite forallb_forall in F.
  destruct (Nat.lt_ge_cases (Z.to_nat c) (length tab)) as [L|L].
  - specialize (F _ (nth_In tab 0 L)). apply andb_true_iff in F. destruct F as [F1 F2]. apply Z.leb_le in F1. apply Z.ltb_lt in F2. lia.
