Definition cache_dealloc_specC : Prop :=
  forall (ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
         (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte) (mo : Model) (g : lghost)
         (st : rtstate) (c k lo : Z),
  RTS st m mo g ->
  In (c, k) (st_apend st) -> 1 <= c <= 30 ->
  a0 = wz (acache st) -> a1 = wz A_ALLOC -> a2 = wz c -> a3 = wz (cptr_addr st c k) ->
  tp = wz ATP ->
  rt_prov st <= g_res g ->
  stk asegs m lo (bv_unsigned sp) -> alloc_ceiling <= lo -> lo <= bv_unsigned sp - ACDEALLOC_STACK ->
  mem_inv asegs m ->
  LSCPS asegs (cdealloc_post ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 F fc st c k lo m g)
        (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
            F (wz ACDEALLOC) fc None m (seg_rom asegs)) mo g.

