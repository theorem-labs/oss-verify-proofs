Definition grant_refusable (m : Model) (n : Z) : bool :=
  mmap_grant_refusable (Z_to_bv 64 34) m n.

Lemma grant_ok_not_refusable : forall hint m a n,
  grant_ok hint m a n = true -> grant_refusable m n = false.
Proof.
  intros hint m a n H. unfold grant_ok in H. rewrite !andb_true_iff in H.
  destruct H as [[[[H1 H2] H3] H4] H5].
  apply Z.eqb_eq in H1. apply Z.ltb_lt in H2. apply Z.leb_le in H3.
  unfold grant_refusable.
  apply (mmap_grant_not_refusable (Z_to_bv 64 34) m n a H1 H2 H3 H4).
  unfold mmap_noreserve_backed_ok.
  replace (mmap_noreserve_b (Z_to_bv 64 34)) with false by (vm_compute; reflexivity).
  exact H5.
Qed.

Lemma grant_refusable_false_iff : forall hint m n,
  grant_refusable m n = false <-> exists a, grant_ok hint m a n = true.
Proof.
  intros hint m n. split.
  - intros H. unfold grant_refusable in H.
    destruct (mmap_grant_refusable_false _ _ _ H) as (Hb & a & H1 & H2 & H3 & H4).
    unfold mmap_noreserve_backed_ok in Hb.
    replace (mmap_noreserve_b (Z_to_bv 64 34)) with false in Hb by (vm_compute; reflexivity).
    exists a. unfold grant_ok.
    rewrite (proj2 (Z.eqb_eq _ _) H1), (proj2 (Z.ltb_lt _ _) H2), (proj2 (Z.leb_le _ _) H3), H4, Hb.
    reflexivity.
  - intros (a & Ha). exact (grant_ok_not_refusable hint m a n Ha).
Qed.

