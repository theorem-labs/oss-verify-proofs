Definition istrlen_entry : Z := 0x6a2c4.

Definition istrlen_post (ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 : word) (F : bvmap 5 word) (fc : bv 32)
    (a0 : word) (str slack : list byte) (m : word -> option byte) : machine_state -> Prop :=
  fun ms' => exists t0 t1 t2 a1 a2 a3 a4 a5 a6 a7 t3 t4 t5 t6,
    ms' = MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 (Z.of_nat (length str))) a1 a2 a3 a4 a5 a6 a7
                 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
             F (ret_pc ra) fc None m (seg_rom rsegs)
    /\ munch [] m m /\ wmono rsegs m m /\ mem_inv rsegs m
    /\ bytes_at rsegs m (bv_unsigned a0) (str ++ Z_to_bv 8 0 :: slack).

Section P.
  Variables (ra sp gp tp t0 t1 t2 s0 s1 a0 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
            (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte) (str slack : list byte).
  Hypothesis STR : bytes_at rsegs m (bv_unsigned a0) (str ++ Z_to_bv 8 0 :: slack).
  Hypothesis NONUL : ~ In (Z_to_bv 8 0) str.
  Hypothesis MI : mem_inv rsegs m.
  Let MU : munch [] m m := munch_refl [] m.
  Let WM : wmono rsegs m m := wmono_refl rsegs m.
  Notation A := (bv_unsigned a0).
  Notation L := (Z.of_nat (length str)).

  #[using="WM MU MI NONUL STR"] Lemma isl_loop : forall (c j : nat) x12,
    (length str - j = c)%nat -> (j <= length str)%nat ->
    evt rsegs (istrlen_post ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 F fc a0 str slack m)
      (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 (Z_to_bv 64 (Z.of_nat j)) x12 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
          F (Z_to_bv 64 0x6a2c8) fc None m (seg_rom rsegs)).
  Proof.
    induction c as [|c IH]; intros j x12 Hc Hj;
      pose proof (bytes_at_bound _ _ _ _ STR) as AB; rewrite length_app in AB; cbn [length] in AB.
    - assert (E : j = length str) by lia. subst j.
      pose proof (u8ro_read rsegs m A _ L (Z_to_bv 8 0) (Z_to_bv 64 (A + L)) STR
                    ltac:(rewrite Nat2Z.id, nth_error_app2, Nat.sub_diag by lia; reflexivity) ltac:(lia) eq_refl) as RD.
      zstep. zstep. cbv beta. change (bv_unsigned (Z_to_bv 8 0)) with 0%Z. zstep.
      zstep. if_cases K; zify_cond K. { exfalso. lia. }
      zstep. zstep. replace (L + 1 + -1)%Z with L by lia. finish.
    - destruct (nth_error str j) as [b|] eqn:Hb. 2:{ apply nth_error_None in Hb. lia. }
      assert (BNZ : bv_unsigned b <> 0%Z).
      { intros E. apply NONUL. replace (Z_to_bv 8 0) with b; [eapply nth_error_In; exact Hb|]. apply bv_eq. rewrite E. reflexivity. }
      pose proof (bv_unsigned_in_range _ b) as BR.
      pose proof (u8ro_read rsegs m A _ (Z.of_nat j) b (Z_to_bv 64 (A + Z.of_nat j)) STR
                    ltac:(rewrite Nat2Z.id, nth_error_app1 by lia; exact Hb) ltac:(lia) eq_refl) as RD.
      zstep. zstep. cbv beta. zstep.
      zstep. if_cases K; zify_cond K. 2:{ exfalso. lia. }
      replace (Z.of_nat j + 1)%Z with (Z.of_nat (S j)) by lia. apply IH; lia.
  Qed.
End P.

Lemma istrlen_spec : forall ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6
    (F : bvmap 5 word) fc (m : word -> option byte) (str slack : list byte),
  bytes_at rsegs m (bv_unsigned a0) (str ++ Z_to_bv 8 0 :: slack) ->
  ~ In (Z_to_bv 8 0) str ->
  mem_inv rsegs m ->
  evt rsegs (istrlen_post ra sp gp tp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 F fc a0 str slack m)
    (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
        F (Z_to_bv 64 0x6a2c4) fc None m (seg_rom rsegs)).
Proof.
  intros until slack. intros STR NONUL MI.
  pose proof (munch_refl [] m) as MU. pose proof (wmono_refl rsegs m) as WM.
  zstep. change (Z_to_bv 64 0) with (Z_to_bv 64 (Z.of_nat 0)).
  eapply isl_loop; try eassumption; [reflexivity | lia].
Qed.
