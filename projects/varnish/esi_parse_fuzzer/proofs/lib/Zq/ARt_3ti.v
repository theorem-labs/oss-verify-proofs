Theorem rzlog_ok : rzlog_stmt.
Proof.
  unfold rzlog_stmt. intros until lo. intros MI ST LOLE Hl A0 RA.
  unfold rzlog_entry in *.
  pose proof (munch_refl [(bv_unsigned sp - rzlog_stack, bv_unsigned sp)] m) as MU. unfold rzlog_stack in *.
  pose proof (wmono_refl rsegs m) as WM.
  pose proof (zr_word sp) as SPR; unfold inr64 in SPR.
  assert (LO0 : 0 <= lo) by (destruct ST as [? _]; assumption).
  carve_frame 16%nat ST.
  assert (CASES : l = 0 \/ l = 1 \/ l = 2 \/ l = 3 \/ l = 4 \/ l = 5 \/ l = 6 \/ l = 7) by lia.
  destruct CASES as [-> | [-> | [-> | [-> | [-> | [-> | [-> | -> ]]]]]]]; cbn in A0; subst a0.
  all: repeat brstep.
  all: release_frame FR ST (bv_unsigned sp); finish.
Qed.
