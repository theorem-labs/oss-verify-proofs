Definition ssp_cells (mem : word -> option byte) (can : word) : Prop :=
  rdn RSEGS mem (Z_to_bv 64 0x30428) 8%nat = Some (word_to_le_bytes 8 (Z_to_bv 64 0x623c8))
  /\ rdn RSEGS mem (Z_to_bv 64 0x623c8) 8%nat = Some (word_to_le_bytes 8 can).

