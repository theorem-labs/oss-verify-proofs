Theorem get_thread_ok : get_thread_stmt.
Proof.
  unfold get_thread_stmt. intros until lo. intros MI ST LOLE CEIL TC RA. pose proof alloc_ceiling_val as CV.
  unfold get_thread_entry in *.
  pose proof (munch_refl [(bv_unsigned sp - 16, bv_unsigned sp)] m) as MU.
  pose proof (wmono_refl rsegs m) as WM.
  pose proof (zr_word sp) as SPR; unfold inr64 in SPR.
  pose proof (zr_word tp) as TPR; unfold inr64 in TPR.
  assert (LO0 : 0 <= lo) by (destruct ST as [? _]; assumption).
  (first [ dand13 TC as Cini Ckey Ctsd Cctx Cthr Btsd Btsd' Bctx Bctx' Bthr Bthr' Btp Bctx2 | destruct TC as (Cini & Ckey & Ctsd & Cctx & Cthr & Btsd & Btsd' & Bctx & Bctx' & Bthr & Bthr' & Btp & Bctx2) ]). unfold pz_in, pz0_in, fl_in, kLowShadowMapBeg, kHighMemBeg in *. aobj_lin_all.
  replace (bv_unsigned tp - 88) with (bv_unsigned tp + -88) in Ctsd by lia.
  carve_frame 16%nat ST.
  repeat (brstep; fold_xlits).
  br_not_taken.
  repeat (brstep; fold_xlits).
  release_frame FR ST (bv_unsigned sp). finish.
Qed.

Theorem thread_stats_ok : thread_stats_stmt.
Proof.
  unfold thread_stats_stmt. intros until lo. intros MI ST LOLE CEIL TC RA. pose proof alloc_ceiling_val as CV.
  unfold thread_stats_entry in *.
  pose proof (munch_refl [(bv_unsigned sp - 32, bv_unsigned sp)] m) as MU.
  pose proof (wmono_refl rsegs m) as WM.
  pose proof (zr_word sp) as SPR; unfold inr64 in SPR.
  pose proof (zr_word tp) as TPR; unfold inr64 in TPR.
  assert (LO0 : 0 <= lo) by (destruct ST as [? _]; assumption).
  pose proof TC as TC'.
  (first [ dand13 TC' as Cini Ckey Ctsd Cctx Cthr Btsd Btsd' Bctx Bctx' Bthr Bthr' Btp Bctx2 | destruct TC' as (Cini & Ckey & Ctsd & Cctx & Cthr & Btsd & Btsd' & Bctx & Bctx' & Bthr & Bthr' & Btp & Bctx2) ]). unfold pz_in, pz0_in, fl_in, kLowShadowMapBeg, kHighMemBeg in *. aobj_lin_all.
  carve_frame 16%nat ST.
  do 3 zstep.
  callz get_thread_ok.
  1:{ exact MI. }
  1:{ rewrite unsigned_lit by lia. exact ST. }
  1:{ rewrite unsigned_lit by lia. lia. }
  1:{ lia. }
  1:{ unfold thread_cells, kHighMemBeg. split; [exact Cini | split; [exact Ckey | split; [exact Ctsd | split; [exact Cctx | split; [exact Cthr | plia]]]]]. }
  1:{ rewrite unsigned_lit by lia. reflexivity. }
  rename POST into ST.
  zstep. br_not_taken.
  repeat (brstep; fold_xlits).
  release_frame FR ST (bv_unsigned sp).
  unfold off_th_stats.
  finish.
Qed.

