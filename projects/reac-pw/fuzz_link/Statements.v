(** * reac-pw / fuzz_link: theorem statements

    SUBJECT.  Four builds of reac-pw's own fuzz target [fuzz_link], which
    OSS-Fuzz does not run, for reac-pw 1.0.42 (FreeREAC/reac-pw at f86a30a3),
    static riscv64 Linux programs run as [<file> FILE]:
      plain       no sanitizer
      ubsan       UndefinedBehaviorSanitizer; a failed check executes a trap
      asan        AddressSanitizer; a report aborts
      asan_ubsan  both
    [Images] names their memory images.  A driver linked into every build reads
    FILE as [u16 config word][config bytes][u32 allocation mask][payload]
    (little-endian; the low 15 bits of the config word are the config length,
    and this harness binary ignores the mask), calls
    LLVMFuzzerTestOneInput(payload, length) one to four times ((config[0] & 3) +
    1; once when there is no config), and prints each return value.  With a
    wrong argument count, a missing or unreadable FILE, a FILE shorter than its
    header, or one of 64 MiB or more, it exits with status 2 without calling the
    harness.  Every statement quantifies over all of these cases and over every
    other process input (see Vocabulary in OSSVerify.Core.Shapes).

    WHAT THE HARNESS CHECKS.  Runs a sequence of input-chosen operations against
    a fake kernel netlink socket: read an interface's alias and link kind, write
    an alias, mark and unmark served interfaces, and decide a verdict from a
    kind and alias; checks requests, return codes, buffer bounds, socket use and
    the kept marks against a model of the kernel and the marking policy. The
    harness points the marking code's messages at a fixed buffer in memory, so
    the run writes none of them; no check depends on them.  The harness checks:
    (a) Every socket the reader opens it closes before it returns, and it sends,
    receives and closes only that socket. [abort(); not confirmed in the binary]
    (b) Each operation sends exactly the netlink requests it owes, in order and
    byte for byte. [abort(); not confirmed in the binary]
    (c) A read or write that cannot be made (no name, an empty name, an alias
    too long, an interface with no index) opens no socket. [abort(); not
    confirmed in the binary]
    (d) A read answers the reply's code, and on success the link kind and alias
    the reply carries, cut to the buffers. [abort(); not confirmed in the
    binary]
    (e) A text written into a buffer ends in a NUL inside it, and the byte after
    the buffer is unchanged. [abort(); not confirmed in the binary]
    (f) A write answers the reply's code, and refuses an alias too long for the
    kernel with -ENAMETOOLONG. [abort(); not confirmed in the binary]
    (g) The verdict on an interface follows its alias (one set by the host is
    left alone, one of this daemon's is its own), then its link kind. [abort();
    not confirmed in the binary]
    (h) A mark answers its verdict, or the error of the read or write that
    stopped it, and -EINVAL with no marks or no name. [abort(); not confirmed in
    the binary]
    (i) The marks kept are the interfaces this daemon marked, or found marked by
    an earlier run of its own, each once, at most 32; the unmark clears them
    all. [abort(); not confirmed in the binary]
    Only the checks marked ''confirmed in the binary'' had their assertion text
    or message found in the binary's bytes; for the others no usable text was
    found, which does not mean that they are compiled out, and no statement
    below relies on them.

    Whether each statement is open, proved or known false is recorded in the
    harness README, not here: this file changes only when a statement does. *)

