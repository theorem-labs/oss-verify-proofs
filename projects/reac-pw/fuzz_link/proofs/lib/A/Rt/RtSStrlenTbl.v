(* The strlen interceptor body 0x430e0..0x43374 (165 instructions) is outside AE34's icpt_ranges:
   that table holds the trampolines (0x43044, 46) and resumes at the strnlen interceptor
   (0x43374, 165).  tbl_sl is tbl_icpt plus that one range. *)
Definition sl_ranges : list (Z * nat) := [(0x430e0, 165%nat)].
Definition tbl_sl : ctable := Eval vm_compute in build_ranges sl_ranges tbl_icpt.
Lemma tbl_sl_eq : tbl_sl = build_ranges sl_ranges tbl_icpt.
Proof. vm_cast_no_check (eq_refl tbl_sl). Qed.
Lemma tbl_sl_ok : table_ok tfibsegs tbl_sl.
Proof.
rewrite tbl_sl_eq. apply build_ranges_ok; [| exact tbl_icpt_ok].
unfold sl_ranges. repeat constructor; cbn; discriminate.
Qed.
(* the strlen trampoline, the first and the last instruction word of the interceptor body *)
Lemma tbl_sl_probe :
clookup tbl_sl 0x43044 = Some 0x09c0006f /\
clookup tbl_sl 0x430e0 = Some 0x81010113 /\
clookup tbl_sl 0x43370 = Some 0xe29ff06f /\
clookup tbl_sl 0x43374 = Some 0x81010113.
Proof. vm_compute. repeat split; reflexivity. Qed.

