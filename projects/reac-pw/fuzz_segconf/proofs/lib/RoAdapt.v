(* Frame v3 (ro_agree) adapters for the lib/Lib-form libc contracts: transfer lemmas between a memory m with
   MemNorm.ro_agree and its normalized copy (MemNorm.normalize: read-only addresses dropped), and the tactic
   ro_adapt, which proves <f>_ro_contract from <f>_contract (generated by the roadapt tool). *)
From Stdlib Require Import ZArith NArith List Lia Bool.
From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase RiscvSemantics MemImageType State Run.
From OSSVerify.Proofs.reac_pw.fuzz_segconf.lib.Lib Require Import PropExec MState Mem Exec Frame Step Cells.
From OSSVerify.Proofs.reac_pw.fuzz_segconf.lib Require MemNorm.
Import ListNotations.
Open Scope Z_scope.

Section WithSegs.
Variable segs : list Segment.

(* The n bytes at A are at no read-only address (true for the stack, heap blocks, .data and .bss). *)
Definition not_ro (A n : Z) : Prop := forall i, 0 <= i < n -> Mem.ro_addr segs (wa (A + i)) = false.

Lemma rw_cells_norm : forall m A cs, MemNorm.ro_agree segs m -> rw_cells segs m A cs ->
  not_ro A (Z.of_nat (cells_size cs)) -> rw_cells segs (MemNorm.normalize segs m) A cs.
Proof.
  intros m A cs HR [[Hwf Hb] Hw] Hn. split; [split; [exact Hwf|]|].
  - apply MemNorm.bytes_at_normalize; assumption.
  - eapply MemNorm.wr_at_norm; [apply MemNorm.mem_rel_normalize; exact HR|exact Hw|exact Hn].
Qed.

Lemma wr_at_norm' : forall m A n, MemNorm.ro_agree segs m -> wr_at segs m A n -> not_ro A n ->
  wr_at segs (MemNorm.normalize segs m) A n.
Proof. intros m A n HR Hw Hn. eapply MemNorm.wr_at_norm; [apply MemNorm.mem_rel_normalize; exact HR|exact Hw|exact Hn]. Qed.

Lemma stk_norm : forall m lo hi, MemNorm.ro_agree segs m -> stk segs m lo hi -> not_ro lo (hi - lo) ->
  stk segs (MemNorm.normalize segs m) lo hi.
Proof.
  intros m lo hi HR (H1 & H2 & H) Hn. pose proof (MemNorm.mem_rel_normalize segs m HR) as REL.
  split; [exact H1|]. split; [exact H2|]. intros a Ha. destruct (H a Ha) as [Hv [b Hb]].
  assert (RO : Mem.ro_addr segs (wa a) = false).
  { specialize (Hn (a - lo) ltac:(lia)). replace (lo + (a - lo)) with a in Hn by lia. exact Hn. }
  split.
  - rewrite (MemNorm.wview_rel_rw segs m _ _ REL RO). exact Hv.
  - exists b. rewrite <- (MemNorm.mrd_rel segs m _ _ REL). exact Hb.
Qed.

Lemma rw_cells_back : forall m m0 A cs, MemNorm.mem_rel segs m m0 -> rw_cells segs m0 A cs -> rw_cells segs m A cs.
Proof.
  intros m m0 A cs REL [[Hwf Hb] Hw]. split; [split; [exact Hwf|]|].
  - apply (proj2 (MemNorm.bytes_at_rel segs m m0 _ _ REL)). exact Hb.
  - eapply MemNorm.wr_at_rel; [exact REL|exact Hw].
Qed.

Lemma bytes_at_back : forall m m0 A bs, MemNorm.mem_rel segs m m0 -> bytes_at segs m0 A bs -> bytes_at segs m A bs.
Proof. intros m m0 A bs REL H. apply (proj2 (MemNorm.bytes_at_rel segs m m0 _ _ REL)). exact H. Qed.

Lemma stk_back : forall m m0 lo hi, MemNorm.mem_rel segs m m0 -> stk segs m0 lo hi -> stk segs m lo hi.
Proof.
  intros m m0 lo hi REL (H1 & H2 & H). split; [exact H1|]. split; [exact H2|]. intros a Ha.
  destruct (H a Ha) as [Hv [b Hb]]. pose proof (MemNorm.ro_false_of_wview segs m m0 _ REL Hv) as RO. split.
  - rewrite <- (MemNorm.wview_rel_rw segs m m0 _ REL RO). exact Hv.
  - exists b. rewrite (MemNorm.mrd_rel segs m m0 _ REL). exact Hb.
Qed.
End WithSegs.

(* ro_adapt WX: goal `<f>_contract -> <f>_ro_contract`, where <f>_ro_contract is <f>_contract with
   `mem_inv rsegs m` replaced by `MemNorm.ro_agree rsegs m`, a not_ro premise after each rw_cells / stk / wr_at
   premise on m, and <f>_post replaced by <f>_ro_post (the same text with `mem_inv rsegs m'` replaced by
   `MemNorm.ro_agree rsegs m'`). WX : MemNorm.wx_apart rsegs = true. *)
Ltac ro_pre segs HRO :=
  repeat match goal with
  | H : bytes_at segs ?m ?A ?bs |- _ =>
      lazymatch type of H with bytes_at _ (MemNorm.normalize _ _) _ _ => fail | _ => idtac end;
      let H' := fresh "N" in pose proof (MemNorm.bytes_at_normalize segs m A bs HRO H) as H'; clear H
  | H : rw_cells segs ?m ?A ?cs, Hn : not_ro segs ?A _ |- _ =>
      lazymatch type of H with rw_cells _ (MemNorm.normalize _ _) _ _ => fail | _ => idtac end;
      let H' := fresh "N" in pose proof (rw_cells_norm segs m A cs HRO H Hn) as H'; clear H
  | H : stk segs ?m ?lo ?hi, Hn : not_ro segs ?lo _ |- _ =>
      lazymatch type of H with stk _ (MemNorm.normalize _ _) _ _ => fail | _ => idtac end;
      let H' := fresh "N" in pose proof (stk_norm segs m lo hi HRO H Hn) as H'; clear H
  | H : wr_at segs ?m ?A ?n, Hn : not_ro segs ?A _ |- _ =>
      lazymatch type of H with wr_at _ (MemNorm.normalize _ _) _ _ => fail | _ => idtac end;
      let H' := fresh "N" in pose proof (wr_at_norm' segs m A n HRO H Hn) as H'; clear H
  end.

Ltac ro_conj segs REL HRO :=
  first
  [ eassumption
  | eapply MemNorm.munch_rel; [exact REL|eassumption|eassumption|eassumption]
  | eapply MemNorm.wmono_rel; [exact REL|eassumption|eassumption|eassumption]
  | eapply MemNorm.ro_agree_same; [exact HRO|eassumption]
  | eapply bytes_at_back; [eassumption|eassumption]
  | eapply rw_cells_back; [eassumption|eassumption]
  | eapply stk_back; [eassumption|eassumption]
  | eapply MemNorm.wr_at_rel; [eassumption|eassumption] ].

Ltac ro_adapt segs WX :=
  let H := fresh "C" in intros H; red; intros;
  let HRO := match goal with h : MemNorm.ro_agree segs _ |- _ => h end in
  let m := match type of HRO with MemNorm.ro_agree _ ?m => m end in
  let REL := fresh "REL" in pose proof (MemNorm.mem_rel_normalize segs m HRO) as REL;
  ro_pre segs HRO;
  pose proof (MemNorm.mem_inv_normalize segs m) as MIN;
  eapply evt_mono;
  [ eapply MemNorm.evt_normalize; [exact WX|exact HRO|]; eapply H; first [exact MIN | eassumption | assumption]
  | ];
  let s := fresh "s" in let s0 := fresh "s0" in let P := fresh "P" in let MR := fresh "MR" in let RS := fresh "RS" in
  intros s (s0 & P & MR & RS); red in P;
  repeat match type of P with exists _, _ => let x := fresh "x" in destruct P as [x P] end;
  repeat match type of P with _ /\ _ => let Q := fresh "Q" in destruct P as [Q P] end;
  match goal with Q : s0 = _ |- _ => subst s0 end;
  destruct s as [regs fregs pc svc resv fcsr mem rom];
  destruct MR as (Hr & Hf & Hpc & Hsvc & Hres & Hfc & Hrom & Hmem);
  cbn in Hr, Hf, Hpc, Hsvc, Hres, Hfc, Hrom, Hmem, RS;
  red;
  repeat match goal with |- exists _, _ => eexists end;
  repeat match goal with |- _ /\ _ => split end;
  [ unfold MS; subst; reflexivity | .. ];
  ro_conj segs REL HRO.
