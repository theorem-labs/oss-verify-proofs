  intros ms model ms' evs st Hlazy Hsvc Hstep Hss.
  inversion Hss; subst.
  -
    match goal with H : mi_account_step segs ms model = MachineOk _ |- _ =>
      rewrite (mi_account_step_no_lazy segs ms model Hlazy) in H;
