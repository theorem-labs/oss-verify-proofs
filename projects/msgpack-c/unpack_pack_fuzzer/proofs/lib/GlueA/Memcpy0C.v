Module Memcpy0C.
Definition amemcpy0_apply (st : sstate) : option (list sstate) :=
  match ActrA.acall_pre ActrA.ASTACK None st with
  | Some (r, hargs, wl, st1) =>
      match getr st X12 with
      | VL n => if weqb n wzero then Some [setpc (setr (clobber st1) X10 (getr st X10)) r] else None
      | _ => None
      end
  | None => None
  end.
Definition amemcpy0_c (pc : int) : contract := Contract pc amemcpy0_apply.
End Memcpy0C.

