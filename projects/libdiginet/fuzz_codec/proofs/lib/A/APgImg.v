- unfold codec_asan_obj. generalize (a - A_OBJ 0)%nat as m. intros m. do 33 (destruct m as [|m]; [zlit|]). zlit.
- unfold codec_asan_hi. generalize (a - A_HI 0)%nat as m. intros m. do 66 (destruct m as [|m]; [zlit|]). zlit.
Qed.
