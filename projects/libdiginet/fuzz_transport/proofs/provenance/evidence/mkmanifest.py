#!/usr/bin/env python3
"""Writes MANIFEST.md (the index) and MANIFEST (this directory's own rows) of provenance/evidence/ from each
subdirectory's MANIFEST, whose lines are `<path> <kind> <sha256> <role...>` (paths relative to that directory, each
naming a file of it) and `#` notes.  Run from provenance/evidence/.
MANIFEST.md: per subdirectory, its MANIFEST rows as a table (file, kind, role) and its notes; then the sha256 of every
file of provenance/evidence/ but MANIFEST.md and MANIFEST.  MANIFEST: the rows of MANIFEST.md and of this script."""
import hashlib, os


def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


dirs = sorted(d for d in os.listdir('.') if os.path.isdir(d))
out = ['# provenance/evidence/', '',
       'Generated by mkmanifest.py from the MANIFEST of each directory: ' + ', '.join(d + '/' for d in dirs) + '. '
       'Commit ids in these records are kept as the runs wrote them; the commits they name that are not in the released '
       'history are preserved in the internal record.', '']
for d in dirs:
    rows, notes = [], []
    for line in open(os.path.join(d, 'MANIFEST')).read().splitlines():
        if not line.strip():
            continue
        if line.lstrip().startswith('#'):
            notes.append(line.lstrip()[1:].strip())
            continue
        rows.append(line.split(None, 3) + [''] * (4 - len(line.split(None, 3))))
    out += ['## ' + d + '/', '', '| file | kind | role |', '|---|---|---|']
    out += ['| %s | %s | %s |' % (f[0], f[1], f[3].replace('|', '\\|')) for f in rows]
    out += [''] + ['- ' + n for n in notes] + [''] if notes else ['']
out += ['## sha256', '', '| file | sha256 |', '|---|---|']
for root, _, fs in sorted(os.walk('.')):
    for f in sorted(fs):
        p = os.path.relpath(os.path.join(root, f), '.')
        if p not in ('MANIFEST.md', 'MANIFEST'):
            out.append(f'| {p} | {sha(p)} |')
open('MANIFEST.md', 'w').write('\n'.join(out) + '\n')
open('MANIFEST', 'w').write(
    '# provenance/evidence/: <path> <kind> <sha256> <role>, paths relative to this directory; each subdirectory\'s\n'
    '# MANIFEST names its own files. Both files are written by mkmanifest.py.\n'
    f'MANIFEST.md index {sha("MANIFEST.md")} the index: each subdirectory\'s MANIFEST as a table, then the sha256 of every '
    'file here but MANIFEST.md and MANIFEST\n'
    f'mkmanifest.py script {sha("mkmanifest.py")} writes MANIFEST.md and MANIFEST from the subdirectories\' MANIFESTs; '
    'run from provenance/evidence/\n'
    f'untime-removed.tsv file {sha("untime-removed.tsv")} the unit\'s index of removed `timeout` markers, one row per marker: file, first line, line count, sha256 of the marker\'s text (core-B/cutuntime-B.sh, core-B/README.md)\n')
