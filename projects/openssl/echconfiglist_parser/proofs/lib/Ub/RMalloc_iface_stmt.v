Definition RERRNO : Z := 0x335ff4.        (* [comment removed for export] *)
Definition RLIBC : Z := 0x356328.         (* [comment removed for export] *)
Definition RAUXV_CELL : Z := 0x356330.    (* [comment removed for export] *)
Definition RCTX : Z := 0x3563a0.          (* [comment removed for export] *)
Definition RSSP_GUARD : Z := 0x3560d8.    (* [comment removed for export] *)
Definition RGOT_SSP : Z := 0x321b98.      (* [comment removed for export] *)
Definition RVMLOCK : Z := 0x357800.       (* [comment removed for export] *)

Definition mem := word -> option byte.
Definition block : Type := (bptr * Z * Z)%type.
Definition blk_id (b : block) : bptr := fst (fst b).
Definition blk_addr (b : block) : Z := snd (fst b).
Definition blk_size (b : block) : Z := snd b.
Definition in_block (LB : list block) (a : Z) : Prop :=
  exists b, In b LB /\ blk_addr b <= a < blk_addr b + blk_size b.

Definition ralloc_static (a : Z) : Prop :=
  (RLIBC <= a < RCTX + 936) \/ (RERRNO <= a < RERRNO + 4)
  \/ (RSSP_GUARD <= a < RSSP_GUARD + 8) \/ (RGOT_SSP <= a < RGOT_SSP + 8) \/ (RVMLOCK <= a < RVMLOCK + 4).

