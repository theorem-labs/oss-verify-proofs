(* [comment removed for export] *)
Definition AAUXV_CELL : Z := 0xc01f28.

(* LPS 75d69e00: the auxiliary vector, keyed by Lib/AuxvTable's single generator.  [r] is
   [la_rseq]: 27 pairs without CONFIG_RSEQ, 29 with, so the length is a function of [r]
   and this tree pins neither it nor the terminator's position.  AT_NULL's value is 0 in
   the model, so it is no longer carried as a free existential.  LPS 727298f3: the vector
   publishes the vDSO, and [aauxv_ok]'s last conjunct ties the AT_SYSINFO_EHDR it carries to
   the run constant [hvdso] (the vDSO's clock_gettime entry, 1460 bytes into the image,
   Lib/VdsoImg's [rvdso_cgt_off_measured]), as Ref/RMallocTree's [rauxv_ok] does. *)
Definition aauxv_list (v : auxv_vals) (rnd execfn : Z) (r : bool) : list word :=
  map wz (auxv_words_Z v rnd execfn r).

Lemma aauxv_list_length : forall v rnd execfn r,
  length (aauxv_list v rnd execfn r) = (2 * auxv_count r)%nat.
Proof. intros v rnd execfn r. apply (length_auxv_list v rnd execfn r). Qed.

Lemma aauxv_list_length_arms : forall v rnd execfn r,
  length (aauxv_list v rnd execfn r) = (if r then 58 else 54)%nat.
Proof. intros v rnd execfn [|]; reflexivity. Qed.

(* LPS c0dd863a: the claim holds the vector's FIRST PAIR only, [firstn 2] of the same table: the key
   33 and AT_SYSINFO_EHDR, which time()'s [__vdsosym] reads (Both/As/F_timeI.v [ati_auxv_pair]) and
   which is the only part of the vector the code after main entry reads; every other user of
   [aauxv_ok] carries it through the frame lemmas below.  The main-entry states know the vector's
   other values only as present ([KUnk]) or, for the CONFIG_RSEQ tail, not at all.  The bound on
   [av] keeps the whole vector's length. *)
Section HCW.
  Context {HCEIL : HeapCeil}.

  Definition aauxv_ok (m : mem) (B : Z) : Prop :=
    exists av (v : auxv_vals) (rnd execfn : Z) (r : bool),
      rw_cells asegs m AAUXV_CELL [C8 (wz av)]
      /\ bytes_at asegs m av (u64s (firstn 2 (aauxv_list v rnd execfn r)))
      /\ aceil <= B /\ B <= av /\ av + auxv_vec_bytes r <= 2^63
      /\ auxv_vals_ok v /\ 0 <= rnd < 2^64 /\ 0 <= execfn < 2^64
      /\ ax_sysinfo v + 1460 = hvdso.

  (* [comment removed for export] *)
  Definition aauxv_win_ok (B : Z) (iv : Z * Z) : Prop :=
    snd iv <= B /\ (snd iv <= AAUXV_CELL \/ AAUXV_CELL + 8 <= fst iv).

  Lemma aauxv_win_ok_intro : forall B lo hi,
    hi <= B -> (hi <= AAUXV_CELL \/ AAUXV_CELL + 8 <= lo) -> aauxv_win_ok B (lo, hi).
  Proof. intros B lo hi H1 H2. exact (conj H1 H2). Qed.

  (* [comment removed for export] *)
  Lemma aauxv_win_ok_low : forall B lo hi,
    aceil <= B -> hi <= aceil -> (hi <= AAUXV_CELL \/ AAUXV_CELL + 8 <= lo) -> aauxv_win_ok B (lo, hi).
  Proof. intros B lo hi H1 H2 H3. split; cbn; lia. Qed.

  (* [comment removed for export] *)
  Lemma aauxv_win_ok_stack : forall B lo hi, aceil <= lo -> hi <= B -> aauxv_win_ok B (lo, hi).
  Proof. intros B lo hi H1 H2. pose proof aceil_facts. unfold aauxv_win_ok, AAUXV_CELL. cbn. lia. Qed.

  Lemma aauxv_ok_bounds : forall m B, aauxv_ok m B -> aceil <= B.
  Proof. intros m B (av & v & rnd & execfn & r & _ & _ & H & _). exact H. Qed.

  Lemma aauxv_ok_weaken : forall m B B', aauxv_ok m B -> aceil <= B' <= B -> aauxv_ok m B'.
  Proof.
    intros m B B' (av & v & rnd & execfn & r & C & A & HC & HBA & HAV & HV & HRN & HEX & HVD) HB.
    exists av, v, rnd, execfn, r.
    split; [exact C|]. split; [exact A|].
    split; [lia|]. split; [lia|]. split; [exact HAV|].
    split; [exact HV|]. split; [exact HRN|]. split; [exact HEX| exact HVD].
  Qed.

  Lemma Forall_disjoint_from_aux : forall (P : Z * Z -> Prop) W a n,
    Forall P W -> (forall lo hi, P (lo, hi) -> a + n <= lo \/ hi <= a) -> disjoint_from W a n.
  Proof.
    intros P W a n F HP. induction F as [|[lo hi] W Hx F IH]; cbn; [exact I|]. split; [apply (HP _ _ Hx)| exact IH].
  Qed.

  (* [comment removed for export] *)
  Lemma aauxv_ok_frame : forall m m' B W,
    aauxv_ok m B -> munch W m m' -> wmono asegs m m' -> Forall (aauxv_win_ok B) W -> aauxv_ok m' B.
  Proof.
    intros m m' B W (av & v & rnd & execfn & r & C & A & H) MU WM FW.
    exists av, v, rnd, execfn, r. destruct r; (split; [|split; [|exact H]]).
    - eapply rw_cells_transport; eauto. eapply Forall_disjoint_from_aux; [exact FW|]. intros lo hi [X1 X2]. cbn in X1, X2 |- *. lia.
    - eapply bytes_at_transport; eauto. eapply Forall_disjoint_from_aux; [exact FW|]. intros lo hi [X1 X2]. cbn in X1, X2 |- *. lia.
    - eapply rw_cells_transport; eauto. eapply Forall_disjoint_from_aux; [exact FW|]. intros lo hi [X1 X2]. cbn in X1, X2 |- *. lia.
    - eapply bytes_at_transport; eauto. eapply Forall_disjoint_from_aux; [exact FW|]. intros lo hi [X1 X2]. cbn in X1, X2 |- *. lia.
  Qed.

  (* [comment removed for export] *)
  Lemma aauxv_ok_apres : forall (H : asr) LB SP m m' B,
    aauxv_ok m B -> apres H LB SP m m' -> SP <= B -> aauxv_ok m' B.
  Proof.
    intros H LB SP m m' B (av & v & rnd & execfn & r & C & A & HB) HP HSP.
    exists av, v, rnd, execfn, r. split; [|split; [|exact HB]].
    - eapply apres_rw_cells; [exact HP| exact C|]. right; left. intros a Ha. cbn in Ha. unfold AAUXV_CELL in Ha. unfold aimg_client. lia.
    - eapply apres_bytes_at; [exact HP| exact A|]. left. lia.
  Qed.

  (* [comment removed for export] *)
  Lemma aauxv_ok_xpres : forall (H : asr) LB SP X m m' B,
    aauxv_ok m B -> xpres H LB SP X m m' -> SP <= B -> Forall (aauxv_win_ok B) X -> aauxv_ok m' B.
  Proof.
    intros H LB SP X m m' B (av & v & rnd & execfn & r & C & A & HB) HP HSP FX.
    exists av, v, rnd, execfn, r. split; [|split; [|exact HB]].
    - eapply xpres_rw_cells; [exact HP| exact C|]. split.
      + right; left. intros a Ha. cbn in Ha. unfold aimg_client, AAUXV_CELL in *. lia.
      + apply Forall_forall. intros [lo hi] Hin. pose proof (proj1 (Forall_forall _ _) FX _ Hin) as [_ K]. cbn in K |- *. lia.
    - eapply xpres_bytes_at; [exact HP| exact A|]. split.
      + left. lia.
      + apply Forall_forall. intros [lo hi] Hin. pose proof (proj1 (Forall_forall _ _) FX _ Hin) as [K _]. cbn in K |- *. lia.
  Qed.
End HCW.
