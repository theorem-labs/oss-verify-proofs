Definition site_eqb (s t : list Z) : bool := (length s =? length t)%nat && forallb (fun p => fst p =? snd p) (combine s t).
Definition site_memb (s : list Z) : bool := existsb (site_eqb s) SITE_TRACES.

Lemma site_eqb_eq : forall s t, site_eqb s t = true -> s = t.
Proof.
  induction s as [|x s IH]; intros [|y t] H; unfold site_eqb in H; cbn in H; try reflexivity; try discriminate H.
  apply andb_prop in H as [H1 H2]. apply andb_prop in H2 as [H2 H3]. apply Z.eqb_eq in H2. subst y. f_equal. apply IH.
  unfold site_eqb. rewrite H1. exact H3.
Qed.

Lemma site_memb_In : forall s, site_memb s = true -> In s SITE_TRACES.
Proof. intros s H. unfold site_memb in H. apply existsb_exists in H as (t & Hin & E). apply site_eqb_eq in E. subst t. exact Hin. Qed.

Lemma alloc_ras_sites : forall r, In r ALLOC_RAS -> In [r] SITE_TRACES.
Proof.
  intros r H. apply site_memb_In.
  assert (X : forallb (fun r => site_memb [r]) ALLOC_RAS = true) by (vm_compute; reflexivity).
  exact (proj1 (forallb_forall _ _) X r H).
Qed.
