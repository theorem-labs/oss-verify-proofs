Definition bn_postA_p {A : Type} (ra sp gp s0 s1 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 : word)
    (Σ : rts RT) (st : bstate bptr) (OW LB : list block) (lo : Z) (m : mem) (PL : placement) (EA : BnRepDefs.err_addrs) (cost : Z)
    (RES : A -> bstate bptr -> list block -> placement -> word -> Prop)
    (r : A * bstate bptr) (Σ' : rts RT) : machine_state -> Prop :=
  fun ms' => exists t0 t1 t2 a0 a1 a2 a3 a4 a5 a6 a7 t3 t4 t5 t6 (F' : bvmap 5 word) (fc' : bv 32) m' OW' PL',
    ms' = MS (mkR ra sp gp (wz TP_A) t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
             F' (ret_pc ra) fc' None m' (seg_rom bgasegs)
    /\ AHEAP Σ' OW' LB m' /\ lib_state (snd r) m' OW' PL' EA
    /\ stk bgasegs m' lo (bv_unsigned sp) /\ mem_inv bgasegs m'
    /\ ax_pres LB (bv_unsigned sp) (XW PL) m m'
    /\ rt_credit RT Σ - cost <= rt_credit RT Σ'
    /\ RES (fst r) (snd r) OW' PL' a0.

Lemma zero_bn_cellsA : forall m A,
  rw_cells bgasegs m A [CB 24%nat (repeat (Z_to_bv 8 0) 24%nat)] -> rw_cells bgasegs m A (bn_cells 0 (bn_nil 0)).
Proof.
  intros m A H. eapply bk_rw_cells_recast; [exact H | cbn; repeat split | reflexivity | reflexivity].
Qed.

Lemma cnt_bal_cons : forall (st : bstate bptr) OW b, cnt_bal st (b :: OW) = cnt_bal st OW + 1.
Proof. intros st OW b. unfold cnt_bal. cbn [length]. lia. Qed.

End WithRT.
