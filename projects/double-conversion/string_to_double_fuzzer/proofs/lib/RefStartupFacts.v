Definition D_main_cells : list (Z * nat) :=
  [(0xc4848%Z, 8%nat); (0xe4bb0%Z, 8%nat); (0xe4c10%Z, 8%nat); (0xe4bd8%Z, 8%nat); (0xe4ba0%Z, 8%nat); (0xe4b98%Z, 8%nat); (0xe4940%Z, 8%nat); (0xe4950%Z, 8%nat); (0xe4948%Z, 8%nat); (0xe4bc0%Z, 8%nat); (0xe4bc8%Z, 8%nat); (0xc4928%Z, 8%nat); (0xc4910%Z, 8%nat); (0xc4850%Z, 8%nat); (0xe4ba8%Z, 1%nat); (0xc4878%Z, 4%nat); (0xc4870%Z, 4%nat); (0xc48e8%Z, 8%nat); (0xc48c8%Z, 8%nat); (0xc4858%Z, 8%nat); (0xc4860%Z, 8%nat); (0xc4868%Z, 8%nat); (0xe4b88%Z, 4%nat); (0xe4b8c%Z, 4%nat); (0xe4b89%Z, 1%nat); (0xc4908%Z, 8%nat); (0xb2ea0%Z, 1%nat)].

Definition range_disjoint_b (a : Z) (n : nat) (c : Z * nat) : bool :=
  ((a + Z.of_nat n <=? fst c) || (fst c + Z.of_nat (snd c) <=? a))%Z.

Definition D_main_missb (a : Z) (n : nat) : bool :=
  forallb (range_disjoint_b a n) D_main_cells && (0 <=? a)%Z && (a + Z.of_nat n <=? 0xe6000)%Z.

