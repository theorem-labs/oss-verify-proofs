Ltac acc_hint_cheap :=
  first [ assumption
        | lazymatch goal with
          | |- acc_in ?RNG (?a, _) =>
              let E := addr_expr a in let X := leftmost E in
              first [ match goal with H : rng RNG ?lo _ |- _ => let Y := leftmost lo in constr_eq X Y; solve_acc_with_cheap H end
                    | match goal with H : rng RNG _ _ |- _ => solve_acc_with_cheap H end ]
          end ].
