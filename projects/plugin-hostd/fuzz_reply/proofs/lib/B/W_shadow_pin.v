(* the bytes lo, lo + 1, ..., lo + n - 1 *)
Definition shp_zseq (lo n : Z) : list Z := map (fun k => lo + Z.of_nat k) (seq 0 (Z.to_nat n)).
Lemma shp_zseq_in : forall lo n a, lo <= a < lo + n -> In a (shp_zseq lo n).
Proof.
intros lo n a Ha. unfold shp_zseq. apply in_map_iff. exists (Z.to_nat (a - lo)). split.
- rewrite Z2Nat.id by lia. lia.
- apply in_seq. lia.
Qed.
(* address, width and value of an `ACell (ANum z) w (AV (ANum v))` row *)
Definition shp_cell_num (c : acell) : option (Z * nat * Z) :=
match c with ACell (ANum z) w (AV (ANum v)) => Some (z, w, v) | _ => None end.
Lemma shp_cell_num_ok : forall c z w v, shp_cell_num c = Some (z, w, v) -> c = ACell (ANum z) w (AV (ANum v)).
Proof.
intros [ca cw cv] z w v H. destruct ca; try discriminate H. destruct cv as [e|m x]; [|discriminate H].
destruct e; try discriminate H. cbn in H. injection H as <- <- <-. reflexivity.
Qed.
(* the byte a row holds at s *)
Definition shp_cell_at (s : Z) (c : acell) : option Z :=
match shp_cell_num c with
| Some (z, w, v) => if (z <=? s) && (s <? z + Z.of_nat w) then Some (le_byte v w (Z.to_nat (s - z))) else None
| None => None
end.
Fixpoint shp_cells_at (s : Z) (cs : list acell) : option Z :=
match cs with
| [] => None
| c :: cs' => match shp_cell_at s c with Some v => Some v | None => shp_cells_at s cs' end
end.
(* s is a shadow byte of a zero-shadow range (zero_shadow covers snd r / 8 shadow bytes from shadow_addr (fst r)) *)
Definition shp_zs_at (s : Z) (zs : list (Z * Z)) : bool :=
existsb (fun r => (SHADOW_OFF + fst r / 8 <=? s) && (s <? SHADOW_OFF + fst r / 8 + snd r / 8)) zs.
Definition shp_val (cs : list acell) (zs : list (Z * Z)) (s : Z) : option Z :=
match shp_cells_at s cs with Some v => Some v | None => if shp_zs_at s zs then Some 0 else None end.
Definition shp_saddrb (x s : Z) : bool := (s =? 0) || ((x mod 8 <? s) && (s <? 8)).
Definition shp_check (cs : list acell) (zs : list (Z * Z)) (a n : Z) : bool :=
forallb (fun x => match shp_val cs zs (shadow_of_addr SHADOW_OFF x) with Some s => shp_saddrb x s | None => false end)
  (shp_zseq a n) &&
((n <=? 0) || forallb (fun s => match shp_val cs zs s with Some _ => true | None => false end)
  (shp_zseq (shadow_addr a / 8 * 8) (shadow_addr (a + n - 1) / 8 * 8 + 8 - shadow_addr a / 8 * 8))).

Lemma shp_cells_at_ok : forall s cs v, shp_cells_at s cs = Some v -> exists c, In c cs /\ shp_cell_at s c = Some v.
Proof.
intros s cs v. induction cs as [|c cs IH]; intros H; cbn [shp_cells_at] in H; [discriminate H|].
destruct (shp_cell_at s c) as [u|] eqn:Ec.
- injection H as <-. exists c. split; [left; reflexivity | exact Ec].
- destruct (IH H) as (c' & Hc' & Hv). exists c'. split; [right; exact Hc' | exact Hv].
Qed.

