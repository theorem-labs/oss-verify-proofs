(* the n bytes at a pass ASan's check, and the shadow bytes of their 8-aligned hull are visible, in every AR state.
   Bound: AR states only.  ashp is derived from AR (am_const, am_zshadow), never assumed about other states; on the
   exit path asan.module_dtor (.fini_array[0], image A 0x8624c [A; B: 0x867cc]) -> __asan_unregister_globals -> PoisonShadow
   rewrites the pinned shadow cells, so AR (for the start-up instance) does not hold past it and ashp says nothing
   there.  A change that makes AR hold past module_dtor must first drop those cells from as_const. *)
Definition ashp (a n : Z) : Prop :=
forall ly S (W : world SEGS) mem md, AR SEGS B ly S W mem md ->
range_addressable (aview SEGS (w_H W) mem) SHADOW_OFF a n /\ (0 < n -> shadow_hull_vis (aview SEGS (w_H W) mem) a n).

Lemma ashp_sub : forall a n n', 0 < n' <= n -> ashp a n -> ashp a n'.
Proof.
intros a n n' Hn H ly S W mem md HAR. destruct (H ly S W mem md HAR) as [Hr Hh]. split.
- exact (range_addressable_sub _ _ a n a n' Hr ltac:(lia) ltac:(lia)).
- intros _ s Hs. apply (Hh ltac:(lia)).
  assert (M : shadow_addr (a + n' - 1) / 8 * 8 <= shadow_addr (a + n - 1) / 8 * 8).
  { apply Z.mul_le_mono_nonneg_r; [lia|]. apply Z.div_le_mono; [lia|]. unfold shadow_addr.
    apply Z.add_le_mono_l. apply Z.div_le_mono; lia. }
  lia.
Qed.

Section b.
Variable cs : list acell.
Variable zs : list (Z * Z).
Hypothesis HCS : forall ly c, In c cs -> In c (as_const B ly).
Hypothesis HZS : forall r, In r zs -> In r (as_zero_shadow B).

Lemma shp_cell_at_ok : forall s c v ly (rd : reader), shp_cell_at s c = Some v -> cell_holds B ly rd c -> rd s = Some v.
Proof.
intros s c v ly rd H Hh. unfold shp_cell_at in H.
destruct (shp_cell_num c) as [[[z w] u]|] eqn:Ec; [|discriminate H].
apply shp_cell_num_ok in Ec. subst c.
destruct ((z <=? s) && (s <? z + Z.of_nat w)) eqn:E; [|discriminate H]. injection H as <-.
apply andb_true_iff in E as [E1 E2]. apply Z.leb_le in E1. apply Z.ltb_lt in E2.
red in Hh. cbn [c_at c_w c_val aeval] in Hh. specialize (Hh (Z.to_nat (s - z)) ltac:(lia)).
rewrite Z2Nat.id in Hh by lia. replace (z + (s - z)) with s in Hh by lia. exact Hh.
Qed.

Lemma shp_val_ok : forall ly S (W : world SEGS) mem md s v, AR SEGS B ly S W mem md -> shp_val cs zs s = Some v ->
aview SEGS (w_H W) mem s = Some v.
Proof.
intros ly S W mem md s v (HM & _) H. unfold shp_val in H.
destruct (shp_cells_at s cs) as [u|] eqn:Ec.
- injection H as <-. apply shp_cells_at_ok in Ec as (c & Hc & Hu).
  pose proof (proj1 (Forall_forall _ _) (YG0n.am_const _ _ _ _ HM) c (HCS ly c Hc)) as Hh.
  exact (shp_cell_at_ok s c u ly _ Hu Hh).
- destruct (shp_zs_at s zs) eqn:Ez; [|discriminate H]. injection H as <-.
  unfold shp_zs_at in Ez. apply existsb_exists in Ez as (r & Hr & Hb).
  apply andb_true_iff in Hb as [H1 H2]. apply Z.leb_le in H1. apply Z.ltb_lt in H2.
  pose proof (YG0n.am_zshadow _ _ _ _ HM) as Hz. unfold YG0n.zshadow_ok, YG0n.zero_shadow_ranges in Hz.
  apply Forall_cons_iff in Hz as [_ Hz].
  pose proof (proj1 (Forall_forall _ _) Hz r (HZS r Hr)) as Hzr. red in Hzr.
  specialize (Hzr (s - (SHADOW_OFF + fst r / 8)) ltac:(lia)). unfold YG0v.shadow_of_addr in Hzr.
  replace (SHADOW_OFF + fst r / 8 + (s - (SHADOW_OFF + fst r / 8))) with s in Hzr by lia. exact Hzr.
Qed.

Theorem shp_ashp : forall a n, shp_check cs zs a n = true -> ashp a n.
Proof.
intros a n Hc ly S W mem md HAR. unfold shp_check in Hc. apply andb_true_iff in Hc as [Hr Hh]. split.
- intros x Hx. rewrite forallb_forall in Hr. specialize (Hr x (shp_zseq_in a n x Hx)). cbv beta in Hr.
  destruct (shp_val cs zs (shadow_of_addr SHADOW_OFF x)) as [s|] eqn:Ev; [|discriminate Hr].
  exists s. split; [exact (shp_val_ok ly S W mem md _ s HAR Ev)|].
  unfold shp_saddrb in Hr. unfold saddr_ok. apply orb_true_iff in Hr as [Hr|Hr]; [left; apply Z.eqb_eq; exact Hr|right].
  apply andb_true_iff in Hr as [H1 H2]. apply Z.ltb_lt in H1. apply Z.ltb_lt in H2. split; assumption.
- intros Hn s Hs. apply orb_true_iff in Hh as [Hh|Hh]; [apply Z.leb_le in Hh; lia|].
  rewrite forallb_forall in Hh.
  assert (Hin : In s (shp_zseq (shadow_addr a / 8 * 8)
    (shadow_addr (a + n - 1) / 8 * 8 + 8 - shadow_addr a / 8 * 8))) by (apply shp_zseq_in; lia).
  specialize (Hh s Hin). cbv beta in Hh.
  destruct (shp_val cs zs s) as [v|] eqn:Ev; [|discriminate Hh].
  rewrite (shp_val_ok ly S W mem md s v HAR Ev). discriminate.
Qed.
End b.
End a.
