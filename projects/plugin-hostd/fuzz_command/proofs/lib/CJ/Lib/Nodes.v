Definition eff0 (r : word) : resp := mkEffect r [] [].
Definition efferr (e : Z) : resp := eff0 (errno_ret e).
(* [comment removed for export] *)
Definition eff0c (r : word) (cis : list (word * nat)) : resp := mkEffectU r [] [] [] [] cis.

