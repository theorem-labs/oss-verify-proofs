Definition open_result (mo : Model) (ent : FdEntry) (r : word) (mo' : Model) : Prop :=
  (exists e, In e openat_errnos /\ r = errno_ret e /\ mo' = mo)
  \/ (let fd := alloc_fd (m_fds mo) in
      fd_lookup (m_fds mo) fd = None /\ r = fd /\
      mo' = with_fds (fd_insert (m_fds mo) fd ent) mo).

