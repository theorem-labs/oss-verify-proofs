#!/usr/bin/env python3
"""Read an image's asan_globals descriptors (the [start, stop) that asan.module_dtor passes to
__asan_unregister_elf_globals, read from its two GOT words; image A fuzz_command.asan: 0xa7088 / 0xa7090) and print,
as Rocq text, the x2_globals table of lib/A/Rt/RtDtorTbl.v (image B fuzz_command.asan-ubsan: slots 0xa6be8 / 0xa6bf0,
lib/B/Rt/RtDtorTbl.v).
Usage: gen_dtor_tbl.py IMAGE [START_SLOT STOP_SLOT] [--into FILE]   (slots in hex; default image A's).
Without --into it prints the table to stdout.  With --into it replaces, in FILE, the lines from the one that starts
"(* BEGIN generated table:" through "(* END generated table *)" with the table, and leaves every other line of FILE.

Copy of record of the generator (sha256 14fe15ed7db6...) that wrote both RtDtorTbl.v tables.  Its table lines are that
generator's, byte for byte.  Changes: the BEGIN line names the generator by file name and sha256 (the earlier one
printed the path it ran from), the END line is "(* END generated table *)", the list of odr indicators goes to stderr,
and --into."""
import os
import hashlib
import struct
import sys

from elftools.elf.elffile import ELFFile

START_SLOT, STOP_SLOT = 0xA7088, 0xA7090


BEGIN = "(* BEGIN generated table:"
END = "(* END generated table *)"


def main():
    argv = sys.argv[1:]
    into = None
    if "--into" in argv:
        i = argv.index("--into")
        into = argv[i + 1]
        del argv[i:i + 2]
    sys.argv = sys.argv[:1] + argv
    path = sys.argv[1]
    me = os.path.realpath(__file__)
    me_sha = hashlib.sha256(open(me, "rb").read()).hexdigest()
    out = []
    emit = out.append
    data = open(path, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    with open(path, "rb") as f:
        elf = ELFFile(f)
        loads = [s for s in elf.iter_segments() if s["p_type"] == "PT_LOAD"]

        def rd(addr, n):
            for s in loads:
                va, fs, ms = s["p_vaddr"], s["p_filesz"], s["p_memsz"]
                if va <= addr and addr + n <= va + ms:
                    out = b""
                    for a in range(addr, addr + n):
                        out += data[s["p_offset"] + a - va: s["p_offset"] + a - va + 1] if a < va + fs else b"\0"
                    return out
            raise SystemExit("address %#x not in a PT_LOAD" % addr)

        def q(addr):
            return struct.unpack("<Q", rd(addr, 8))[0]

        start_slot = int(sys.argv[2], 16) if len(sys.argv) > 3 else START_SLOT
        stop_slot = int(sys.argv[3], 16) if len(sys.argv) > 3 else STOP_SLOT
        start, stop = q(start_slot), q(stop_slot)
        assert (stop - start) % 64 == 0, (start, stop)
        n_all = (stop - start) // 64
        n = n_all
        recs = []
        for i in range(n):
            w = [q(start + 64 * i + 8 * k) for k in range(8)]
            recs.append(w)
        emit("%s generated by %s (sha256 %s) from" % (BEGIN, os.path.basename(me), me_sha))
        emit("   %s (ELF sha256 %s); do not edit. *)" % (os.path.basename(path), sha))
        emit("Definition A_ASAN_GLOBALS : Z := %#x.   (* *(0x%x), the start asan.module_dtor passes *)" % (start, start_slot))
        emit("Definition A_ASAN_GLOBALS_SZ : Z := %d.   (* *(0x%x) - start = %d records of 64 bytes *)" % (stop - start, stop_slot, n_all))
        emit("Definition A_NGLOBALS : Z := %d." % n_all)
        emit("(* the %d records of [A_ASAN_GLOBALS, + A_ASAN_GLOBALS_SZ), in order: beg, size, size_with_redzone, name," % n)
        emit("   module_name, has_dynamic_init, location, odr_indicator *)")
        rows = []
        for w in recs:
            rows.append("mkG " + " ".join(("%#x" % v) if v > 9 else str(v) for v in w))
        emit("Definition x2_globals : list aglobal :=")
        emit("[ " + ";\n".join(rows) + " ].")
        emit(END)
        odr = sorted(w[7] for w in recs if w[7] not in (0, 0xFFFFFFFFFFFFFFFF))
        sys.stderr.write("(* odr indicators != 0, != -1: %s *)\n" % ", ".join("%#x" % a for a in odr))
    text = "\n".join(out) + "\n"
    if into is None:
        sys.stdout.write(text)
        return
    lines = open(into).read().split("\n")
    b = [k for k, l in enumerate(lines) if l.startswith(BEGIN)]
    e = [k for k, l in enumerate(lines) if l == END]
    if len(b) != 1 or len(e) != 1 or e[0] < b[0]:
        raise SystemExit("%s: need exactly one BEGIN line and one END line after it (found %d, %d)" % (into, len(b), len(e)))
    new = lines[:b[0]] + text.rstrip("\n").split("\n") + lines[e[0] + 1:]
    open(into, "w").write("\n".join(new))


if __name__ == "__main__":
    main()
