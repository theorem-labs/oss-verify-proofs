(* ---- fm.asan image: code tables over a function's range, the shadow-base cells (fm-fn-measure.md section 2: GOT
   0x99c98 -> __asan_shadow_memory_dynamic_address 0xa2078 -> 0x7fff8000) ---- *)
Fixpoint fmw_ranges (rs : list (Z * nat)) (t : ctable) : ctable :=
  match rs with [] => t | (lo, n) :: rest => fmw_ranges rest (build_table tfibsegs lo n t) end.
Lemma fmw_ranges_ok : forall rs t,
  Forall (fun r => 0 <= fst r) rs -> table_ok tfibsegs t -> table_ok tfibsegs (fmw_ranges rs t).
Proof.
  induction rs as [|[lo n] rest IH]; intros t Hrs Ht; cbn; [exact Ht|].
  inversion Hrs; subst. apply IH; [assumption|]. apply build_table_ok; [cbn in *; assumption | exact Ht].
Qed.
