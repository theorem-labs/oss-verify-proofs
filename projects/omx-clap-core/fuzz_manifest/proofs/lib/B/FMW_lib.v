Lemma fw_region_nth : forall E ss ms i r,
  st_ok segs E ss ms -> nth_error (ss_mem ss) i = Some r -> region_ok segs E (ms_mem ms) r.
Proof.
  intros E ss ms i r HS Hi. destruct (st_ok_mem_ok segs E ss ms HS) as (_ & Hrs & _).
  exact (proj1 (Forall_forall _ _) Hrs r (nth_error_In _ _ Hi)).
Qed.
Lemma fw_field : forall E m n b cs lo hi wlo whi od (w : N) e v,
  region_ok segs E m (YP09.mkRegion (Some n) lo hi wlo whi cs) ->
  bv_unsigned (ew E n) = b -> In (YP09.mkChunk od (CVal w e)) cs -> sv_denot E e = Z_to_bv 64 v ->
  0 <= v < 2 ^ (8 * Z.of_N w) -> (Z.of_N w <= 8) ->
  val_mem segs m (b + od) (N.to_nat w) v.
Proof.
  intros E m n b cs lo hi wlo whi od w e v (_ & _ & _ & Hcs) Hn Hc He Hv Hw.
  pose proof (proj1 (Forall_forall _ _) Hcs _ Hc) as Hck. cbn [YP09.r_base base_val] in Hck. rewrite Hn in Hck.
  exact (val_of_chunk_ok segs E m b od w e v Hck He Hv Hw).
Qed.
Lemma fw_aview_frame : forall E rs H (m m' : word -> option byte),
  frame_of E rs (mrestrict H m) (mrestrict H m') ->
  forall a, 0 <= a < 2 ^ 64 -> ~ in_wrange E rs a -> aview segs H m' a = aview segs H m a.
Proof.
  intros E rs H m m' HF a Ha Hno. apply aview_eq_of. apply HF. rewrite unsigned_lit_small by lia. exact Hno.
Qed.
Lemma fw_nowin : forall E rs H (m m' : word -> option byte),
  frame_of E rs (mrestrict H m) (mrestrict H m') -> forallb (fun r => YP09.r_whi r <=? YP09.r_wlo r) rs = true ->
  forall a, 0 <= a < 2 ^ 64 -> aview segs H m' a = aview segs H m a.
Proof.
  intros E rs H m m' HF Hw a Ha. apply (fw_aview_frame E rs H m m' HF a Ha).
  intros (r & Hin & Hr). rewrite forallb_forall in Hw. specialize (Hw r Hin). apply Z.leb_le in Hw. lia.
Qed.
Lemma fw_sv_U : forall E e v, U E e = v -> sv_denot E e = Z_to_bv 64 v.
Proof. intros E e v <-. unfold U. symmetry. apply Z_to_bv_bv_unsigned. Qed.
Lemma fw_win : forall E rs H (m m' : word -> option byte) lo hi,
  frame_of E rs (mrestrict H m) (mrestrict H m') ->
  Forall (fun r => YP09.r_whi r <= YP09.r_wlo r \/
    (lo <= base_val E (YP09.r_base r) + YP09.r_wlo r /\ base_val E (YP09.r_base r) + YP09.r_whi r <= hi)) rs ->
  forall a, 0 <= a < 2 ^ 64 -> ~ (lo <= a < hi) -> aview segs H m' a = aview segs H m a.
Proof.
  intros E rs H m m' lo hi HF Hrs a Ha Hn. apply (fw_aview_frame E rs H m m' HF a Ha).
  intros (r & Hin & Hr). rewrite Forall_forall in Hrs. destruct (Hrs r Hin) as [Hw|[Hl Hh]]; lia.
Qed.
Lemma fw_val_eqv : forall H (m m' : word -> option byte) a n v,
  (forall x, 0 <= x < 2 ^ 64 -> aview segs H m' x = aview segs H m x) -> 0 <= a -> a + Z.of_nat n <= 2 ^ 64 ->
  val_mem segs (mrestrict H m) a n v -> val_mem segs (mrestrict H m') a n v.
Proof.
  intros H m m' a n v HA Ha Han Hv k Hk. rewrite (mbyte_of_aview segs H H m m'); [apply Hv; exact Hk|].
  apply HA. lia.
Qed.
Lemma fw_writable_kept : forall H (m m2 : word -> option byte) a,
  (apresent H m a -> apresent H m2 a) -> writable_at segs (mrestrict H m) a -> writable_at segs (mrestrict H m2) a.
Proof.
  intros H m m2 a Hp Hw. unfold writable_at, wview, mrestrict in *. revert Hw.
  destruct (H (Z_to_bv 64 a)) eqn:EH; intros Hw; [exact Hw|].
  destruct (m (Z_to_bv 64 a)) as [b|] eqn:Em.
  - destruct (Hp (conj EH (ex_intro _ b Em))) as [_ [b2 Hb2]]. rewrite Hb2. discriminate.
  - destruct (m2 (Z_to_bv 64 a)); [discriminate | exact Hw].
Qed.
Lemma fw_region_kept : forall E H (m m2 : word -> option byte) n b lo hi wlo whi cs,
  bv_unsigned (ew E n) = b ->
  (forall a, b + lo <= a < b + hi -> aview segs H m2 a = aview segs H m a) ->
  (forall a, apresent H m a -> apresent H m2 a) ->
  region_kept segs E (mrestrict H m) (mrestrict H m2) (YP09.mkRegion (Some n) lo hi wlo whi cs).
Proof.
  intros E H m m2 n b lo hi wlo whi cs Hn Hav Hp.
  split; cbn [YP09.r_base YP09.r_lo YP09.r_hi YP09.r_wlo YP09.r_whi base_val]; rewrite Hn; intros a Ha.
  - apply (mbyte_of_aview segs). apply Hav. exact Ha.
  - apply fw_writable_kept. apply Hp.
Qed.

(* ---- facts that read only below alloc_ceiling: kept by stack-only writes ---- *)
Definition fw_low (H : word -> bool) (m m' : word -> option byte) : Prop :=
  forall a, 0 <= a < alloc_ceiling -> aview segs H m' a = aview segs H m a.
Lemma fw_val_low : forall H m m' a n v, fw_low H m m' -> 0 <= a -> a + Z.of_nat n <= alloc_ceiling ->
  val_mem segs (mrestrict H m) a n v -> val_mem segs (mrestrict H m') a n v.
Proof.
  intros H m m' a n v HL Ha Han Hv k Hk. rewrite (mbyte_of_aview segs H H m m'); [apply Hv; exact Hk|].
  apply HL. lia.
Qed.
Lemma fw_cstr_low : forall W mem mem' p l,
  fw_low (w_H W) mem mem' -> cstr_ok segs W mem p l -> cstr_ok segs W mem' p l.
Proof.
  intros W mem mem' p l HL ((HGa & HNZ) & H4096 & Hceil & H32 & Ham & HRA & HHV & HT).
  pose proof asan_consts as (C1 & C2 & C3 & C4 & C5).
  split; [split; [|exact HNZ]|].
  { intros j Hj. destruct (HGa j Hj) as [Hv Hr]. split; [|exact Hr].
    rewrite length_app in Hj. cbn [length] in Hj.
    apply (fw_val_low _ mem mem'); [exact HL | lia | cbn; lia | exact Hv]. }
  split; [exact H4096|]. split; [exact Hceil|]. split; [exact H32|]. split; [exact Ham|].
  split.
  { eapply range_addressable_agree; [|exact HRA]. intros x Hx. apply HL.
    unfold shadow_of_addr, SHADOW_OFF in *. split; [apply Z.add_nonneg_nonneg; [lia | apply Z.div_pos; lia]|].
    assert (x / 8 < 2 ^ 44) by (apply Z.div_lt_upper_bound; lia). lia. }
  split.
  { intros s Hs. rewrite HL; [exact (HHV s Hs)|].
    unfold shadow_addr, SHADOW_OFF in *.
    assert (0 <= (0x7fff8000 + p / 8) / 8 * 8) by (apply Z.mul_nonneg_nonneg; [apply Z.div_pos; [apply Z.add_nonneg_nonneg; [lia | apply Z.div_pos; lia] | lia] | lia]).
    assert ((p + Z.of_nat (length l) + 1 - 1) / 8 < 2 ^ 44) by (apply Z.div_lt_upper_bound; lia).
    assert ((0x7fff8000 + (p + Z.of_nat (length l) + 1 - 1) / 8) / 8 * 8 <= 0x7fff8000 + (p + Z.of_nat (length l) + 1 - 1) / 8)
      by (pose proof (Z.mul_div_le (0x7fff8000 + (p + Z.of_nat (length l) + 1 - 1) / 8) 8 ltac:(lia)); lia).
    lia. }
  intros a Ha. rewrite HL; [exact (HT a Ha)|].
  pose proof (Z.mod_pos_bound (p + Z.of_nat (length l)) 8 ltac:(lia)). lia.
Qed.
Lemma fw_glob_low : forall W mem mem' live peak cnt fail,
  fw_low (w_H W) mem mem' -> fm_glob segs W mem live peak cnt fail -> fm_glob segs W mem' live peak cnt fail.
