  assert (L1 : firstn (length e1) l = e1).
  { replace (length e1) with (Nat.min (length e1) (length e1 + length e2))%nat at 1 by lia.
    rewrite <- firstn_firstn, H, firstn_app, Nat.sub_diag. simpl. rewrite app_nil_r. apply firstn_all. }
  split; [exact L1|].
