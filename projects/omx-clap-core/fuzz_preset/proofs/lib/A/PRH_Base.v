Inductive prh_reach {PI : PrhImg} (CTX0 : list (list Z)) : prh_fn -> list Z -> Prop :=
| prh_reach_top : forall c, In c CTX0 -> prh_reach CTX0 F_LLVMFuzzerTestOneInput c
| prh_reach_call : forall F G c r, prh_reach CTX0 F c -> In r (pi_call_rets F G) ->
    prh_reach CTX0 G (if pi_fp F then r :: c else [r])
| prh_reach_tail : forall F G c, prh_reach CTX0 F c -> pi_tails F G = true -> prh_reach CTX0 G c.
(* a function's OBSERVED entry context x = raZ regs :: spine ch: a prefix of a reachable one (the chain may be cut
   when a frame record lies near the stack top) *)
Definition prh_ctx {PI : PrhImg} (CTX0 : list (list Z)) (F : prh_fn) (x : list Z) : Prop :=
