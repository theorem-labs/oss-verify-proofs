(* THE OUTCOMES OF THE NEXT k HARNESS ALLOCATIONS (fuzz_malloc, fuzz_realloc), counted from g_count = cnt, under #102's
   refusal rule (merged alloc.c:70-78; PRH_FnAlloc.v prh_alloc_post and tfuzz_realloc_specX, the S1 owner's agreement
   14:30:49Z): the one set to fail (cnt + i = fail, failing() :40-46) fails and touches neither g_ran_out nor g_peak;
   any other that fails is a REFUSAL (prh_refused), and refused (n) sets g_ran_out = 1 ONLY when the call's USER
   request n is at most g_most (most, the ledger's field); a refusal of a larger request leaves g_ran_out as it was.
   ns lists the k calls' user requests in call order (fuzz_realloc (p, n): the NEW size n; the TOOBIG path
   n > SIZE_MAX - HEAD is a refusal too). ONE predicate (the kit owner's ruling, 2026-10-29): every text that states a
   run of harness allocations states prh_oks with its own ns. Before #102's rule this set g_ran_out on ANY refusal,
   which is FALSE when the refused request exceeds g_most. Plain ReaderRes.v:92 `oks` is the case with no refusal. *)
Definition prh_refused (ok : list bool) (cnt fail : Z) (i : nat) : bool :=
  negb (nth i ok true) && negb (cnt + Z.of_nat i =? fail).
Definition prh_oks (ok : list bool) (cnt fail : Z) (k : nat) (ns : list Z) (most ran ran' : Z) : Prop :=
  (forall i, (i < k)%nat -> cnt + Z.of_nat i = fail -> nth i ok true = false) /\
  (ran' = ran \/
   (ran' = 1 /\ exists i, (i < k)%nat /\ prh_refused ok cnt fail i = true /\ nth i ns 0 <= most)) /\
  (forall i, (i < k)%nat -> prh_refused ok cnt fail i = true -> nth i ns 0 <= most -> ran' = 1).

(* THE REFUSAL PEAK of the same k calls: refused (n) raises g_peak to min (SIZE_MAX, g_live + n) whether or not it
   sets g_ran_out, at the g_live of the moment it runs - after disown for a realloc of a live block (merged
   alloc.c:104-128), so live - k + n there. hs lists, per call in call order, that g_live + n: the live count the call
   leaves IF GRANTED (live + n for a malloc and for realloc (NULL, n); live - k + n for a realloc of a k-byte block).
   A text whose run may contain refusals states peak' = Z.max (its granted run's peak) (prh_refused_peak ok cnt fail
   k hs): the chosen failure adds nothing (failing () touches neither cell), and own ()'s g_peak = max (g_peak,
   g_live) after each grant is the other term. Under prh_granted it is 0 (prh_refused_peak_granted below). *)
Definition prh_refused_peak (ok : list bool) (cnt fail : Z) (k : nat) (hs : list Z) : Z :=
  fold_right Z.max 0
    (map (fun i => if prh_refused ok cnt fail i then Z.min SIZE_MAXZ (nth i hs 0) else 0) (List.seq 0 k)).

(* THE PER-CALL LISTS OF A READER TRACE (PjGrammar.ev, prh_oks's indexing: the calls PjGrammar.calls counts). ONE
   home, for every text whose run is a reader trace or is written as one (pj_set's prhPj_set_trace). prh_ev_reqs:
   each call's user request, PjReqBound.ev_req (EAlloc n and EFail n give n, EGrow m n the NEW size n). prh_ev_helds:
   the bytes the trace holds above its start right after each call AS IF GRANTED, PjGrammar.held of the prefix
   through it (+ n for EAlloc n, + n - m for EGrow m n), which is prh_refused_peak's hs less the entry's live count. A
   refused call's EFail n does not carry m, so a text takes prh_ev_helds of the ALL-GRANTED trace: a reader run stops
   at its first failure, and up to it the trace is the granted one's (PjGrammar.agrees). *)
Definition prh_ev_reqs (t : list PjGrammar.ev) : list Z :=
  map PjReqBound.ev_req (filter PjGrammar.is_call t).
Fixpoint prh_ev_helds (t : list PjGrammar.ev) : list Z :=
  match t with
  | [] => []
  | e :: r =>
      (if PjGrammar.is_call e then [PjGrammar.held_ev e] else []) ++
      map (Z.add (PjGrammar.held_ev e)) (prh_ev_helds r)
  end.

(* NO REFUSAL among the next k harness allocations: every one that fails is the one set to fail (the converse of
   prh_oks's first conjunct). A text whose position after a refusal is no position of the model's run (the instance
   then frees a block the all-granted run still holds, e.g. pj_write's fuzz_free (buf) after a refused grow) states its
   exact advance under this; a refusal is excluded once, globally, by the driver (P8's preset_no_refusal). *)
Definition prh_granted (ok : list bool) (cnt fail : Z) (k : nat) : Prop :=
  forall i, (i < k)%nat -> nth i ok true = false -> cnt + Z.of_nat i = fail.

(* with no refusal the refusal peak is 0, so Z.max x (prh_refused_peak ..) = x for x >= 0 *)
Lemma prh_refused_peak_granted : forall ok cnt fail k hs,
  prh_granted ok cnt fail k -> prh_refused_peak ok cnt fail k hs = 0.
Proof.
  intros ok cnt fail k hs G. unfold prh_refused_peak.
  assert (E : forall l, (forall i, In i l -> (i < k)%nat) ->
    fold_right Z.max 0
      (map (fun i => if prh_refused ok cnt fail i then Z.min SIZE_MAXZ (nth i hs 0) else 0) l) = 0).
  { induction l as [|i l IH]; intros H; [reflexivity|]. cbn [map fold_right].
    rewrite IH by (intros j Hj; apply H; right; exact Hj).
    unfold prh_refused. destruct (nth i ok true) eqn:Eo; [reflexivity|].
    rewrite (proj2 (Z.eqb_eq _ _) (G i (H i (or_introl eq_refl)) Eo)). reflexivity. }
  apply E. intros i Hi. apply List.in_seq in Hi. lia.
Qed.

