Lemma prh_run_at_app_iff : forall sm x os i e1 e2,
  prh_run_at sm x os i (e1 ++ e2) <->
  prh_run_at sm x os i e1 /\ prh_run_at sm x os (i + length e1) e2.
Proof.
  unfold prh_run_at. intros sm x os i e1 e2. split; [|intros [H1 H2]; exact (prh_run_at_app sm x os i e1 e2 H1 H2)].
  intro H. rewrite length_app in H.
