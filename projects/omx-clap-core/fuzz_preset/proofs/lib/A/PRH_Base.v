(* ---- the program's OBSERVED CALL CONTEXTS, generated from the call graph: the top (LLVMFuzzerTestOneInput) runs in
   a context of CTX0 (the driver's, supplied by the slot); a call F -> G from return site r (pi_call_rets F G) runs G
   in r :: c when F is a frame-pointer function (pi_fp), and in [r] otherwise (F holds a value in s0: an integer, or a
