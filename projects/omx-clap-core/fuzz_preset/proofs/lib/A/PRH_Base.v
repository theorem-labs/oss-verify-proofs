  pose proof (Z_div_mod_eq_full YM05.alloc_ceiling 4096) as HCd.
  pose proof (Z_div_mod_eq_full (p + Z.of_nat (length l)) 8) as HSd.
  pose proof (Z.mod_pos_bound (p + Z.of_nat (length l)) 8 ltac:(lia)) as HSm.
