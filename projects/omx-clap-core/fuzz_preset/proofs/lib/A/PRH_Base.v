Lemma prh_firstn_add : forall (A : Type) n m (l : list A),
  firstn (n + m) l = firstn n l ++ firstn m (skipn n l).
Proof.
  intros A n. induction n as [|n IH]; intros m l; [reflexivity|].
  destruct l as [|a l]; [now destruct m|]. simpl. now rewrite IH.
Qed.

Lemma prh_run_at_app : forall sm x os i evs1 evs2,
  prh_run_at sm x os i evs1 -> prh_run_at sm x os (i + length evs1) evs2 ->
  prh_run_at sm x os i (evs1 ++ evs2).
Proof.
  unfold prh_run_at. intros sm x os i evs1 evs2 H1 H2.
  rewrite length_app, prh_firstn_add, H1. f_equal.
  rewrite <- H2 at 2. f_equal. rewrite skipn_skipn. f_equal. apply Nat.add_comm.
Qed.

