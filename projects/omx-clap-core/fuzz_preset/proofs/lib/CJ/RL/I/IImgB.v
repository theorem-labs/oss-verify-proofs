Definition N_sym_asan (k : Z) : Z := tsym N_exact_asan N_iv k.
Definition N_img_asan : RImg := {| img_segs := rsegs; sym := N_sym_asan |}.
Lemma N_sym_asan_agree : forall k, ~ In k (map fst N_wrap) -> N_sym_asan k = N_sym k.
Proof.
  intros k Hk. unfold N_sym_asan, N_sym, tsym, N_exact_asan.
  assert (E : zlookup k (N_wrap ++ N_exact) = zlookup k N_exact).
  { revert Hk. generalize N_wrap as l. induction l as [|[a x] l IH]; cbn [app zlookup map In fst]; intros Hk; [reflexivity|].
    destruct (Z.eqb_spec k a) as [->|Hne]; [exfalso; apply Hk; left; reflexivity | exact (IH (fun H => Hk (or_intror H)))]. }
  rewrite E. reflexivity.
Qed.
