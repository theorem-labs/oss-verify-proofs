(** * omx-clap-core / fuzz_state: theorem statements

    SUBJECT.  Four builds of omx-clap-core's own fuzz target [fuzz_state], which
    OSS-Fuzz does not run, for omx-clap-core 0.20.1 (FreeMixer/omx-clap-core at
    246923f0), static riscv64 Linux programs run as [<file> FILE]:
      plain       no sanitizer
      ubsan       UndefinedBehaviorSanitizer; a failed check executes a trap
      asan        AddressSanitizer; a report aborts
      asan_ubsan  both
    [Images] names their memory images.  A driver linked into every build reads
    FILE as [u16 config word][config bytes][u32 allocation mask][payload]
    (little-endian; the low 15 bits of the config word are the config length,
    and this harness binary ignores the mask), calls
    LLVMFuzzerTestOneInput(payload, length) one to four times ((config[0] & 3) +
    1; once when there is no config), and prints each return value.  With a
    wrong argument count, a missing or unreadable FILE, a FILE shorter than its
    header, or one of 64 MiB or more, it exits with status 2 without calling the
    harness.  Every statement quantifies over all of these cases and over every
    other process input (see Vocabulary in OSSVerify.Core.Shapes).

    WHAT THE HARNESS CHECKS.  Takes the input up to its first NUL, of at most 3
    MiB, as the base64 text of a preset's state body and decodes it with
    preset_base64_decode, checking the answer against the harness's own reading
    of RFC 4648 base64 (whitespace skipped, padding optional). A decoded body is
    encoded again with preset_base64_encode, compared with the harness's own
    encoding, decoded back, and carried as state.bytes through a whole preset
    document written and read again. The text is then decoded, and the body
    encoded, with the allocation failing.  The harness checks:
    (a) The text decoded from three copies with different bytes after its NUL
    gets the same answer each time, and the same bytes whenever two of them
    decode: the decoder reads nothing past the NUL. [abort(); not confirmed in
    the binary]
    (b) For a text of n characters the decoder holds at most n / 4 * 3 + 3
    bytes. [abort(); not confirmed in the binary]
    (c) The decoder refuses exactly the texts the harness's own reading of RFC
    4648 base64 refuses, and decodes every other text to the bytes the harness
    reads from it. [abort(); not confirmed in the binary]
    (d) A refused text returns no body, leaves the length it was handed
    unwritten, and gives back every byte the decoder allocated. [abort(); not
    confirmed in the binary]
    (e) Any text decoded with its allocation failing is refused cleanly in the
    same way, and a body encoded with the encoder's allocation failing returns
    no text and holds no memory. [abort(); not confirmed in the binary]
    (f) A decoded body encodes to the padded RFC 4648 text of (len + 2) / 3 * 4
    characters, letter for letter the harness's own encoding, equal to the input
    when the input (without whitespace) is already that encoding, and decodes
    back to the same bytes. [abort(); not confirmed in the binary]
    (g) The encoded body set as state.bytes of a preset document, written and
    read back, decodes to the same bytes. [abort(); not confirmed in the binary]
    Only the checks marked ''confirmed in the binary'' had their assertion text
    or message found in the binary's bytes; for the others no usable text was
    found, which does not mean that they are compiled out, and no statement
    below relies on them.

    Whether each statement is open, proved or known false is recorded in the
    harness README, not here: this file changes only when a statement does. *)

From Stdlib Require Import QArith.
From OSSVerify.Core Require Import Shapes.
