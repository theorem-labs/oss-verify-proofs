Lemma lb_remove_second : forall b1 b2 : block, List.NoDup (map blk_id [b1; b2]) -> lb_remove (blk_id b2) [b1; b2] = [b1].
Proof.
  intros b1 b2 ND. cbn [map] in ND. pose proof ND as ND0. apply NoDup_cons_iff in ND. destruct ND as [NI ND2].
  unfold lb_remove. rewrite filter_cons. destruct (decide _) as [Y|N].
  - f_equal. apply (lb_remove_head b2 []). exact ND2.
  - exfalso. destruct (bptr_eqb (blk_id b1) (blk_id b2)) eqn:E.
    + apply NI. left. apply bptr_eqb_eq in E. symmetry. exact E.
    + apply N. cbn [negb]. exact I.
Qed.

