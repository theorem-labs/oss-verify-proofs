(** * FO.Thm_halts_fo — compress_fuzzer plain halts, forced-only

    The tree proves the forced-only core directly (the term below: halting under
    [FOCore.alloc_forced_cfg], no budget premise), after its node relation was moved onto the filtered
    run.  The release shells are the [budget] cells at that configuration and, by monotonicity
    ([FOCore.halts_core_mono]), at the release generator's [forced_only_cfg].  Generated by
    port/tools/mk_fo_overlay.py. *)

From Stdlib Require Import ZArith List.
From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase MemImageType State Run.
From LinuxProcessSemantics.EquivalenceDefinition Require Import Equivalence MustExit HaltsAllowed.
From OSSVerify.Proofs.zlib.compress_fuzzer.lib.plain_halts_any_exit.World Require Import Src_zlib_compress_fuzzer_repro.
From OSSVerify.Proofs.zlib.compress_fuzzer.lib.plain_halts_any_exit Require HaltsFO.
From OSSVerify.Proofs.zlib.compress_fuzzer.lib.plain_halts_any_exit Require FO.NoCkStandIn.
From OSSVerify.Proofs.zlib.compress_fuzzer.lib.plain_halts_any_exit.FO Require Import FOCore.
Unset Lia Cache. Unset Nia Cache. Unset Nra Cache.

Definition img : Image :=
  mkImage Src_zlib_compress_fuzzer_repro.M.loaded_segments Src_zlib_compress_fuzzer_repro.M.init_pc Src_zlib_compress_fuzzer_repro.M.phdrs.

Theorem halts_plain_core_af : halts_core alloc_forced_cfg source_alloc_limit AnyExit.codes img.
Proof. exact (OSSVerify.Proofs.zlib.compress_fuzzer.lib.plain_halts_any_exit.HaltsFO.halts_plain_core OSSVerify.Proofs.zlib.compress_fuzzer.lib.plain_halts_any_exit.FO.NoCkStandIn.no_ckfail). Qed.

Theorem halts_plain_alloc_forced :
  halts_allowed_T_scfg_budgets alloc_forced_cfg ShippedBudgets.lim_source AnyExit.codes img.
Proof. apply halts_allowed_T_scfg_budgets_of_core, halts_plain_core_af. Qed.

Theorem halts_plain_forced_only :
  halts_allowed_T_scfg_budgets forced_only_cfg ShippedBudgets.lim_source AnyExit.codes img.
Proof.
  apply halts_allowed_T_scfg_budgets_of_core.
  exact (halts_core_mono forced_only_cfg alloc_forced_cfg _ _ _ (forced_only_cfg_least _) halts_plain_core_af).
Qed.
