Theorem zr_l2z_compress_path14 : forall x : list Z,
  ZR_Input x ->
  exists enc,
    zr_deflate 2 15 x = Some enc
    /\ zlen enc <= zlen x + Z.shiftr (zlen x) 12 + Z.shiftr (zlen x) 14
                   + Z.shiftr (zlen x) 25 + 13
    /\ zr_inflate14 Z_NO_FLUSH 15 (zlen x) enc = Some x.
Proof.
  intros x Hx.
  pose proof (proj2 Hx) as Hxlen.
  assert (Hxnn : 0 <= zlen x) by (unfold zlen; lia).
  destruct (ZRepro_Emitter_l2z_holds x Hx)
    as [enc [Henc [Hlen [Hbytes Hframe]]]].
  assert (Hcap : zlen x <= 4294967295)
    by (unfold ZR_MAX_INPUT in Hxlen; lia).
  assert (Hin : zlen enc <= 4294967290)
    by (pose proof (zr_bound_small 15 (zlen x) (conj Hxnn Hxlen)); lia).
  exists enc. split; [exact Henc|]. split.
  { rewrite <- zr_compress_bound_agrees. exact Hlen. }
  apply (zr_zlib_face_final14 zr_huff_dyn_leg_holds14
           x enc Z_NO_FLUSH (zlen x) Hx Hframe (or_introl eq_refl)
           ltac:(lia) Hcap Hin Hbytes).
  exact (ZRepro_Pump_l2z_holds14
           x enc Z_NO_FLUSH (zlen x) Hx Henc (or_introl eq_refl)
           ltac:(lia) Hcap).
Qed.

