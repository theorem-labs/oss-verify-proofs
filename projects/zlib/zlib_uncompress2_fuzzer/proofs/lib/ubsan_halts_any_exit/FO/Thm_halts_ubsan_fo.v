(** * FO.Thm_halts_ubsan_fo — zlib_uncompress2_fuzzer UBSan halts, forced-only

    The bundle proves the may-fail statement for the UBSan build (the term below) with no patch.  [FOCore] moves
    it onto every spurious-failure configuration; the release shells are the [budget] cells at the zlib
    re-issue's configuration (memory forced-only) and at the release generator's [forced_only_cfg].  Generated by
    port/tools/mk_t2b_halts.py. *)

