(** The core: halting under every configuration, no budget premise. *)
Theorem halts_ubsan_core : forall cfg, halts_core cfg source_alloc_limit AnyExit.codes img_ubsan.
Proof.
  intros cfg. apply halts_core_of_halts_allowed_may_fail.
  exact (OSSVerify.Proofs.zlib.zlib_uncompress2_fuzzer.lib.ubsan_halts_any_exit.Thm_uncompress2_halts.halts_ubsan (@OSSVerify.Proofs.zlib.zlib_uncompress2_fuzzer.lib.ubsan_halts_any_exit.I7U.T_TopI.zlib_contract_U7)).  (* the contract for every run *)
Qed.

