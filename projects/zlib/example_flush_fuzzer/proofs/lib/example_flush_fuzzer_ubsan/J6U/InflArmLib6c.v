Lemma icset_total_out_facts : forall c m,
  ic_next_in (icset_total_out c m) = ic_next_in c /\ ic_avail_in (icset_total_out c m) = ic_avail_in c
  /\ ic_next_out (icset_total_out c m) = ic_next_out c /\ ic_avail_out (icset_total_out c m) = ic_avail_out c
  /\ ic_input (icset_total_out c m) = ic_input c /\ ic_outbuf (icset_total_out c m) = ic_outbuf c
  /\ ic_total_in (icset_total_out c m) = ic_total_in c /\ ic_adler (icset_total_out c m) = ic_adler c
  /\ ic_msg (icset_total_out c m) = ic_msg c /\ ic_data_type (icset_total_out c m) = ic_data_type c
  /\ ic_total_out (icset_total_out c m) = m.
Proof. intros c m. destruct c. repeat split; reflexivity. Qed.

