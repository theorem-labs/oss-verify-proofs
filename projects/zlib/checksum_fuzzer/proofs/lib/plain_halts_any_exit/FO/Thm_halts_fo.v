(** * FO.Thm_halts_fo — checksum_fuzzer plain halts, forced-only

    The bundle proves the may-fail statement (the term below) with no patch.  [FOCore] moves it onto every
    spurious-failure configuration; the two release shells are the [budget] cells at the zlib re-issue's
    configuration (memory forced-only) and at the release generator's [forced_only_cfg].  Generated by
    port/tools/mk_fo_overlay.py. *)

