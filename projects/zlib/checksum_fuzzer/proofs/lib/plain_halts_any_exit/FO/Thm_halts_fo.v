From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase MemImageType State Run.
From LinuxProcessSemantics.EquivalenceDefinition Require Import Equivalence MustExit HaltsAllowed.
From OSSVerify.Proofs.zlib.checksum_fuzzer.lib.plain_halts_any_exit.World Require Import Src_zlib_checksum_fuzzer_repro.
From OSSVerify.Proofs.zlib.checksum_fuzzer.lib.plain_halts_any_exit Require Thm_checksum_halts.
From OSSVerify.Proofs.zlib.checksum_fuzzer.lib.plain_halts_any_exit.FO Require Import FOCore.
Unset Lia Cache. Unset Nia Cache. Unset Nra Cache.

Definition img : Image :=
  mkImage Src_zlib_checksum_fuzzer_repro.M.loaded_segments Src_zlib_checksum_fuzzer_repro.M.init_pc Src_zlib_checksum_fuzzer_repro.M.phdrs.

(** The core: halting under every configuration, no budget premise. *)
Theorem halts_plain_core : forall cfg, halts_core cfg source_alloc_limit AnyExit.codes img.
Proof.
  intros cfg. apply halts_core_of_halts_allowed_may_fail.
  exact (OSSVerify.Proofs.zlib.checksum_fuzzer.lib.plain_halts_any_exit.Thm_checksum_halts.halts_plain).
Qed.

Theorem halts_plain_alloc_forced :
  halts_allowed_T_scfg_budgets alloc_forced_cfg ShippedBudgets.lim_source AnyExit.codes img.
Proof. apply halts_allowed_T_scfg_budgets_of_core, halts_plain_core. Qed.

Theorem halts_plain_forced_only :
  halts_allowed_T_scfg_budgets forced_only_cfg ShippedBudgets.lim_source AnyExit.codes img.
Proof. apply halts_allowed_T_scfg_budgets_of_core, halts_plain_core. Qed.
