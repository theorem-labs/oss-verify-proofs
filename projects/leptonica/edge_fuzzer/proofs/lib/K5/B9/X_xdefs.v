Lemma XENVC_loc' : forall m m', XENVC m ->
  (forall a : word, in_ranges XENV_FPA (bv_unsigned a) -> ~ in_ranges REG_CELLS (bv_unsigned a) -> m' a = m a) -> XENVC m'.
Proof.
  intros m m' (TID & ATA & EXL & LIBC & OFL & SEU & SOU & SIN & SINU & GDS & FLG & CPL & ODR) AG.
  assert (R : forall lo hi cs A, In (lo, hi) XENV_FPA -> (forall x, lo <= x < hi -> ~ in_ranges REG_CELLS x) -> lo <= A -> A + Z.of_nat (cells_size cs) <= hi ->
            rw_cells asegs m A cs -> rw_cells asegs m' A cs).
  { intros lo hi cs A Hin HD H1 H2 H. apply (rw_cells_agree_nw asegs m m' _ _ H).
    intros a Ha. pose proof (rw_cells_bound asegs m _ _ H). apply AG; [apply (in_XENV_FPA lo hi); [exact Hin| lia]| apply HD; lia]. }
  split; [destruct TID as (t & Ht & C); exists t; split; [exact Ht| apply (R 0x717e10 0x717e14); [cbn; tauto| DJ| lia| cbn; lia| exact C]]|].
  split; [apply (R 0x738028 0x738030); [cbn; tauto| DJ| lia| cbn; lia| exact ATA]|].
  split; [apply (R 0x738128 0x73812c); [cbn; tauto| DJ| lia| cbn; lia| exact EXL]|].
  split; [destruct LIBC as (c1 & c2 & c3 & t & C); exists c1, c2, c3, t; apply (R 0x738148 0x738150); [cbn; tauto| DJ| lia| cbn; lia| exact C]|].
  split; [apply (R 0x7385b0 0x7385b8); [cbn; tauto| DJ| lia| cbn; lia| exact OFL]|].
  split; [apply (R 0x1d3e80 0x1d3e88); [cbn; tauto| DJ| lia| cbn; lia| exact SEU]|].
  split; [apply (R 0x1d3f70 0x1d3f78); [cbn; tauto| DJ| lia| cbn; lia| exact SOU]|].
  split; [destruct SIN as (j0 & j1 & j2 & j3 & j4 & C); exists j0, j1, j2, j3, j4; apply (R 0x1d3f78 0x1e1488); [cbn; tauto| DJ| lia| | exact C];
          destruct C as [[Hw _] _]; cbn in Hw; cbn [cells_size csize]; lia|].
  split; [apply (R 0x1d3f78 0x1e1488); [cbn; tauto| DJ| lia| cbn; lia| exact SINU]|].
  split; [apply (gds_at_agree _ m m' _ GDS); intros a Ha; rewrite asan_gds_length in Ha; cbn in Ha;
          apply AG; [apply (in_XENV_FPA 0x1d3f78 0x1e1488); [cbn; tauto| lia]| intros Hr; apply in_REG_CELLS in Hr; lia]|].
