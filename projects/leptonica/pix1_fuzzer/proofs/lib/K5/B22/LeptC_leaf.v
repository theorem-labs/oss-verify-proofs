Lemma cb4_c4 : forall (m : mem) A bs, rw_cells asegs m A [CB 4 bs] -> exists w : word, rw_cells asegs m A [C4 w].
Proof.
  intros m A bs H. exists (Z_to_bv 64 (bytes_le_to_Z bs)).
  pose proof H as [[[L _] _] _]. cbn in L.
  apply (rw_cells_recell m A _ _ H); [cbn; tauto| | reflexivity].
  cbn [cells_bytes cbytes app]. f_equal. unfold le4. rewrite Z_to_bv_unsigned. unfold bv_wrap, bv_modulus. change (2 ^ Z.of_N 64) with (2 ^ 64).
  rewrite (Z_to_le_bytes_mod 4 _ 64) by lia. rewrite <- L. exact (le_bytes_roundtrip bs).
Qed.


