Theorem strtokSafe_end_ok : strtokSafe_end_cps RT.
Proof using AF GP.
  intros Σ PMc ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 F fc m lo tl
    FDO MST -> -> -> -> OP TLC ENV RES.
  unfold lpost, lenv, lres, keeps, keepsL, optrF in *. destruct ENV as (LH & SSP & ART0 & MI & ST & LOW & LOR & SPT & SPA & SPB).
  destruct RES as (FRB & LVB & CRB & LVP).
  destruct OP as (OWNF & TL0 & TL8 & TLH & TLS).
  pose proof OWNF as (ff & kf & FIN & F1 & F2 & F8 & F0 & FT & FB).
  assert (OWN : accok (rt_live RT Σ) (rt_frames RT Σ) m tl 8) by (right; exact OWNF).
  hide FB. hide OWNF.
  destruct (af_client_consts RT AF Σ m ART0) as (G1 & G2 & G3 & G4).
  pose proof (af_sp0_range RT AF Σ m ART0) as SP0R. pose proof (af_sp0_win RT AF Σ m ART0) as SP0W.
  unfold entry_st, e_strtokSafe, g_GOT_shadow_offset_cell, g_shadow_memory_dynamic_address, g_GOT_detect_uar, g_detect_stack_use_after_return in *.
  set (usp := bv_unsigned sp) in *.
  assert (ESP : sp = Z_to_bv 64 usp) by (unfold usp; symmetry; apply Z_to_bv_bv_unsigned). rewrite ESP.
  assert (USP : 0 <= usp < 2^64) by (unfold usp; apply bv_unsigned_in_range).
  unfold LSTK, STDERR_STACK in *. unfold STACK_WIN, USTACK_TOP, RT_STACK, SEGTOP_A in *. unfold SHB in *.
  lazymatch goal with |- cps _ _ ?Q => set (QF := Q) end.
  pose proof ST as (STa & STb & _).
  lib_refresh RT GP.
  set (PF := fun a => aclient (rt_live RT Σ) (rt_frames RT Σ) usp a).
  pose proof (agree_refl PF m) as AGF.
  assert (PFS : forall a, PF a -> usp <= a \/ a < lo).
  { intros a Ha. destruct (aclient_split RT AF Σ m usp a ART0 Ha) as [H|H]; [left; exact H| right; unfold STACK_WIN in H; lia]. }
  assert (TLLO : tl + 8 <= lo).
  { pose proof (af_frames_range RT AF Σ m ff kf ART0 FIN) as (_ & R & _).
    unfold STACK_WIN, USTACK_TOP, RT_STACK, SEGTOP_A in *. lia. }
  assert (TLR : 0 < tl /\ tl + 8 < 2^47) by (clear - TL0 TLLO LOR SPT; lia).
  destruct TLR as [_ TLR1].
  unfold LIT_SEPS in *.
  refresh RT AF. unfold shad, SHB in *.
  tok_stops ltac:(fun stops => walk_to AF MST [(usp - 96, usp)] stops; pwalk stops).
  cps_stop.
  art_now RT AF ltac:(cbn [ivls_client]; split; [intros zz Hzz; left; ul| exact I]).
  lazymatch goal with
  | AGFx : agree_on ?PFx _ ?mm, MUx : munch _ ?mm _ |- _ =>
      is_var PFx; agf_munch AGFx MUx ltac:(fun Hx => cbn [outside]; pose proof (PFS _ Hx); split; [lia| exact I])
  end.
  apply cps_finish; intros c Hc; subst QF; cbv beta.
  eapply (ASTA_conseq RT); [exact Hc|]; intros ms <-; eexists.
  split; [unfold ret_st; rewrite ESP; do 16 eexists; reflexivity|].
  split; [split; [split; [assumption| split; [assumption| split; [exact WM | assumption]]]| split; assumption]|].
  intros a Ha _; apply AGF; exact Ha.
Qed.
End STRTOKEND.
