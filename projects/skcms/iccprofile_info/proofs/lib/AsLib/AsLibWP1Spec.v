Definition rte_pre_as (data : word) (len : Z) (bs : list byte) (c : word)
    (FP : FPState) (regs : bvmap 5 word) (mem : word -> option byte) : Prop :=
  getr regs 10 = c /\ as_data_ok ceil mem data len bs /\ curve_ok segs mem data len (bv_unsigned c) /\
  (bv_unsigned c mod 8 = 0)%Z /\ heapish ceil (bv_unsigned c) 32 /\ shz mem (bv_unsigned c) 3 /\
  as_sb segs L mem /\
  (exists sp, getr regs 2 = sp /\ as_frame segs ceil mem sp 16).

Definition rte_post_as (data : word) (len : Z) (bs : list byte) (c : word)
    (regs : bvmap 5 word) (mem : word -> option byte)
    (FP' : FPState) (regs' : bvmap 5 word) (mem' : word -> option byte) : Prop :=
  frame_mod mem mem' [(Z_to_bv 64 (bv_unsigned (getr regs 2) - 16), 16%Z)].

Definition rte_contract_as : Prop :=
