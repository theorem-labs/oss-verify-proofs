#!/usr/bin/env python3
"""core_check.py CORE_REF CORE_SHA LAYER_SHA -- records, from git alone, that the image-B start-up layer is built in the
unit's image-B core: the core branch head (`git ls-remote`), that LAYER_SHA is an ancestor of it, the merge commit that
brings it in, that the core head changes nothing outside provenance/ after that merge, the core's own build record
(section 0 of provenance/evidence/core-B/GATES.md at the head), and that the shared provenance/evidence/MANIFEST.md (and
MANIFEST, where the head carries one) is exactly what its own header's writer of record writes from the slices present
there (the no-hand-edit rule for a shared file). That writer is a registered tool (WRITERS below), read from git and run
here; no slice ships a copy of it. Exit 1 if any of these does not hold. Paths from ucib_env.py.

  core_check.py <image-B core branch> f47e2a8927b9 89a444c41f23
"""
import hashlib, os, re, shutil, subprocess, sys, tempfile

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ucib_env import need  # noqa: E402

OVPI = need('UCIB_OVPI')
EV = 'proofs/reac-repacer/fuzz_uci/provenance/evidence'
# the registered writer of provenance/evidence/MANIFEST.md and MANIFEST: sha256 -> the (commit, path) that hold that
# copy. The index names the writer that wrote it in its own header line; when that is not this registered copy (an
# older head), the writer is read from that head's own tree at the path the header names, so each head is checked
# against the file that wrote it. No slice ships a copy of any of them.
WRITERS = {
    'a0ba0eb66d6693325368f3dae7dec2e19ca4c3566de3cc51deec41d92227ba0a':
        ('4f2904dd062', 'tools/mk_top_manifest/a0ba0eb66d66/mk_top_manifest.py'),
}
MKTOP_SHA = 'a0ba0eb66d6693325368f3dae7dec2e19ca4c3566de3cc51deec41d92227ba0a'


def git(*a, check=True):
    r = subprocess.run(['git', '-C', OVPI] + list(a), capture_output=True, text=True)
    if check and r.returncode:
        raise SystemExit('core_check: git %s failed: %s' % (' '.join(a), r.stderr.strip()))
    return r


def main():
    ref, head, layer = sys.argv[1:4]
    bad = 0
    ls = git('ls-remote', 'origin', 'refs/heads/' + ref).stdout.split()
    print('ls-remote %s = %s (want %s...): %s' % (ref, ls[0] if ls else '-', head, bool(ls) and ls[0].startswith(head)))
    bad += not (ls and ls[0].startswith(head))
    git('fetch', '-q', 'origin', ref)
    anc = git('merge-base', '--is-ancestor', layer, head, check=False).returncode == 0
    print('layer %s is an ancestor of core head %s: %s' % (layer, head, anc))
    bad += not anc
    merges = git('log', '--merges', '--format=%h %p %s', '--ancestry-path', '%s..%s' % (layer, head)).stdout.strip().split('\n')
    mine = [l for l in merges if l and layer[:10] in l]
    print('merge commit(s) bringing %s in: %s' % (layer, mine or 'none'))
    bad += not mine
    if mine:
        mc = mine[-1].split()[0]
        after = [p for p in git('diff', '--name-only', mc, head).stdout.split() if '/provenance/' not in p]
        print('files the core head changes after merge %s outside provenance/: %d %s' % (mc, len(after), after[:5]))
        bad += bool(after)
    gm = git('show', '%s:%s/core-B/GATES.md' % (head, EV)).stdout
    sec = re.search(r'## 0\..*?(?=\n## )', gm, re.S)
    rec = [l.strip() for l in (sec.group(0) if sec else '').split('\n') if 'cb build' in l or 'rc 0' in l or 'PINNED' in l]
    print('core build record (core-B/GATES.md section 0 at %s): %s' % (head, ' '.join(rec) or 'NOT FOUND'))
    bad += not any('rc 0, 0 failed' in l for l in rec)
    tmp = tempfile.mkdtemp(prefix='ucib-core-')
    try:
        arch = subprocess.run(['git', '-C', OVPI, 'archive', head, EV], capture_output=True, check=True).stdout
        subprocess.run(['tar', '-x', '-C', tmp], input=arch, check=True)
        top = os.path.join(tmp, EV)
        committed = {f: open(os.path.join(top, f), 'rb').read() for f in ('MANIFEST.md', 'MANIFEST')
                     if os.path.isfile(os.path.join(top, f))}
        loose = sorted(f for f in os.listdir(top) if os.path.isfile(os.path.join(top, f))
                       and f not in ('MANIFEST.md', 'MANIFEST'))
        # the index names its own writer: `(copy of record <path>, sha256 <sha>)`, or `(<path>)` in the first
        # generation of the header. A registered sha is read from the tool set; anything else from this head's tree.
        text = committed['MANIFEST.md'].decode()
        m = re.search(r'copy of record (\S+), sha256 ([0-9a-f]{64})\)', text) or re.search(
            r'Generated by mk_top_manifest\.py \(([^)\s]+)\)', text)
        named = m.group(1) if m else None
        wsha = m.group(2) if m and m.lastindex == 2 else None
        if wsha in WRITERS:
            src = WRITERS[wsha]
            blob = subprocess.run(['git', '-C', OVPI, 'show', '%s:%s' % src], capture_output=True, check=True).stdout
        elif named:
            p = os.path.join(top, named)
            blob = open(p, 'rb').read() if os.path.isfile(p) else None
            wsha = wsha or (hashlib.sha256(blob).hexdigest() if blob else None)
            src = ('%s (this head\'s own tree)' % head, named)
        else:
            blob, src = None, None
        print('the index at %s names its writer %s, sha256 %s, read from %s: %s' % (
            head, named, wsha, '%s:%s' % src if src else 'NOWHERE',
            'the registered writer of record' if wsha == MKTOP_SHA else
            'not the registered writer of record (%s)' % MKTOP_SHA))
        bad += blob is None or hashlib.sha256(blob).hexdigest() != wsha
        if blob is not None and hashlib.sha256(blob).hexdigest() == wsha:
            gen = os.path.join(tmp, 'mk_top_manifest.py')
            open(gen, 'wb').write(blob)
            out = subprocess.run([sys.executable, gen, top], capture_output=True, text=True,
                                 check=True).stdout.strip().replace('\n', '; ')
            for name, data in sorted(committed.items()):
                regen = open(os.path.join(top, name), 'rb').read()
                print('provenance/evidence/%s at %s vs that writer (%s): %s' % (
                    name, head, out, 'BYTE-EQUAL' if regen == data else 'differs'))
                if regen != data:
                    extra = [l for l in regen.decode().split('\n') if l not in data.decode().split('\n')]
                    print('  lines only the writer writes: %s (loose top-level files: %s)' % (extra, loose))
                    bad += any(l for l in extra if not any(lf in l for lf in loose))
    finally:
        shutil.rmtree(tmp)
    print('core_check: %s' % ('PASS' if not bad else 'FAIL (%d)' % bad))
    sys.exit(1 if bad else 0)


main()
