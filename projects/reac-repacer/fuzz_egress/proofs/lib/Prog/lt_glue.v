Lemma rw_cells_app : forall segs m A cs1 cs2, rw_cells segs m A cs1 ->
  rw_cells segs m (A + Z.of_nat (cells_size cs1)) cs2 -> rw_cells segs m A (cs1 ++ cs2).
Proof.
  intros segs m A cs1 cs2 [[W1 B1] (R1a & R1b & R1)] [[W2 B2] (R2a & R2b & R2)].
  split; [split|].
  - apply cells_wf_app. split; assumption.
  - rewrite cells_bytes_app. apply bytes_at_app. split; [exact B1|].
    rewrite cells_bytes_length by exact W1. exact B2.
  - rewrite cells_size_app. split; [lia|]. split; [lia|]. intros i Hi.
    destruct (Z_lt_le_dec i (Z.of_nat (cells_size cs1))) as [H|H]; [apply R1; lia|].
    replace (A + i) with (A + Z.of_nat (cells_size cs1) + (i - Z.of_nat (cells_size cs1))) by lia.
    apply R2. lia.
Qed.

(* the first cell of a cell list, and the rest after it *)
Lemma rwc_cons : forall segs m A c cs, rw_cells segs m A (c :: cs) ->
  rw_cells segs m A [c] /\ rw_cells segs m (A + Z.of_nat (csize c)) cs.
Proof.
  intros segs m A c cs [[[Hc Hwf] Hb] (W0 & W1 & Hw)].
  cbn [cells_bytes] in Hb. apply bytes_at_app in Hb as [Hb1 Hb2]. rewrite cbytes_length in Hb2 by exact Hc.
  cbn [cells_size] in W1, Hw.
  split.
  - split; [split; [split; [exact Hc | exact I] | cbn [cells_bytes]; rewrite app_nil_r; exact Hb1]|].
    cbn [cells_size]. split; [lia|]. split; [lia|]. intros i Hi. apply Hw. lia.
  - split; [split; [exact Hwf | exact Hb2]|].
    split; [lia|]. split; [lia|]. intros i Hi.
    replace (A + Z.of_nat (csize c) + i) with (A + (Z.of_nat (csize c) + i)) by lia. apply Hw. lia.
Qed.

(* a cell list's meaning is its bytes: reshape it freely *)
Lemma rwc_bytes : forall segs m A cs cs', rw_cells segs m A cs -> cells_wf cs' ->
  cells_bytes cs' = cells_bytes cs -> rw_cells segs m A cs'.
Proof.
  intros segs m A cs cs' [[Hwf Hb] Hw] Hwf' E.
  split; [split; [exact Hwf' | rewrite E; exact Hb]|].
  rewrite <- (cells_bytes_length cs' Hwf'), E, (cells_bytes_length cs Hwf). exact Hw.
Qed.

Lemma cells_wf_c1 : forall bs, cells_wf (map C1 bs).
Proof. induction bs as [|x bs IH]; cbn; [exact I | split; [exact I | exact IH]]. Qed.

Lemma cells_bytes_c1 : forall bs, cells_bytes (map C1 bs) = bs.
Proof. induction bs as [|x bs IH]; cbn; [reflexivity | rewrite IH; reflexivity]. Qed.

(* a run of bytes as one byte cell each *)
Lemma rwc_c1 : forall segs m A n bs, rw_cells segs m A [CB n bs] -> rw_cells segs m A (map C1 bs).
Proof.
  intros segs m A n bs H. apply (rwc_bytes segs m A _ _ H); [apply cells_wf_c1|].
  rewrite cells_bytes_c1. cbn [cells_bytes cbytes]. rewrite app_nil_r. reflexivity.
Qed.

(* the first k bytes of a run, and the n - k after them *)
Lemma rwc_cut : forall segs m A n bs k, rw_cells segs m A [CB n bs] -> (k <= n)%nat ->
  rw_cells segs m A [CB k (firstn k bs)] /\ rw_cells segs m (A + Z.of_nat k) [CB (n - k) (skipn k bs)].
Proof.
  intros segs m A n bs k H Hk.
  pose proof H as [[[Hc _] _] _]. cbn [cell_wf] in Hc.
  assert (H2 : rw_cells segs m A [CB k (firstn k bs); CB (n - k) (skipn k bs)]).
  { apply (rwc_bytes segs m A _ _ H).
    - cbn [cells_wf cell_wf]. rewrite length_firstn, length_skipn. repeat split; lia.
    - cbn [cells_bytes cbytes]. rewrite !app_nil_r. apply firstn_skipn. }
  destruct (rwc_cons segs m A _ _ H2) as [R1 R2]. split; [exact R1 | exact R2].
Qed.

(* two runs side by side are one run *)
Lemma rwc_join : forall segs m A k n bs1 bs2, rw_cells segs m A [CB k bs1] ->
  rw_cells segs m (A + Z.of_nat k) [CB n bs2] -> rw_cells segs m A [CB (k + n) (bs1 ++ bs2)].
Proof.
  intros segs m A k n bs1 bs2 H1 H2.
  pose proof H1 as [[[Hc1 _] _] _]. pose proof H2 as [[[Hc2 _] _] _]. cbn [cell_wf] in Hc1, Hc2.
  assert (H : rw_cells segs m A ([CB k bs1] ++ [CB n bs2])).
  { apply rw_cells_app; [exact H1|]. cbn [cells_size csize]. rewrite Nat.add_0_r. exact H2. }
  apply (rwc_bytes segs m A _ _ H).
  - cbn [cells_wf cell_wf]. rewrite length_app. split; [lia | exact I].
  - cbn [cells_bytes cbytes app]. rewrite !app_nil_r. reflexivity.
Qed.

