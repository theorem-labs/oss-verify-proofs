Open Scope Z_scope.

Definition REAC_FRAME_CLEAN_LEN : Z := 0x13cac.
Definition A_M : Z := 0x10398.
Definition A_T : Z := 0x103e8.
Definition KM : Z := 0x8e38e38e38e38e39.
Definition KT : Z := 0x071c71c71c71c71d.

Definition reac_frame_clean_len_model (n : Z) : Z :=
  if (54 <=? n) && ((n - 52) mod 36 =? 2) then n - 2 else n.

Definition reac_frame_clean_len_contract : Prop :=
  forall (ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
         (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte),
    bytes_at rsegs m A_M (le8 (Z_to_bv 64 KM)) ->
    bytes_at rsegs m A_T (le8 (Z_to_bv 64 KT)) ->
    evt rsegs
      (fun ms' => exists a1' a2' a3' : word,
         ms' = MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 (reac_frame_clean_len_model (bv_unsigned a0)))
                       a1' a2' a3' a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
                  F (ret_pc ra) fc None m (seg_rom rsegs))
      (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
          F (Z_to_bv 64 REAC_FRAME_CLEAN_LEN) fc None m (seg_rom rsegs)).
