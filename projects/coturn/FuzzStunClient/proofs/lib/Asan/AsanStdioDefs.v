Definition ssp_cells (mem : word -> option byte) (can : word) : Prop :=
  rdn ASEGS mem (Z_to_bv 64 0xabb08) 8%nat = Some (word_to_le_bytes 8 (Z_to_bv 64 0x606630))
  /\ rdn ASEGS mem (Z_to_bv 64 0x606630) 8%nat = Some (word_to_le_bytes 8 can).

