Definition CHECK_STEP : Z := 0x153ec.
Definition CHECK_STEP_K : Z := 224.

Definition check_step_contract : Prop :=
  forall (ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
         (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte) (lo : Z) (b : list byte),
    mem_inv rsegs m ->
    stk rsegs m lo (bv_unsigned sp) ->
    lo + CHECK_STEP_K <= bv_unsigned sp ->
    bv_unsigned sp mod 16 = 0 ->
    bv_unsigned a2 <= 342 ->
    bytes_at rsegs m (bv_unsigned a0) (scene_block b (bv_unsigned a2)) ->
    bytes_at rsegs m (bv_unsigned a1) b -> length b = 8904%nat ->
    bv_unsigned sp <= bv_unsigned a0 ->
    (bv_unsigned a1 + 8904 <= lo \/ bv_unsigned sp <= bv_unsigned a1) ->
    evt rsegs
      (fun ms' => exists (t0' t1' t2' a0' a1' a2' a3' a4' a5' a6' a7' t3' t4' t5' t6' : word)
                         (m' : word -> option byte),
         ms' = MS (mkR ra sp gp tp t0' t1' t2' s0 s1 a0' a1' a2' a3' a4' a5' a6' a7'
                       s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3' t4' t5' t6')
                  F (ret_pc ra) fc None m' (seg_rom rsegs) /\
         munch [(bv_unsigned sp - CHECK_STEP_K, bv_unsigned sp)] m m' /\
         wmono rsegs m m' /\
         mem_inv rsegs m' /\
         stk rsegs m' lo (bv_unsigned sp))
      (MS (mkR ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
          F (Z_to_bv 64 CHECK_STEP) fc None m (seg_rom rsegs)).
