  (0 <=? p) && forallb (fun k => bd_byte_ok (p + Z.of_nat k)) (seq 0 n) && (p + Z.of_nat n <=? B.AsanRT.APPMEM_END).

Lemma bd_le_byte_small : forall k, 0 <= k < 256 -> lib.Reusable.YG0f.le_byte k 1 0 = k.
