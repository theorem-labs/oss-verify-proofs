(* No as_owned_static extent of B meets [lo, hi). *)
Definition bd_own_avoid (lo hi : Z) : bool :=
  forallb (fun r => (fst r + snd r <=? lo) || (hi <=? fst r)) lib.Reusable.YF0m.Tfib_owned_static.

Lemma bd_own_avoid_sound : forall lo hi a, bd_own_avoid lo hi = true -> lo <= a < hi ->
  ~ Exists (lib.Reusable.YG0n.in_zr a) lib.Reusable.YF0m.Tfib_owned_static.
Proof.
  intros lo hi a Hc Ha HE. apply Exists_exists in HE as (r & Hr & Hz).
  unfold bd_own_avoid in Hc. rewrite forallb_forall in Hc. specialize (Hc r Hr).
  unfold lib.Reusable.YG0n.in_zr in Hz.
  apply orb_prop in Hc as [Hc | Hc]; apply Z.leb_le in Hc; lia.
Qed.

(* [lo, hi) lies in the full granules of an 8-aligned Tfib_zero_shadow range. *)
Definition bd_zs_cov (lo hi : Z) : bool :=
  existsb (fun r => (fst r mod 8 =? 0) && (fst r <=? lo) && (hi <=? fst r + 8 * (snd r / 8)))
    lib.Reusable.YF0m.Tfib_zero_shadow.

Lemma bd_zs_cov_sound : forall lo hi, bd_zs_cov lo hi = true ->
  exists r, In r lib.Reusable.YF0m.Tfib_zero_shadow /\ fst r mod 8 = 0 /\ fst r <= lo /\
            hi <= fst r + 8 * (snd r / 8).
Proof.
  intros lo hi H. apply existsb_exists in H as (r & Hr & Hb).
  apply andb_prop in Hb as [Hb H3]. apply andb_prop in Hb as [H1 H2].
  apply Z.eqb_eq in H1. apply Z.leb_le in H2. apply Z.leb_le in H3.
  exists r. split; [exact Hr|]. split; [exact H1|]. split; [exact H2 | exact H3].
Qed.

