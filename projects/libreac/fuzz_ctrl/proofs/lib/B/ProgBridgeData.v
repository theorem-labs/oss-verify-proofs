(* The bytes bs at a lie inside the cell (c, w) := v, and each is v's little-endian byte at its offset.  The range
   test guards the byte test with `if`, so vm_compute (call by value) builds the offset Z.to_nat (a - c) only for
   the cell that contains a, where it is below w. *)
Definition bd_bytes_match (c : Z) (w : nat) (v a : Z) (bs : list byte) : bool :=
  if (c <=? a) && (a + Z.of_nat (length bs) <=? c + Z.of_nat w) then
    forallb (fun i => match nth_error bs i with
                      | Some b => bv_unsigned b =? lib.Reusable.YG0f.le_byte v w (Z.to_nat (a - c) + i)
                      | None => false
                      end) (seq 0 (length bs))
  else false.

