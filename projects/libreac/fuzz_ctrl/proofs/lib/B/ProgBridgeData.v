(* B's constant shadow cells hold, at shadow_addr a, a partial-granule value k that admits a. *)
Definition bd_cs_ok (a : Z) : bool :=
  existsb (fun c => match bd_cell_sh c with
                    | Some (s, k) => (s =? B.AsanRT.shadow_addr a) && (a mod 8 <? k) && (k <=? 7)
                    | None => false
                    end) lib.Reusable.YF0m.Tfib_const_shadow.

(* Byte a is in low application memory, and its shadow byte is a zero-shadow byte or a constant shadow cell. *)
Definition bd_byte_ok (a : Z) : bool :=
  (0 <=? a) && (a <? B.AsanRT.LOWMEM_END) && (bd_zs_cov a (a + 1) || bd_cs_ok a).

(* The n bytes from p are bd_byte_ok and lie below APPMEM_END. *)
