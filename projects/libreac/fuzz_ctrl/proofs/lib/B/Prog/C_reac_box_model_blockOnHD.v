(* The word cover of a sub-range of the run's frame [fr, fr + 64) is in the run's region: the frame is the real-stack
   frame A - 64 inside the window [S - 4272, S) (A between S - 176 and S - 160), or the class-0 frame
   fs_frame FS 0 j (0 <= j < 16384) inside the class-0 block, whose shadow is
   asan_stack_malloc_shadow_R FS 0 = [shadow_addr (FS + 36864), + 131072). *)
Lemma mbHD_R_fr : forall (S FS p b o : Z) (row nb : list byte) (A fr j q k a : Z),
  FS mod 64 = 0 -> S - 176 <= A <= S - 160 ->
  (fr = A - 64 \/ (0 <= j < 16384 /\ fr = fs_frame FS 0 j)) ->
  0 <= k -> fr <= q -> q + k <= fr + 64 -> sh_word_on q k a ->
  reac_box_model_block_shadow_R S FS p b o row nb a.
Proof.
  intros S FS p b o row nb A fr j q k a H64 HA Hfr Hk Hq1 Hq2 Ha.
  destruct Hfr as [Efr | (Hj & Efr)].
  - apply (mbHB_R_win S FS p b o row nb q k a Hk); [lia | lia | exact Ha].
  - unfold reac_box_model_block_shadow_R. right; left. unfold asan_stack_malloc_shadow_R.
    assert (E0 : fs_frame FS 0 0 = FS + 36864)
      by (unfold fs_frame, fs_B; cbn [Z.of_nat]; change (2 ^ 0) with 1; lia).
    assert (Ej : fr = FS + 36864 + 64 * j)
      by (rewrite Efr; unfold fs_frame, fs_B; cbn [Z.of_nat]; change (2 ^ 0) with 1; lia).
    rewrite E0. clear Efr E0.
    destruct Ha as (Hk0 & Hlo & Hhi).
    unfold rng_asan.sh_al8_lo, rng_asan.sh_al8_hi, shadow_addr in Hlo, Hhi. unfold shadow_addr.
    unfold ASAN_K in *.
    Z.div_mod_to_equations. lia.
Qed.

(* build_dt1_single's region at the operands (O, D, N) as literal words, from the word covers of the two ranges. *)
Lemma mbHD_bd : forall (P : Z -> Prop) (mc : word -> option byte) (O D N : Z),
  shadow_rw_on P mc -> 0 <= O < 2^64 -> 0 <= D < 2^64 -> 0 <= N < 2^64 ->
  (forall a, sh_word_on D N a -> P a) -> (forall a, sh_word_on (O + 20) N a -> P a) ->
  shadow_rw_on (build_dt1_single_shadow_R (bv_unsigned (Z_to_bv 64 O)) (bv_unsigned (Z_to_bv 64 D))
                  (bv_unsigned (Z_to_bv 64 N))) mc.
Proof.
  intros P mc O D N H RO RD RN HD HO. apply (shadow_rw_on_mono P _ mc); [|exact H].
  intros a Ha. unfold build_dt1_single_shadow_R in Ha.
  rewrite (unsigned_lit O RO), (unsigned_lit D RD), (unsigned_lit N RN) in Ha.
  destruct Ha as [Ha|Ha]; [exact (HD a Ha) | exact (HO a Ha)].
Qed.

