(* A region premise at m holds at every later memory of the run (the run's BI: wmono m mc and rd_mono m mc). *)
Lemma mbHB_carry : forall (P : Z -> Prop) (m mc : word -> option byte), shadow_rw_on P m -> wmono rsegs m mc ->
  (forall x : word, (exists v, mrd rsegs m x = Some v) -> exists v, mrd rsegs mc x = Some v) ->
  shadow_rw_on P mc.
Proof.
  intros P m mc H Hw Hr a Hp Ha. destruct (H a Hp Ha) as [Hv Hb]. split; [apply Hw, Hv | apply Hr, Hb].
Qed.

(* The word cover of [q, q + k) lies in the word cover of [p, p + n) when [q, q + k) lies in [p, p + n). *)
Lemma mbHB_sub : forall p n q k a, 0 <= k -> p <= q -> q + k <= p + n -> sh_word_on q k a -> sh_word_on p n a.
Proof.
  intros p n q k a Hk Hpq Hqn [Hk0 [Hlo Hhi]].
  unfold sh_word_on, rng_asan.sh_al8_lo, rng_asan.sh_al8_hi, shadow_addr in *.
  assert (D1 : p / 8 <= q / 8) by (apply Z.div_le_mono; lia).
  assert (D2 : (q + k - 1) / 8 <= (p + n - 1) / 8) by (apply Z.div_le_mono; lia).
  assert (L1 : (p / 8 + ASAN_K) / 8 <= (q / 8 + ASAN_K) / 8) by (apply Z.div_le_mono; lia).
  assert (L2 : ((q + k - 1) / 8 + ASAN_K) / 8 <= ((p + n - 1) / 8 + ASAN_K) / 8)
    by (apply Z.div_le_mono; lia).
  split; [lia | split; lia].
Qed.

Section R.
  Variables (S FS p b o : Z) (row nb : list byte).

  (* disjunct 1: the window [S - 4272, S) *)
  Lemma mbHB_R_win : forall q k a, 0 <= k -> S - 4272 <= q -> q + k <= S -> sh_word_on q k a ->
    reac_box_model_block_shadow_R S FS p b o row nb a.
  Proof.
    intros q k a Hk H1 H2 H. unfold reac_box_model_block_shadow_R. left.
    apply (mbHB_sub _ _ q k a Hk); [unfold REAC_BOX_MODEL_BLOCK_K; lia | unfold REAC_BOX_MODEL_BLOCK_K; lia | exact H].
  Qed.

  (* disjunct 3: the row [p, p + 296), p <> 0 *)
  Lemma mbHB_R_row : forall q k a, 0 <= k -> p <> 0 -> p <= q -> q + k <= p + 296 -> sh_word_on q k a ->
    reac_box_model_block_shadow_R S FS p b o row nb a.
  Proof.
    intros q k a Hk Hp H1 H2 H. unfold reac_box_model_block_shadow_R. right; right; left.
    split; [exact Hp | exact (mbHB_sub _ _ q k a Hk H1 H2 H)].
  Qed.

  (* disjunct 5: the output block [o, o + 32), o <> 0 *)
  Lemma mbHB_R_o : forall q k a, 0 <= k -> o <> 0 -> o <= q -> q + k <= o + 32 -> sh_word_on q k a ->
    reac_box_model_block_shadow_R S FS p b o row nb a.
  Proof.
    intros q k a Hk Ho H1 H2 H. unfold reac_box_model_block_shadow_R. right; right; right; right; left.
    split; [exact Ho | exact (mbHB_sub _ _ q k a Hk H1 H2 H)].
  Qed.

  (* disjuncts 6 and 7: the JOIN block that b selects *)
  Lemma mbHB_R_j14 : forall a, b = 1 -> sh_word_on JOIN_0014 32 a -> reac_box_model_block_shadow_R S FS p b o row nb a.
  Proof.
    intros a Hb H. unfold reac_box_model_block_shadow_R. right; right; right; right; right; left.
    exact (conj Hb H).
  Qed.

  Lemma mbHB_R_j13 : forall a, b = 2 -> sh_word_on JOIN_0013 32 a -> reac_box_model_block_shadow_R S FS p b o row nb a.
  Proof.
    intros a Hb H. unfold reac_box_model_block_shadow_R. right; right; right; right; right; right.
    exact (conj Hb H).
  Qed.
End R.

(* __asan_memcpy's region at the operands (D, S, N) as literal words, from the word covers of the two ranges. *)
Lemma mbHB_cpy : forall (P : Z -> Prop) (mc : word -> option byte) (D Sr N : Z),
  shadow_rw_on P mc -> 0 <= D < 2^64 -> 0 <= Sr < 2^64 -> 0 <= N < 2^64 ->
  (forall a, sh_word_on Sr N a -> P a) -> (forall a, sh_word_on D N a -> P a) ->
  shadow_rw_on (asan_memcpy_shadow_R (Z_to_bv 64 D) (Z_to_bv 64 Sr) (Z_to_bv 64 N)) mc.
Proof.
  intros P mc D Sr N H RD RS RN HS HD. apply (shadow_rw_on_mono P _ mc); [|exact H].
  intros a Ha. unfold asan_memcpy_shadow_R in Ha.
  rewrite (unsigned_lit D RD), (unsigned_lit Sr RS), (unsigned_lit N RN) in Ha.
  destruct Ha as [Ha|Ha]; [exact (HS a Ha) | exact (HD a Ha)].
Qed.

