(* ---- the footprint form (RECIPE.md step 1 (a working note, not in this delivery)) ----
   The function reads and writes no memory: it computes from a0 alone. So the footprint twin needs NO rng premise,
   and the run is an ExecF.evtF under EVERY footprint RNG. kind_of_link1_contract_of_F gives the old statement back
   with ExecF.RNG_all. *)
Definition kind_of_link1_contract_F : Prop :=
  forall (RNG : ExecF.footprint)
         (ra sp gp tp t0 t1 t2 s0 s1 a0 a1 a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6 : word)
         (F : bvmap 5 word) (fc : bv 32) (m : word -> option byte),
    ExecF.evtF rsegs RNG
      (fun ms' => exists a1' : word,
         ms' = MS (mkR ra sp gp tp t0 t1 t2 s0 s1 (Z_to_bv 64 (KL1 (bv_signed a0)))
                       a1' a2 a3 a4 a5 a6 a7 s2 s3 s4 s5 s6 s7 s8 s9 s10 s11 t3 t4 t5 t6)
                  F (ret_pc ra) fc None m (seg_rom rsegs))
