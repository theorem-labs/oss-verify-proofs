Definition rbyte (row : list byte) (k : nat) : byte := nth k row (Z_to_bv 8 0).
Definition rval (row : list byte) (k : nat) : Z := bv_unsigned (rbyte row k).

Definition u32le (row : list byte) (k : nat) : Z :=
  rval row k + 256 * rval row (k + 1) + 65536 * rval row (k + 2) + 16777216 * rval row (k + 3).

Definition s32 (u : Z) : Z := if u <? 2^31 then u else u - 2^32.

Definition box_org (row : list byte) : Z := rval row 288.
Definition box_ic (row : list byte) : Z := s32 (u32le row 16).
Definition box_oc (row : list byte) : Z := s32 (u32le row 20).
Definition box_sel (row : list byte) : byte := rbyte row 252.
Definition box_st (row : list byte) : byte := rbyte row 253.
Definition box_lay (row : list byte) : Z := rval row 290.
Definition box_cfg (row : list byte) : list byte := firstn 32 (skipn 24 row).
Definition box_tail (row : list byte) : list byte := firstn 11 (skipn 254 row).

Definition gram_ok (row : list byte) : bool :=
  (0 <=? box_ic row) && (0 <=? box_oc row) && (box_ic row mod 4 =? 0) && (box_oc row mod 4 =? 0) &&
  (box_ic row / 4 + box_oc row / 4 <=? 12).

Definition decl_ok (row : list byte) : bool := (box_org row =? 0) || gram_ok row.

Definition slot_bytes (lay a b : Z) : list byte :=
  if lay =? 1
  then repeat (Z_to_bv 8 1) (Z.to_nat b) ++ repeat (Z_to_bv 8 0) (Z.to_nat a) ++ repeat (Z_to_bv 8 3) (Z.to_nat (12 - a - b))
  else repeat (Z_to_bv 8 2) (Z.to_nat a) ++ repeat (Z_to_bv 8 1) (Z.to_nat b) ++ repeat (Z_to_bv 8 3) (Z.to_nat (12 - a - b)).

Definition gram_head (row : list byte) : list byte :=
  [Z_to_bv 8 1; Z_to_bv 8 3; Z_to_bv 8 0; Z_to_bv 8 16; box_sel row; Z_to_bv 8 0; Z_to_bv 8 0; box_st row].

Definition gram_pre (row : list byte) : list byte :=
  gram_head row ++ slot_bytes (box_lay row) (box_ic row / 4) (box_oc row / 4) ++ box_tail row.

Definition check_byte (bs : list byte) : byte := Z_to_bv 8 ((256 - psum bs 31 mod 256) mod 256).

Definition gram (row : list byte) : list byte := gram_pre row ++ [check_byte (gram_pre row)].

Definition decl (row : list byte) : list byte := if box_org row =? 0 then box_cfg row else gram row.

