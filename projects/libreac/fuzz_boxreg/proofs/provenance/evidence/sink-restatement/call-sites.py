#!/usr/bin/env python3
"""By-use call-site list of the FILE-sink names in fuzz_boxreg.

Usage, from the repository root:  call-sites.py REF > CALL-SITES.md
For each name, `git grep -n -w NAME REF -- 'proofs/libreac/fuzz_boxreg/*.v'` gives every line of a .v file of the unit
that names it. Each line is listed with the declaration it sits in: the nearest line at or above it that starts a
vernacular declaration, by the regex DECL below. A line whose every occurrence of the name is inside a comment is
marked `comment` (comments are lexed with nesting; strings are skipped); it is not a use.
"""
import re
import subprocess
import sys

UNIT = "proofs/libreac/fuzz_boxreg"
NAMES = ["src0_sink", "sk_file", "sink_at", "fopen_spec", "unlink_spec", "fwrite_spec", "fclose_spec", "stdio_env",
         "env_addr", "env_ivl"]
DECL = re.compile(r"^\s*(?:#\[[^\]]*\]\s*)?(?:(?:Local|Global|Program|Polymorphic|Monomorphic)\s+)*"
                  r"(Lemma|Theorem|Corollary|Fact|Remark|Proposition|Example|Definition|Fixpoint|CoFixpoint|Instance|"
                  r"Record|Structure|Class|Inductive|CoInductive|Ltac|Let|Notation|Existing Instance|Hint)\b\s*([^\s:({]*)")


def git(*a):
    return subprocess.run(["git", *a], check=True, capture_output=True, text=True).stdout


def code_mask(text):
    """For each character, True when it is code (outside comments and strings)."""
    mask = [True] * len(text)
    i, n, depth = 0, len(text), 0
    while i < n:
        if depth == 0 and text[i] == '"':
            j = i + 1
            while j < n:
                if text[j] == '"':
                    if j + 1 < n and text[j + 1] == '"':
                        j += 2
                        continue
                    break
                j += 1
            for k in range(i, min(j + 1, n)):
                mask[k] = False
            i = j + 1
            continue
        if text.startswith("(*", i):
            depth += 1
            mask[i] = mask[i + 1] = False
            i += 2
            continue
        if depth and text.startswith("*)", i):
            depth -= 1
            mask[i] = mask[i + 1] = False
            i += 2
            continue
        if depth:
            mask[i] = False
        i += 1
    return mask


def main():
    ref = sys.argv[1]
    sha = git("rev-parse", ref).strip()
    hits = {}
    for name in NAMES:
        out = subprocess.run(["git", "grep", "-n", "-w", "-e", name, sha, "--", f"{UNIT}/*.v"], capture_output=True,
                             text=True).stdout
        for line in out.splitlines():
            _, path, ln, _ = line.split(":", 3)
            hits.setdefault(path, []).append((int(ln), name))
    rows = []
    for path in sorted(hits):
        text = git("show", f"{sha}:{path}")
        lines = text.split("\n")
        mask = code_mask(text)
        starts = [0]
        for l in lines:
            starts.append(starts[-1] + len(l) + 1)
        decl_at = []
        cur = ("(before any declaration)", "")
        for k, l in enumerate(lines):
            m = DECL.match(l)
            if m and mask[starts[k] + len(l) - len(l.lstrip())]:
                cur = (m.group(1), m.group(2).rstrip(".") or "-")
            decl_at.append(cur)
        for ln, name in sorted(hits[path]):
            l = lines[ln - 1]
            code = any(mask[starts[ln - 1] + m.start()] for m in re.finditer(rf"(?<![A-Za-z0-9_']){re.escape(name)}(?![A-Za-z0-9_'])", l))
            kind, decl = decl_at[ln - 1]
            rows.append((name, path[len(UNIT) + 1:], ln, kind, decl, "use" if code else "comment"))
    print("# By-use call sites of the FILE-sink names (fuzz_boxreg)")
    print()
    print(f"Generated by `provenance/evidence/sink-restatement/call-sites.py {ref}` at commit {sha}.")
    print(f"Each row is a line of a .v file under {UNIT} that `git grep -n -w` finds for the name; paths are relative")
    print("to the unit. `declaration` is the vernacular declaration the line sits in. `comment` marks a line where the")
    print("name occurs only inside a comment.")
    print()
    print("| name | lines (uses / comment only) | files |")
    print("|---|---|---|")
    for name in NAMES:
        r = [x for x in rows if x[0] == name]
        print(f"| {name} | {len(r)} ({sum(1 for x in r if x[5] == 'use')} / {sum(1 for x in r if x[5] == 'comment')}) | "
              f"{len(set(x[1] for x in r))} |")
    print()
    for name in NAMES:
        r = [x for x in rows if x[0] == name]
        print(f"## {name}")
        print()
        if not r:
            print("No line names it.")
            print()
            continue
        print("| file:line | declaration | kind |")
        print("|---|---|---|")
        for _, p, ln, kind, decl, c in sorted(r, key=lambda x: (x[1], x[2])):
            print(f"| {p}:{ln} | {f'{kind} {decl}'.strip()} | {c} |")
        print()


if __name__ == "__main__":
    main()
