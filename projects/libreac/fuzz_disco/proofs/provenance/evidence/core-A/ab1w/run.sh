#!/usr/bin/env bash
# run.sh REPO TARGET_PIN DONOR_PIN OUTDIR
#
# Re-derives libreac/fuzz_disco's lib/A/AB1w.v in the two recorded steps and compares every output byte for byte.
#   REPO        a git checkout of the proof repository (a sparse checkout is enough: files are read with git show)
#   TARGET_PIN  the released fuzz_disco.asan image (sha256 5e39150dd810...)
#   DONOR_PIN   the released cgif_file_fuzzer.asan image (sha256 7093581aab04...)
#   OUTDIR      a new or empty directory for the outputs
# Step 1: gen_symtab.py writes AB1w.v as it stood in the commit before the function-row regeneration (step 2), and the
#         table AB1w.tsv. That AB1w.v was never shipped: step 1 regenerates it, and run.sh checks it by its sha256.
# Step 2: gen_b1w_own.py rewrites the function-entry rows from the target's own symbols: the shipped AB1w.v and the
#         table AB1w.own.tsv. Its MUSL_LO / MUSL_HI arguments are the recorded ones (MUSL_LO = sysconf, the first musl
#         function of the image).
# Exit 0 only if all four outputs equal their references.
set -euo pipefail
[ $# -eq 4 ] || { echo "usage: run.sh REPO TARGET_PIN DONOR_PIN OUTDIR" >&2; exit 2; }
REPO=$1 PIN=$2 DONOR=$3 OUT=$4
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
TWIN=$HERE/../twin/fuzz_disco.asan.twin.txt
DONOR_SYMS=$HERE/../inputs/cgif_file_fuzzer.asan.syms.txt
AB1W=proofs/libreac/fuzz_disco/lib/A/AB1w.v
export PYTHONDONTWRITEBYTECODE=1
mkdir -p "$OUT"
sha256sum "$PIN" "$DONOR"

git -C "$REPO" show "HEAD:proofs/cgif/cgif_file_fuzzer/lib/A/AB1w.v" > "$OUT/donor.AB1w.v"
# sha256 of lib/A/AB1w.v in the commit before the function-row regeneration (bc84f77d88d2^, git blob a6e91aad8a1c);
# not shipped, regenerated by step 1
STEP1_SHA256=d7d29835c1fde308694a42f68021e76960b96f24bac5dfb2f1aa474e05b00efe
git -C "$REPO" show "HEAD:$AB1W" > "$OUT/ref.shipped.AB1w.v"

nice python3 "$HERE/gen_symtab.py" "$OUT/donor.AB1w.v" "$HERE/inputs/AB1w.in.v" "$DONOR" "$PIN" "$TWIN" \
    "$OUT/AB1w.step1.v" "$OUT/AB1w.tsv" "$DONOR_SYMS"
nice python3 "$HERE/gen_b1w_own.py" "$TWIN" "$OUT/AB1w.step1.v" "$OUT/AB1w.v" "$OUT/AB1w.own.tsv" \
    "$OUT/AB1w.step1.v" 0x8f310 0x9f35c

rc=0
check() {
    if cmp "$1" "$2"; then echo "cmp OK   $3"; else echo "cmp FAIL $3"; rc=1; fi
}
got=$(sha256sum < "$OUT/AB1w.step1.v" | cut -d' ' -f1)
if [ "$got" = "$STEP1_SHA256" ]; then echo "sha256 OK   step-1 OUT    = $STEP1_SHA256"
else echo "sha256 FAIL step-1 OUT    = $got, expected $STEP1_SHA256"; rc=1; fi
check "$OUT/AB1w.tsv" "$HERE/AB1w.tsv" "step-1 REPORT = ab1w/AB1w.tsv"
check "$OUT/AB1w.v" "$OUT/ref.shipped.AB1w.v" "step-2 OUT    = HEAD:$AB1W"
check "$OUT/AB1w.own.tsv" "$HERE/AB1w.own.tsv" "step-2 REPORT = ab1w/AB1w.own.tsv"
exit $rc
