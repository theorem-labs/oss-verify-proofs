#!/usr/bin/env python3
"""mk_manifest.py [DIR] -- writes DIR/MANIFEST (default: this script's directory) for the evidence slice startup-Y.

Each line is `<path relative to DIR> <kind> <sha256> <role>`. The rows come from DIR/ROWS.tsv and from every
DIR/*/ROWS.tsv (tab-separated: path relative to DIR, kind, role), and each subdirectory's ROWS.tsv is itself named
(kind input); the sha256 is computed here over the file's bytes.
Refuses (exit 1) when a file under DIR has no row, when a row names a file that does not exist, when a kind is not
one of script / input / table / gate, or when a path appears twice. MANIFEST itself is not named."""
import glob, hashlib, os, sys

KINDS = ('script', 'input', 'table', 'gate')
HEAD = """# evidence/startup-Y: start-up certificate data of image B (fuzz_disco.asan-ubsan), lib/Reusable
# One line per file: path (relative to this directory), kind, sha256, role.
# kind: script = script of record; table = per-value table; gate = gate record; input = input a script reads.
# run.sh re-derives every generated file below and compares it byte for byte (each subdirectory's run.sh).
# Gate records on the image B pin (cell, code-pointer, image-overlap, start-up walker) are in evidence/gates-Y.
# Re-derive: YB03 / YB01 = collector/ (hsform js / hs on the collector extract, then to_disco); YB05 = yb05/;
# YB12 = yb12/ (tool output + the hand TFIB_TEXT_N); YD2j / YD1k / YD2i = ad2/; YE3i = ye3i/; YCej trace lists = ycej/;
# YB1v = yb1v/.
# Not produced by any script (values checked by evidence/gates-Y, or by the kernel inside the file): YB13 (its numerals
# are checked by vm_compute against the image segments in the file), YB1q (window decode checked by vm_compute), YF0l;
# YD1g (relocated, page index 1534 = 0x5fe000 >> 12 set by hand); YB1h (segment geometry proved by reflexivity / lia
# in the file); YB1m and its split files (certificate checked by vm_cast in the kernel); YB1j (donor copy).
# Generated by mk_manifest.py from the ROWS.tsv files; never edited by hand.
"""


def main():
    root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__)))
    rows, seen, problems = [], set(), []
    for rt in [os.path.join(root, 'ROWS.tsv')] + sorted(glob.glob(os.path.join(root, '*', 'ROWS.tsv'))):
        if not os.path.exists(rt):
            continue
        for n, line in enumerate(open(rt).read().splitlines(), 1):
            if not line.strip() or line.startswith('#'):
                continue
            path, kind, role = line.split('\t', 2)
            where = '%s:%d' % (os.path.relpath(rt, root), n)
            if kind not in KINDS:
                problems.append('%s: kind %r' % (where, kind))
            if path in seen:
                problems.append('%s: %s named twice' % (where, path))
            seen.add(path)
            full = os.path.join(root, path)
            if not os.path.isfile(full):
                problems.append('%s: %s does not exist' % (where, path))
                continue
            rows.append((path, kind, hashlib.sha256(open(full, 'rb').read()).hexdigest(), role.strip()))
        rel = os.path.relpath(rt, root)
        if rel != 'ROWS.tsv' and rel not in seen:
            seen.add(rel)
            rows.append((rel, 'input', hashlib.sha256(open(rt, 'rb').read()).hexdigest(),
                         'The rows of %s/ that mk_manifest.py reads (path, kind, role).' % os.path.dirname(rel)))
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d != '__pycache__']
        for f in fn:
            rel = os.path.relpath(os.path.join(dp, f), root)
            if rel != 'MANIFEST' and rel not in seen:
                problems.append('%s: no row in any ROWS.tsv' % rel)
    if problems:
        sys.exit('mk_manifest: REFUSED\n' + '\n'.join(problems))
    with open(os.path.join(root, 'MANIFEST'), 'w') as f:
        f.write(HEAD)
        for r in sorted(rows):
            f.write('%s %s %s %s\n' % r)
    print('mk_manifest: wrote %s (%d entries)' % (os.path.join(root, 'MANIFEST'), len(rows)))


main()
