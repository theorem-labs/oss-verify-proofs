def loads(b):
    phoff = struct.unpack_from("<Q", b, 0x20)[0]
    es, n = struct.unpack_from("<HH", b, 0x36)
    out = []
    for k in range(n):
        t, _, off, va, _, fs, ms, _ = struct.unpack_from("<IIQQQQQQ", b, phoff + k * es)
        if t == 1:
            out.append((va, fs, ms, off))
    return out


class Img:
    def __init__(self, path):
        self.b = open(path, "rb").read()
        self.segs = loads(self.b)
        self.top = max(va + ms for va, fs, ms, off in self.segs)

    def word(self, a, n=4):
        for va, fs, ms, off in self.segs:
            if va <= a and a + n <= va + fs:
                return int.from_bytes(self.b[off + a - va: off + a - va + n], "little")
        return None

    def string_at(self, a):
        """(text, offset) of the printable NUL-terminated string that holds address a, or None."""
        for va, fs, ms, off in self.segs:
            if va <= a < va + fs:
                b, i = self.b, off + a - va
                ok = lambda c: c in (9, 10) or 32 <= c < 127
                if not ok(b[i]) and b[i] != 0:
                    return None
                s = i
                while s > off and ok(b[s - 1]):
                    s -= 1
                e = i
                while e < off + fs and ok(b[e]):
                    e += 1
                if e - s < 2 or e >= off + fs or b[e] != 0 or (s > off and b[s - 1] != 0):
                    return None
                return b[s:e].decode(), i - s
        return None


def norm(n):
    return re.sub(r"[^A-Za-z0-9_]", "_", n)


class Twin:
    def __init__(self, path):
        e = self.elf = ELFFile(open(path, "rb"))
        self.syms = [(s["st_value"], s["st_size"], s.name, s["st_info"]["type"])
                     for s in e.get_section_by_name(".symtab").iter_symbols()]
        self.funcs = sorted({(a, s, n) for a, s, n, t in self.syms if t == "STT_FUNC"})
        self.fstarts = sorted({a for a, s, n in self.funcs})
        self.fset = set(self.fstarts)
        self.copies = collections.defaultdict(list)
        for a, s, n in self.funcs:
            self.copies[norm(n)].append((a, s))
        self.sec = {s.name: (s["sh_addr"], s["sh_size"]) for s in e.iter_sections()}

    def start(self, name):
        return min((a for a, s in self.copies.get(norm(name), [])), default=None)

    def next_start(self, a):
        import bisect
        i = bisect.bisect_right(self.fstarts, a)
        return self.fstarts[i] if i < len(self.fstarts) else None

    def name_cands(self, name):
        if name in self.copies:
            return self.copies[name]
        m = re.match(r"(.*)_libc$", name)
        if m and m.group(1) in self.copies:
            return self.copies[m.group(1)]
        m = re.match(r"(.*)_(\d+)$", name)
        if m and m.group(1) in self.copies:
            return self.copies[m.group(1)]
        return []


def ival(s):
    try:
        return int(s, 0)
    except (TypeError, ValueError):
        return None


def is_call_before(img, ra):
    """The 4-byte word before ra is jal ra, X or jalr ra, X(rs)."""
    w = img.word(ra - 4)
    if w is None:
        return False
    op, rd = w & 0x7F, (w >> 7) & 0x1F
    return rd == 1 and op in (0x6F, 0x67)


