    for k in RULES:
        if cnt[k]:
            print("%-17s %6d" % (k, cnt[k]), file=sys.stderr)
    for r in untriaged[:40]:
        print("UNTRIAGED\t" + "\t".join(r[:12]), file=sys.stderr)
    sys.exit(1 if untriaged or defects else 0)


