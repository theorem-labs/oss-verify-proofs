def flag_words(v):
    """v as a sum of mmap flag bits, or None."""
    names, rest = [], v
    for bit in sorted(MAP_FLAGS, reverse=True):
        if rest & bit:
            names.append(MAP_FLAGS[bit])
            rest &= ~bit
    return " | ".join(names) if rest == 0 and names else None


def refine_inrange(d, dv, sv, c):
    """A value the checker reads as a non-address but which lies inside the image: say what it is, or None."""
    f, l = d["dst_file"], int(d["dst_line"] or 0)
    line = c["flines"](f)[l - 1] if l else ""
    if re.search(r"\bchange\b", line) and re.search(r"with \(?%d\b" % dv, line):
        return "NON-ADDRESS", "a quotient / sum that the kernel's `change ... with %d` checks on this line" % dv
    if "decode_any" in line:
        return "NON-ADDRESS", "the pc-relative operand of a decoded instruction (decode_any, checked by the kernel)"
    if re.search(r"exists \(%d \+" % dv, line):
        return "NON-ADDRESS", "a quotient in a mod / divide step (exists (%d + ...), checked by lia)" % dv
    if re.search(r"\breplace\b", line) and re.search(r"with \(\(%d \+" % dv, line):
        return "NON-ADDRESS", "a quotient in a `replace ... with ((%d + ...) * 8)` step, checked by zlia" % dv
    if re.search(r"TFIB_TEXT_N|startup_plan_tfib_ranges", d["sentence"]) and dv == c["text_words"]:
        return "NON-ADDRESS", "the number of 4-byte words of .text (measured: %d), a nat count" % c["text_words"]
    if "allocator operation argument" in d["dst_res"] or "a byte count" in d["dst_res"]:
        return "NON-ADDRESS", d["dst_res"][:120]
    if "errno_addr B1" in "\n".join(c["flines"](f)) and dv == 201312:
        return "HAND", ("201312 = errno_addr B1 + 164 (the plain image's errno block), which YN06.v:511 `change "
                        "(errno_addr B1) with (201312 + -164)` checks in the kernel")
    imgs = c["imgs"].get(d["image"])
    if imgs and sv is not None:
        ds, cs = imgs[0].string_at(dv), imgs[1].string_at(sv)
        if ds and cs and ds == cs:
            return "HAND", ("a pointer into the string %r at offset %d in both images (port %#x, cgif %#x): moved "
                            "with its string (measured on both pins)" % (ds[0][:40], ds[1], dv, sv))
    tw = c["twin"]
    cov = sorted((s, a, n) for a, s, n, t in tw.syms if a <= dv < a + s and n and not n.startswith("$"))
    if d["image"] == "B" and cov and re.search(r"kn_read|\bZC\b", line):
        s, a, n = cov[0]
        return "HAND", "%s+%d (twin .symtab), read by kn_read / ZC in the Qed proof" % (n, dv - a)
    return None


def hand_rule(d, sent, dv, sv, c):
    """Rows triaged one by one: each returns ('HAND' or 'MODEL-CONST', detail) only when its measurement agrees."""
    f, l = d["dst_file"].replace("Reusable/", ""), int(d["dst_line"] or 0)
    line = c["flines"](d["dst_file"])[l - 1] if l else ""
    twin, pin = c["twin"], c["pin"]

    def named(v):
        return ", ".join(n for a, s, n, t in twin.syms if a == v and n and not n.startswith("$") and s > 0)

    if d["kind"] == "ident":
        return "HAND", "a hex-looking run inside an identifier (a mangled C++ name on this line), not a numeral"
    if d["verdict"] == "SAME-VALUE-DIFFERENT-OBJECT" and dv == sv:
        fw = flag_words(dv)
        if fw and f in ("YA01.v", "YA09.v"):
            return "MODEL-CONST", "mmap flags word %#x = %s (an ABI constant), equal to the donor's" % (dv, fw)
        if dv == 0x20112D and "KRange (EVar V_HW) 0x112D 0x20112D" in line:
            return "MODEL-CONST", "the value range 0x112D .. 0x20112D of the hardware word V_HW, equal to the donor's"
        if f == "YE7d.v" and "0 <= a < 0x148680" in line and c["rom_top"] < 0x148680:
            return "MODEL-CONST", ("a loose upper bound on read-only image addresses, proved for image B (its "
                                   "read-only PT_LOADs end at %#x)" % c["rom_top"])
    if f == "YCbj.v" and re.search(r"pa_relro_(lo|hi) :=", line):
        lo, hi = twin.sec[".data.rel.ro"][0], sum(twin.sec[".got"])
        rl, rh = c["relro"]
        if dv in (lo, hi) and rl <= lo and hi <= rh:
            return "HAND", ("RELRO range bound: .data.rel.ro starts %#x, .got ends %#x (twin section headers), inside "
                            "PT_GNU_RELRO [%#x, %#x) of the pin" % (lo, hi, rl, rh))
    if f == "YCfn.v":
        lf = twin.start("LLVMFuzzerTestOneInput")
        if "A_LLVMF : Z :=" in line and dv == lf:
            return "HAND", "LLVMFuzzerTestOneInput starts at %#x (twin .symtab)" % lf
        if "RA_LLVMF : Z :=" in line and is_call_before(pin, dv):
            w = pin.word(dv - 4)
            tgt = dv - 4 + ((((w >> 31) & 1) << 20 | ((w >> 12) & 0xFF) << 12 | ((w >> 20) & 1) << 11 |
                             ((w >> 21) & 0x3FF) << 1) - (((w >> 31) & 1) << 21))
            if tgt == lf:
                return "HAND", "return pc of the jal ra at %#x to LLVMFuzzerTestOneInput (pin word %#x)" % (dv - 4, w)
        if "A_EMPTY : Z :=" in line and named(dv) == "oft_aligned_copy.empty":
            return "HAND", ("the data pointer target_run passes for an empty input: oft_aligned_copy.empty (twin "
                            ".symtab, 32 bytes); target_run forms it as auipc/addi -> target_run.initialized "
                            "0x5dbad0, then +16")
    jt = c["jt"]
    if dv in (jt, jt + 4, c["jtval"]) and f in ("YD1x.v", "YFih.v", "YFk2.v") and c["jt_ok"]:
        return "HAND", ("the jump-table cell %#x of __sanitizer::VSNPrintf (the checker's own reading) and its 4-byte "
                        "content %#x (pin word; YFih R_jt := lit4 %#x %#x); cgif's cell is 0x20b40" %
                        (jt, c["jtval"], jt, c["jtval"]))
    if f == "YD2k.v" and dv is not None and dv >= 0x10000 and named(dv):
        return "HAND", "%s (twin .symtab), read by kn_read / ZC in the Qed proof under the matching name" % named(dv)
    if f == "YE23.v" and sent.endswith("XW2") and dv in c["x2w"]:
        return "HAND", "a bound of the shadow windows XW2, equal to YE37's x2_shw windows (measured), see X2-CONST"
    if f == "YE23.v" and re.search(r"ex_(consts|regions)1?$", sent) and dv == 0xA0270:
        fl, fs = twin.sec[".fini_array"]
        if fl <= dv < fl + fs and pin.word(dv, 8) == twin.start("__do_fini"):
            return "HAND", ("a .fini_array cell [%#x, %#x): the pin's word at %#x is %#x = __do_fini" %
                            (fl, fl + fs, dv, pin.word(dv, 8)))
    if re.match(r"(YE2[uvw]|YE35)\.v", f) and re.search(r"SH_(LO|HI)", line):
        m = re.search(r"SH_LO : Z := (0x[0-9a-f]+)\.\s+Definition SH_HI : Z := (0x[0-9a-f]+)\.", line)
        if m:
            lo, hi = (int(x, 16) for x in m.groups())
            a0, a1 = (lo - 0x7FFF8000) * 8, (hi - 0x7FFF8000) * 8
            if dv in (lo, hi) and not any(c["shadow"].get(g, 0) for g in range(a0, a1, 8)):
                return "HAND", ("zero-shadow window [%#x, %#x) = the shadow of [%#x, %#x) in .rodata: the start-up "
                                "shadow is 0 there (no asan_globals descriptor covers it; measured); the Qed proof "
                                "checks the window inside its zero-shadow hypothesis (vm_compute, lia)" % (lo, hi, a0, a1))
    if f in ("YF0s.v", "YF0u.v"):
        if dv in c["yf0m_sym"]:
            return "HAND", ("= YF0m's Tfib_const_sym cell %s (looked up in the kernel: tfib_const_lookup_sym ... "
                            "vm_compute), which G4 checks" % c["yf0m_sym"][dv])
        if dv == c["img_top"] // 8 and ("785408" in line or "IMG_TOP / 8" in line or "TFIB_IMG_END" in line):
            return "HAND", "IMG_TOP / 8 = %#x / 8 = 785408, which `change` checks in the kernel" % c["img_top"]
    if f == "YFet.v" and dv == 0xA618A:
        st = [(a, s) for a, s, n, t in twin.syms if n == "_ZN6__asanL8instanceE"]
        if st and st[0][0] <= dv < st[0][0] + st[0][1]:
            return "HAND", ("__asan::instance + %#x (twin: instance at %#x, %d bytes); the Qed proof's lia step "
                            "checks it against TFIB_INST + o_quar" % (dv - st[0][0], st[0][0], st[0][1]))
    if f in ("YFjm.v", "YFk1.v") and dv == 0x800B3A40:
        bt = [a for a, s, n, t in twin.syms if n == "builtin_tls"]
        if bt and (dv - 0x7FFF8000) * 8 == bt[0] + 0xEB8:
            return "HAND", ("shadow(builtin_tls + 0xeb8) of image B (twin builtin_tls %#x); cgif's 0x800b3400 is "
                            "shadow(its builtin_tls 0x5d9148 + 0xeb8): the same relation; a bound in a Lemma "
                            "statement the kernel proves" % bt[0])
    if f == "YH03.v" and "src0_E_set_thread_area" in line:
        st = c["twinp"].start("__set_thread_area")
        if st is not None and c["twinp"].next_start(st) == dv:
            return "HAND", ("end of __set_thread_area (size 0 at %#x) = the next function's start %#x in the plain "
                            "twin" % (st, dv))
    if f == "YL0g.v" and "LIB_STACK : Z := 65536" in line:
        return "HAND", "a stack size in bytes (LIB_STACK; LIB_STACK_RGB 61440 below it), not an address"
    if f == "YL0k.v" and "src0_R" in line:
        tp = c["twinp"]
        lo, got_hi = tp.sec[".init_array"][0], sum(tp.sec[".got"])
        slot = c["pinp"].word(0x1FEE8, 8)
        guard = [s[0] for s in tp.syms if s[2] == "__stack_chk_guard"]
        if dv in (lo, 0x1FEF0) and got_hi == 0x1FF00 and lo + 208 == 0x1FEE8 and guard and slot == guard[0]:
            return "HAND", ("plain image RELRO bytes [%#x, %#x) (.init_array start .. .got end, plain twin) less the "
                            ".got slot 0x1fee8, which holds &__stack_chk_guard %#x" % (lo, got_hi, slot))
    if f in ("YN0c.v", "YN0e.v", "YN0g.v", "YN19.v") and d["image"] == "P":
        lo, top = c["plain_lo"], c["plain_top"]
        s3 = c["pinp"].segs[2]
        if dv in (lo, top):
            return "HAND", "the plain image extent [%#x, %#x) (plain pin PT_LOADs, page-rounded)" % (lo, top)
        if dv == s3[0] + s3[2]:
            return "HAND", "the end of the plain pin's PT_LOAD 3, %#x (its RW data starts on the next page)" % dv
        s1 = c["pinp"].segs[0]
        if f == "YN19.v" and dv == ((s1[0] + s1[2] + 0xFFF) & ~0xFFF) - s1[0]:
            return "HAND", ("the page span of the plain pin's PT_LOAD 1 from 0x10000 (covered_sound B 0x10000 0x2000, "
                            "vm_compute)")
    if f == "YB1v.v" and "tfibmusl_text_count" in line:
        st = int(re.search(r"tfibmusl_text_start : Z := (0x[0-9a-f]+)", "\n".join(c["flines"](d["dst_file"]))).group(1), 16)
        te = sum(twin.sec[".text"])
        if dv == (te - st) // 4 and (te - st) % 4 == 0:
            return "HAND", ("the 4-byte words from tfibmusl_text_start %#x to the end of .text %#x (= PT_LOAD 2's end): "
                            "%d; the checker's 16105 applies cgif's span to tls.hi - 8, which in cgif runs 12 bytes "
                            "past its own .text end 0x9cc70 (build_table decodes loaded words only)" % (st, te, dv))
    if f == "YD2f.v" and "SOBUF_HI" in line:
        b = [(a, s) for a, s, n, t in twin.syms if n == "buf" and a == 0x5FCB18]
        if b and dv == b[0][0] + 0x410 and "SOBUF_LO : Z := 0x5fcb18." in line:
            return "HAND", ("SOBUF_LO = buf %#x (twin, %d bytes, stdout's buffer), SOBUF_HI = SOBUF_LO + 0x410, the "
                            "same span as cgif's 0x5f9918 .. 0x5f9d28" % (b[0][0], b[0][1]))
    return None



