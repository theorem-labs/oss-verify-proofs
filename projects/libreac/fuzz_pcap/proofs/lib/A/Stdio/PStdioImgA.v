Definition PFMEMOPEN    : Z := (symaddr Symbols.Asan.s_fmemopen).   (* fmemopen+0x0 *)
Definition FM_MALLOC_RA : Z := (symaddr (Symbols.Asan.s_fmemopen + 0x9c)%Z).   (* fmemopen+0x9c: the return of its malloc call (jal at fmemopen+0x98) *)
