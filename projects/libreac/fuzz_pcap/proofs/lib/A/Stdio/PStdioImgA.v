(* PStdioImgA: the per-image entry and return pcs of pcap's musl stdio layer, for the ASAN image.    *)
(*                                                                                                    *)
(* THIS FILE HOLDS NUMERALS ONLY - no statement, no lemma, no Require of a statement file - so that  *)
(* the stdio contract files stay image-free by construction and lib/B never has to Require anything *)
(* image-bearing (ruling of 02:27Z). Every stdio contract takes these pcs as PARAMETERS; each         *)
(* image's walk instantiates them from its own image file (this one for asan, lib/B/Stdio/PStdioImgB.v *)
(* for asan-ubsan, which is a Theorem Labs lane's).                                                   *)
(*                                                                                                    *)
(* THIS IS THE SINGLE HOME of pcap's asan stdio pcs. A walk that needs one REQUIRES this file; it never *)
(* re-declares the pc locally. A local Definition with the same name SHADOWS the imported one without  *)
(* any error, and that is exactly how an asan-ubsan walk ended up calling the ASAN fmemopen entry on   *)
(* 2026-10-28 (02:44Z). A new per-image stdio pc is added HERE, derived the same way.                 *)
(*                                                                                                    *)
(* THE IMAGE: the pin of record,                                                                      *)
(* the pinned fuzz_pcap.asan image,                                                                   *)
(*   sha256 b7a91d9b1fb0017df0462bf382b3211837851bf801e792673b1cee0797cdca2a (stripped, 571,416 B).  *)
(* Each pc is derived by SYMBOL + OFFSET from the pin's UNSTRIPPED TWIN,                             *)
(*   the pinned fuzz_pcap.asan image's unstripped twin,                                               *)
(*   sha256 36da3052c383096eed46abd71490e47af9600c030bdf511c4e83d48924e24291,                         *)
(* and the twin was checked against the pin first (pyelftools, 02:3xZ): the entry point               *)
(* and the text segment (0x2ff70, flags R+X) and both data segments (0x99298, 0x9b528) are           *)
(* BYTE-IDENTICAL; the first read-only segment (0x10000) differs in exactly 24 bytes, all of them    *)
(* either the ELF header's section-table fields (0x10028-0x1003e, which strip rewrites) or the       *)
(* 20-byte .note.gnu.build-id (0x102b8-0x102cb). No pc below and no byte any stdio walk reads lies in *)
(* either region.                                                                                     *)
(*                                                                                                    *)
(* HOW EACH pc WAS DERIVED (symtab STT_FUNC entries of the twin; the call site by decoding fmemopen's  *)
(* own bytes with capstone and resolving each jal as pc + immediate):                                *)
(*   fmemopen   = the symbol fmemopen                      (STT_FUNC, size 464)                       *)
(*   fread      = the symbol fread                         (STT_FUNC, size 316)                       *)
(*   __toread   = the symbol __toread                      (STT_FUNC, size 148)                       *)
(*   mread      = the symbol mread                         (STT_FUNC, size 212)                       *)
(*   the malloc return = fmemopen + 0x9c: the FIRST jal to the malloc trampoline 0x52bd8 is at        *)
(*     fmemopen + 0x98, and it returns to fmemopen + 0x9c (a second jal to it, at fmemopen + 0xa8,    *)
(*     allocates a buffer only when the caller passes buf = NULL, which pcap's path never does).      *)
(* ---------------------------------------------------------------------------------------------- *)
