#!/usr/bin/env python3
"""gen_ro_redzones.py -- generate lib/{A,B}/Rt/RoRedzones.v of libreac/fuzz_identity from the images.

What it writes, per image: `ident_ro_redzones`, the redzone bytes of every READ-ONLY registered ASan global
(a descriptor of the asan_globals section whose object lies in .rodata: the range [beg + size,
beg + size_with_redzone)), as constant cells in the rodata_chk shape of cgif's lib/A/AE2y.v
((region lo, length, [(offset, width, value)])), each value the image's own byte; and the lemma
`ident_ro_redzones_img`, which compares every cell with the image's segments by vm_compute.

Inputs (all four REQUIRED on the command line; no host path is built in): the unstripped twins of the pinned ELFs
(both checked to agree with the pins byte for byte) and the pinned ELFs, for the re-read of every byte:
  --img-a  unstripped fuzz_identity.asan        sha256 c954b804786c...
  --img-b  unstripped fuzz_identity.asan-ubsan  sha256 baf1a4d065e0...
  --pin-a  pinned fuzz_identity.asan;  --pin-b  pinned fuzz_identity.asan-ubsan
Reading is python ELF parsing only (no host nm / objdump).

Header: the generated comment names the tool (`Generated by gen_ro_redzones.py from the image ...`) and no lane,
worker, path or author. The old version (62b4145792e5) wrote a lane name and a ruling reference there; only those
header lines differ, the code after the comment is byte-identical (test_gen_ro_redzones.py checks both).

Usage:
  gen_ro_redzones.py --img-a ELF --img-b ELF --pin-a ELF --pin-b ELF --out-a DIR --out-b DIR [--tsv-dir DIR]
  gen_ro_redzones.py --img-a ELF --img-b ELF --pin-a ELF --pin-b ELF --check-a FILE --check-b FILE [--check-body]
      control: reproduce committed files byte for byte; with --check-body compare only the code after the header
      comment (from the first `From ` line), so files made by the old header still check

Written 2026-10-30 from the cells that made the committed files on 2026-10-28 (same code path); header changed
2026-10-31.
"""
import argparse, hashlib, os, struct, sys

SHA_A, SHA_B = 'c954b804786c', 'baf1a4d065e0'


def sections(path):
    b = open(path, 'rb').read()
    shoff, = struct.unpack_from('<Q', b, 0x28)
    shes, shn, shstr = struct.unpack_from('<HHH', b, 0x3a)
    sh = [struct.unpack_from('<IIQQQQIIQQ', b, shoff + i * shes) for i in range(shn)]
    so = sh[shstr][4]
    out = {}
    for s in sh:
        e = b.index(b'\0', so + s[0])
        out[b[so + s[0]:e].decode()] = (s[3], s[4], s[5], s[2])   # addr, off, size, name index
    return b, out


def rdc(b, secs, a, n):
    """n bytes at address a, from the file image."""
    for _nm, (addr, off, size, _fl) in secs.items():
        if addr and addr <= a and a + n <= addr + size:
            return b[off + a - addr:off + a - addr + n]
    return None


def cstr(b, secs, a):
    for _nm, (addr, off, size, _fl) in secs.items():
        if addr and addr <= a < addr + size:
            o = off + a - addr
            e = b.index(b'\0', o)
            return b[o:e].decode(errors='replace')
    return '?'


def rows_of(path):
    """(idx, beg, size, size_with_redzone, rz_lo, rz_hi, name, bytes hex) per read-only global."""
    b, secs = sections(path)
    _ga, go, gs, _ = secs['asan_globals']
    ro = secs['.rodata']
    rows = []
    for k in range(gs // 64):
        beg, size, szr, name, _mod, _dyn, _loc, _odr = struct.unpack_from('<QQQQQQQQ', b, go + k * 64)
        if ro[0] <= beg < ro[0] + ro[2]:
            lo, hi = beg + size, beg + szr
            bts = rdc(b, secs, lo, hi - lo)
            rows.append((k, hex(beg), size, szr, hex(lo), hex(hi), cstr(b, secs, name),
                         bts.hex() if bts is not None else 'NOT-FILE-BACKED'))
    return rows, gs // 64


def ro_file(rows, leaf, sha, side):
    regs = []
    for r in rows:
        lo, hi = int(r[4], 16), int(r[5], 16)
        bts = bytes.fromhex(r[7])
        cells = '; '.join(f'({i}, 1%N, {bts[i]})' for i in range(hi - lo))
        regs.append(f'(0x{lo:x}, {hi - lo}, [{cells}])  (* {r[6]}: object 0x{int(r[1], 16):x} size {r[2]}, '
                    f'with redzone {r[3]} *)')
    body = ';\n'.join(regs)
    img = leaf.lower().replace('asanubsan', 'asan-ubsan')
    return f'''(* Copyright 2026 Theorem Labs *)
(* SPDX-License-Identifier: Apache-2.0 *)
(* libreac/fuzz_identity, image {side} (fuzz_identity.{img} {sha}): the redzone bytes of the READ-ONLY registered ASan globals
   (descriptors of the asan_globals section whose object lies in .rodata: [beg + size, beg + size_with_redzone)), as
   constant cells in the rodata_chk shape of cgif's lib/A/AE2y.v ((region lo, length, [(offset, width, value)])), each
   value the image's own byte. Generated by gen_ro_redzones.py from the image (python ELF parsing of the unstripped twin,
   every byte re-read from the pinned ELF: all 0x00); the check below compares every cell with the image segments by
   vm_compute. For the core's const table. *)
From OssFuzzTheorems.Proofs.libreac.fuzz_identity.lib.Reusable Require YZ00.
From Stdlib Require Import ZArith NArith List Bool.
From LinuxProcessSemantics.LinuxProcessSem Require Import BvBase RiscvSemantics MemImageType.
From OssFuzzTheorems.Proofs.libreac.fuzz_identity.lib.Reusable Require Import YK11.
From OssFuzzTheorems.libreac.fuzz_identity.images Require Import {leaf}.
Import ListNotations.
Local Set Warnings "-abstract-large-number".
Open Scope Z_scope.
Definition ident_ro_redzones : list (Z * Z * list (Z * N * Z)) :=
[ {body} ].
Definition ro_cells_img_ok (segs : list Segment) (l : list (Z * Z * list (Z * N * Z))) : bool :=
forallb (fun r => forallb (fun c => (Z.of_N (snd (fst c)) =? 1) &&
  match seg_rom segs (Z_to_bv 64 (fst (fst r) + fst (fst c))) with
  | Some b => bv_unsigned b =? snd c
  | None => false
  end) (snd r)) l.
Lemma ident_ro_redzones_img : ro_cells_img_ok {leaf}.M.loaded_segments ident_ro_redzones = true.
Proof. vm_compute. reflexivity. Qed.
'''


def pin_recheck(rows, pin_path):
    """Every redzone byte re-read from the PINNED ELF: returns the count that is not 0x00."""
    b, secs = sections(pin_path)
    bad = 0
    for r in rows:
        lo, hi = int(r[4], 16), int(r[5], 16)
        for a in range(lo, hi):
            v = rdc(b, secs, a, 1)
            if v is None or v[0] != 0:
                bad += 1
    return bad


def body_of(text):
    """The code after the header comment: from the first line that starts with `From `."""
    i = text.index('\nFrom ')
    return text[i + 1:]


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument('--img-a', required=True, help='unstripped fuzz_identity.asan (sha256 c954b804786c...)')
    ap.add_argument('--img-b', required=True, help='unstripped fuzz_identity.asan-ubsan (sha256 baf1a4d065e0...)')
    ap.add_argument('--pin-a', required=True, help='pinned fuzz_identity.asan')
    ap.add_argument('--pin-b', required=True, help='pinned fuzz_identity.asan-ubsan')
    ap.add_argument('--out-a')
    ap.add_argument('--out-b')
    ap.add_argument('--tsv-dir')
    ap.add_argument('--check-a')
    ap.add_argument('--check-b')
    ap.add_argument('--check-body', action='store_true',
                    help='compare only the code after the header comment (from the first "From " line)')
    a = ap.parse_args(argv)
    rc = 0
    for side, leaf, sha, img, pin, out, chk in [
            ('A', 'Asan', SHA_A, a.img_a, a.pin_a, a.out_a, a.check_a),
            ('B', 'AsanUbsan', SHA_B, a.img_b, a.pin_b, a.out_b, a.check_b)]:
        rows, ndesc = rows_of(img)
        nbytes = sum(int(r[5], 16) - int(r[4], 16) for r in rows)
        bad = pin_recheck(rows, pin)
        print(f'{side}: {ndesc} descriptors, {len(rows)} read-only globals, {nbytes} redzone bytes, '
              f'{bad} not 0x00 in the pinned ELF')
        if a.tsv_dir:
            tp = os.path.join(a.tsv_dir, f'ro-redzones-{side}.tsv')
            with open(tp, 'w') as f:
                f.write('idx\tbeg\tsize\tsize_with_redzone\trz_lo\trz_hi\tname\timage_bytes_hex\n')
                for r in rows:
                    f.write('\t'.join(map(str, r)) + '\n')
            print(f'{side}: wrote {tp}')
        text = ro_file(rows, leaf, sha, side)
        if out:
            op = os.path.join(out, 'RoRedzones.v')
            open(op, 'w').write(text)
            print(f'{side}: wrote {op} ({len(text)} bytes, sha256 {hashlib.sha256(text.encode()).hexdigest()[:12]})')
        if chk:
            have = open(chk).read()
            same = (body_of(have) == body_of(text)) if a.check_body else (have == text)
            print(f'{side}: CONTROL{" (body)" if a.check_body else ""} {"EQUAL" if same else "DIFFERENT"} vs {chk} '
                  f'(committed sha256 {hashlib.sha256(have.encode()).hexdigest()[:12]}, '
                  f'generated {hashlib.sha256(text.encode()).hexdigest()[:12]})')
            if not same:
                rc = 1
    return rc


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
