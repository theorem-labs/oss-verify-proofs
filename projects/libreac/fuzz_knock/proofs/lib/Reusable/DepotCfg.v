(* This is the only kernel file whose text differs between units.
   depot_has_trace = true: the image calls __asan_register_globals before main. At main the StackDepot holds one trace,
   ly_tr0, with id 1, and its nodes block (NB) and store block (SB) are mapped. Every trace unit (cgif_file_fuzzer and its
   relocations) sets true.
   depot_has_trace = false: the image registers no globals (libreac/fuzz_knock). At main the depot counter, the hash table and
   the store total are zero, no trace is stored, and NB and SB are not mapped; the first StackDepotPut after main maps them.
   A kernel constant picks its branch when it is defined: `Eval cbv delta [depot_has_trace] iota in if depot_has_trace then T
   else E` reduces only that `if`, so with true the body of the constant is T itself, the one-trace text, and with false it is
   E. depot_pick does the same inside a record field. *)
