Lemma rga_ne_test : forall E n v (b : bool), ew E n = Z_to_bv 64 v -> 0 <= v < 2 ^ 64 ->
branch_taken BC_NE (sv_denot E (SOff n 0)) (sv_denot E (SLit 0)) = b -> if b then v <> 0 else v = 0.
Proof.
intros E n v b He Hv Hb. rewrite branch_ne_U in Hb. rewrite (U_atom E n v He Hv) in Hb.
assert (H0 : U E (SLit 0) = 0) by reflexivity. rewrite H0 in Hb.
destruct b; [apply negb_true_iff in Hb; apply Z.eqb_neq in Hb; exact Hb | apply negb_false_iff in Hb; apply Z.eqb_eq in Hb; exact Hb].
Qed.
