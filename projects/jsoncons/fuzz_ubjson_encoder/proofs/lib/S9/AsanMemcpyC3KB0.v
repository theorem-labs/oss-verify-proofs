  Lemma c3_pro : forall regs (ret : word) k,
    getr regs 1 = ret -> getr regs 11 = at_ src k -> getr regs 13 = at_ dst k ->
    getr regs 12 = Z_to_bv 64 (n - k) -> getr regs 15 = Z_to_bv 64 3 ->
    (0 <= k)%Z -> (32 <= n - k)%Z ->
    exists regs',
      msteps ASEGS0 (mkst regs (0x12fca4 : word) (MK k) rom) (mkst regs' (0x12fddc : word) (MK (k + 1)) rom)
      /\ getr regs' 1 = ret /\ getr regs' 11 = at_ src (k + 16) /\ getr regs' 13 = at_ dst (k + 1)
      /\ getr regs' 12 = Z_to_bv 64 (n - (k + 1)) /\ getr regs' 14 = LWv (SB k 4)
      /\ getr regs' 15 = Z_to_bv 64 18 /\ keeps regs regs'.
  Proof.
    intros regs ret k H1 H11 H13 H12 H15 Hk Hnk. eexists. split.
    - mlw F_12fc60 D_12fc60 k.
      stepn F_12fc64 D_12fc64.
      stepb_tk F_12fc68 D_12fc68 ltac:(cond).
      msb F_12fd84 D_12fd84 k ltac:(eapply (sb_val_word0' _ _ _ _ _ HOK); lia).
      stepn F_12fd88 D_12fd88.
      stepn F_12fd8c D_12fd8c.
      stepn F_12fd90 D_12fd90.
      stepn F_12fd94 D_12fd94.
      mk_eq. apply mst_refl.
    - post. unfold v_addi. unorm. f_equal. lia.
  Qed.

  Lemma c3_loop : forall (q : nat) regs (ret : word) kk ja jw,
    getr regs 1 = ret -> getr regs 11 = at_ src ja -> getr regs 13 = at_ dst kk ->
    getr regs 12 = Z_to_bv 64 (n - kk) -> getr regs 14 = LWv (SB jw 4) -> getr regs 15 = Z_to_bv 64 18 ->
    (ja = kk + 15)%Z -> (jw = kk - 1)%Z -> (1 <= kk)%Z ->
    (16 * (Z.of_nat q + 1) + 3 <= n - kk < 16 * (Z.of_nat q + 1) + 19)%Z ->
    exists regs',
      msteps ASEGS0 (mkst regs (0x12fddc : word) (MK kk) rom)
                   (mkst regs' (0x12fe3c : word) (MK (kk + 16 * (Z.of_nat q + 1))) rom)
      /\ getr regs' 1 = ret /\ getr regs' 11 = at_ src (kk + 16 * (Z.of_nat q + 1) + 15)
      /\ getr regs' 13 = at_ dst (kk + 16 * (Z.of_nat q + 1))
      /\ getr regs' 12 = Z_to_bv 64 (n - (kk + 16 * (Z.of_nat q + 1))) /\ keeps regs regs'.
  Proof.
    induction q as [|q IH]; intros regs ret kk ja jw H1 H11 H13 H12 H14 H15 Hja Hjw Hkk Hq; subst ja jw.
    - eexists. split.
      + stepn F_12fd98 D_12fd98.
        mlw F_12fd9c D_12fd9c (kk + 3)%Z.
        mlw F_12fda0 D_12fda0 (kk + 7)%Z.
        mlw F_12fda4 D_12fda4 (kk + 11)%Z.
        mlw F_12fda8 D_12fda8 (kk + 15)%Z.
        stepn F_12fdac D_12fdac. stepn F_12fdb0 D_12fdb0. stepn F_12fdb4 D_12fdb4.
        stepn F_12fdb8 D_12fdb8. stepn F_12fdbc D_12fdbc. stepn F_12fdc0 D_12fdc0.
        stepn F_12fdc4 D_12fdc4. stepn F_12fdc8 D_12fdc8. stepn F_12fdcc D_12fdcc.
        stepn F_12fdd0 D_12fdd0. stepn F_12fdd4 D_12fdd4.
        stepn F_12fdd8 D_12fdd8.
        msw F_12fddc D_12fddc kk ltac:(m8).
        msw F_12fde0 D_12fde0 (kk + 4)%Z ltac:(m8).
        msw F_12fde4 D_12fde4 (kk + 8)%Z ltac:(m8).
        msw F_12fde8 D_12fde8 (kk + 12)%Z ltac:(m8).
        stepn F_12fdec D_12fdec.
        stepn F_12fdf0 D_12fdf0.
        stepb_ft F_12fdf4 D_12fdf4 ltac:(unfold v_addi; cond).
        mk_eq. apply mst_refl.
      + post. unfold v_addi. unorm. f_equal. lia.
    - eapply (runs_trans ASEGS0 _ (fun r => mkst r (0x12fddc : word) (MK (kk + 16)) rom)
               (fun r => getr r 1 = ret /\ getr r 11 = at_ src (kk + 16 + 15) /\ getr r 13 = at_ dst (kk + 16)
                         /\ getr r 12 = Z_to_bv 64 (n - (kk + 16)) /\ getr r 14 = LWv (SB (kk + 15) 4)
                         /\ getr r 15 = Z_to_bv 64 18 /\ keeps regs r)).
      + eexists. split.
        * stepn F_12fd98 D_12fd98.
          mlw F_12fd9c D_12fd9c (kk + 3)%Z.
          mlw F_12fda0 D_12fda0 (kk + 7)%Z.
          mlw F_12fda4 D_12fda4 (kk + 11)%Z.
          mlw F_12fda8 D_12fda8 (kk + 15)%Z.
          stepn F_12fdac D_12fdac. stepn F_12fdb0 D_12fdb0. stepn F_12fdb4 D_12fdb4.
          stepn F_12fdb8 D_12fdb8. stepn F_12fdbc D_12fdbc. stepn F_12fdc0 D_12fdc0.
