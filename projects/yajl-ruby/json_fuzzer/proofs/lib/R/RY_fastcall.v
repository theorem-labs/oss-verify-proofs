(* [comment removed for export] *)
Ltac fc_strip :=
  repeat match goal with
         | H : _ \/ _ |- _ => clear H
         | H : ~ _ |- _ => clear H
         | H : _ <> _ |- _ => clear H
         | H : _ -> _ |- _ => clear H
         | H : _ <-> _ |- _ => clear H
         end.

(* [comment removed for export] *)
Ltac fc_strip_but D :=
  repeat match goal with
         | H : _ \/ _ |- _ => tryif constr_eq H D then fail else clear H
         | H : ~ _ |- _ => tryif constr_eq H D then fail else clear H
         | H : _ <> _ |- _ => tryif constr_eq H D then fail else clear H
         | H : _ -> _ |- _ => tryif constr_eq H D then fail else clear H
         | H : _ <-> _ |- _ => tryif constr_eq H D then fail else clear H
         end.

(* [comment removed for export] *)
Ltac fc_lia :=
  first [ assumption
        | solve [fc_strip; lia]
        | match goal with D : _ \/ _ |- _ => solve [fc_strip_but D; lia] end
        | lia ].

(* [comment removed for export] *)
Ltac fc_disj :=
  lazymatch goal with
  | |- _ /\ _ => split; [fc_lia | fc_disj]
  | |- True => exact I
  | |- _ => fc_lia
  end.

(* [comment removed for export] *)
Ltac fc_subfp :=
  unfold sub_fp; cbn [outside]; let x := fresh "x" in let Hx := fresh "Hx" in
  intros x Hx; decompose [and] Hx; clear Hx;
  repeat lazymatch goal with |- _ /\ _ => split end;
  first [ exact I
        | assumption
        | let C := fresh "C" in intro C;
          match goal with X : ~ _ |- _ => solve [apply X; fc_strip; lia] end
        | lia ].

Ltac fc_transport_after_call segs m m' MU WM :=
  let W := lazymatch type of MU with munch ?W _ _ => W end in
  repeat match goal with
  | H : bytes_at segs m ?A2 ?bs2 |- _ =>
      first [ apply (bytes_at_transport segs W m m' A2 bs2) in H; [ | exact MU | cbn [disjoint_from]; simpl_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : wr_at segs m ?A2 ?n2 |- _ => apply (wr_at_transport segs m m' A2 n2) in H; [ | exact WM ]
  | H : rw_cells segs m ?A2 ?cs2 |- _ =>
      first [ apply (rw_cells_transport segs W m m' A2 cs2) in H; [ | exact MU | exact WM | cbn [disjoint_from]; simpl_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : ro_cells segs m ?A2 ?cs2 |- _ =>
      first [ apply (ro_cells_transport segs W m m' A2 cs2) in H; [ | exact MU | cbn [disjoint_from]; simpl_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : u8arr segs m ?A2 ?xs |- _ =>
      first [ apply (u8arr_transport segs W m m' A2 xs) in H; [ | exact MU | exact WM | cbn [disjoint_from]; simpl_sizes; simpl_arr_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : u32arr segs m ?A2 ?xs |- _ =>
      first [ apply (u32arr_transport segs W m m' A2 xs) in H; [ | exact MU | exact WM | cbn [disjoint_from]; simpl_sizes; simpl_arr_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : u64arr segs m ?A2 ?xs |- _ =>
      first [ apply (u64arr_transport segs W m m' A2 xs) in H; [ | exact MU | exact WM | cbn [disjoint_from]; simpl_sizes; simpl_arr_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : u8ro segs m ?A2 ?xs |- _ =>
      first [ apply (u8ro_transport segs W m m' A2 xs) in H; [ | exact MU | cbn [disjoint_from]; simpl_sizes; simpl_arr_sizes; fc_disj ]
            | idtac "note: dropping hypothesis (not provably disjoint from callee footprint):" H; clear H ]
  | H : stk segs m ?loq ?hiq |- _ =>
      first [ apply (stk_transport_disjoint segs W m m' loq hiq) in H; [ | exact MU | exact WM | cbn [disjoint_from]; fc_disj ]
            | clear H ]
  | H : munch ?Wq ?mq m |- _ =>
      first [ apply (munch_trans Wq mq m m') in H; [ | eapply (munch_weaken W Wq m m'); [ fc_subfp | exact MU ] ]
            | fail 100 "callee footprint not inside caller footprint" ]
  | H : wmono segs ?mq m |- _ => apply (wmono_trans segs mq m m') in H; [ | exact WM ]
  end.

Ltac fc_post_call segs m :=
  let ms' := fresh "ms'" in let PO := fresh "POST" in
  intros ms' PO;
  destruct_exs PO;
  let E := fresh "E" in let MUc := fresh "MUc" in let WMc := fresh "WMc" in let MIc := fresh "MI" in
  destruct PO as [E [MUc [WMc PO]]];
  first [ destruct PO as [MIc PO] | rename PO into MIc ];
  subst ms';
  lazymatch type of MUc with
  | munch _ m ?m' =>
      fc_transport_after_call segs m m' MUc WMc;
      clear MUc WMc;
      try match goal with H : mem_inv segs m |- _ => clear H end;
      try clear m
  end;
  try destruct_ands PO;
  try (lazymatch goal with
  | |- evt _ _ (MS _ _ (ret_pc (Z_to_bv 64 ?n)) _ _ _ _) =>
      replace (ret_pc (Z_to_bv 64 n)) with (Z_to_bv 64 n) by (symmetry; apply ret_pc_even; [ lia | reflexivity ])
  end).

Tactic Notation "fcall" uconstr(SPEC) :=
  lazymatch goal with
  | |- evt ?segs _ (MS _ _ _ _ _ ?m _) => eapply evt_cut; [ eapply SPEC | fc_post_call segs m ]
  end.
