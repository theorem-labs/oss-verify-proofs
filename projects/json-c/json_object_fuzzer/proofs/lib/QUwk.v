Lemma maps_match_nofog : forall E ms l,
forallb (fun m => negb (is_fog m)) ms = true -> maps_match E ms l -> l = map (amap_den E) ms.
Proof.
intros E ms. induction ms as [|m ms IH]; intros l Hf H; cbn [maps_match map] in *.
- exact H.
- cbn [forallb] in Hf. apply andb_prop in Hf as [Hm Hf]. apply negb_true_iff in Hm. rewrite Hm in H.
destruct H as (l' & -> & H). rewrite (IH l' Hf H). reflexivity.
Qed.
